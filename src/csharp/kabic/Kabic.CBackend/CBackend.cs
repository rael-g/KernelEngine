namespace Kabic.C;

/// <summary>
/// kabic's C backend: renders a domain's component structs as field tables, so the runtime can
/// apply a scene file to component memory by reading a description instead of running a callback
/// somebody wrote by hand for that one component. The table's entry type and the spelling of each
/// kind of field come from the convention.
/// </summary>
public static class CBackend
{
    /// <summary>
    /// Renders the field tables for every non-vtable, non-composed struct in
    /// <paramref name="model"/> that carries at least one describable field.
    /// </summary>
    /// <param name="model">The domain's parsed description.</param>
    /// <param name="guard">Include-guard macro, e.g. <c>KE_RENDER_COMPONENT_FIELDS_H_</c>.</param>
    /// <param name="includes">Headers the table references, in include order.</param>
    /// <param name="convention">Names the shape a component's type has in this ABI.</param>
    public static string RenderFieldTables(ApiModel model, string guard, IReadOnlyList<string> includes,
        Convention convention)
    {
        var table = convention.FieldTable
            ?? throw new InvalidOperationException("the convention declares no 'fieldTable', so there is no field table to render");
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("/* <auto-generated/> Derived from ke_api.json. Do not edit; edit the C header instead. */");
        sb.AppendLine($"#ifndef {guard}");
        sb.AppendLine($"#define {guard}");
        sb.AppendLine();
        sb.AppendLine($"#include <{table.Include}>");
        foreach (var inc in includes) sb.AppendLine($"#include <{inc}>");
        sb.AppendLine("#include <stddef.h>");
        sb.AppendLine();

        var named = Named(model, convention).ToList();
        if (named.Count > 0)
        {
            foreach (var s in named)
                sb.AppendLine($"#define {NameMacro(s, convention)} \"{convention.ComponentNameFor(s.Name)}\"");
            sb.AppendLine();
        }

        foreach (var s in Describable(model, convention))
        {
            var fields = s.Fields.Where(f => Describes(model, f, table)).ToList();
            sb.AppendLine($"static const {table.EntryType} {s.Name}_fields[] = {{");
            foreach (var f in fields)
                sb.AppendLine($"    {{ \"{f.TagValue("name") ?? f.Name}\", {table.Variants[VariantOf(model, f, table)!.Value].Constant}, "
                    + $"offsetof({s.Name}, {f.Name}), sizeof((({s.Name} *)0)->{f.Name}), "
                    + $"{DefaultOf(model, f, table)} }},");
            sb.AppendLine("};");
            sb.AppendLine();
        }

        sb.AppendLine($"#endif /* {guard} */");
        return sb.ToString();
    }

    /// <summary>
    /// The structs this backend describes: a domain's own component structs, in
    /// declaration order. A vtable is behavior; a composed struct belongs to the
    /// domain that owns it, which emits its table there; and a plain helper
    /// struct a component happens to be built out of is not itself addressable
    /// by a scene file, which is what the component suffix tells them apart by.
    /// </summary>
    /// <summary>
    /// The component structs this domain names. Wider than <see cref="Describable"/>: a
    /// component a scene file cannot author still has to be registered under a name, and
    /// every language reaching it needs the same one. A component with no describable field
    /// would otherwise have its name spelled by hand next to a struct that already implies
    /// it.
    /// </summary>
    public static IEnumerable<ApiStruct> Named(ApiModel model, Convention convention) =>
        model.Structs.Where(s => !s.IsVtable && !s.External && convention.IsComponentType(s.Name));

    /// <summary>The macro a component's registered name is reached by from C and Zig.</summary>
    public static string NameMacro(ApiStruct s, Convention convention) =>
        convention.FieldTable!.NameMacroPrefix + convention.ComponentNameFor(s.Name).ToUpperInvariant();

    public static IEnumerable<ApiStruct> Describable(ApiModel model, Convention convention) =>
        model.Structs.Where(s => !s.IsVtable
            && !s.External
            && s.Name.EndsWith(convention.ComponentSuffix, StringComparison.Ordinal)
            && s.Fields.Any(f => Describes(model, f, convention.FieldTable!)));

    /// <summary>
    /// Whether a scene file can address this field at all. <c>[output]</c> is a
    /// field a system writes every tick; describing it would invite a scene to
    /// author a value that is overwritten before anything reads it.
    /// </summary>
    /// <summary>
    /// Renders a field's <c>[default:]</c> as an initializer for the table's
    /// ke_variant, or the null variant when the header declares none.
    /// </summary>
    private static string DefaultOf(ApiModel model, ApiField f, FieldTableConvention table)
    {
        var d = f.TagValue("default");
        if (d is null) return NullVariant(table);

        var kind = VariantOf(model, f, table)!.Value;
        var variant = table.Variants[kind];
        var parts = d.Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        var lanes = kind switch
        {
            FieldKind.Vec2 => 2, FieldKind.Vec3 => 3,
            FieldKind.Vec4 or FieldKind.Quat => 4,
            _ => 1,
        };
        if (parts.Length != lanes)
            throw new InvalidOperationException(
                $"{f.Name}: [default:{d}] has {parts.Length} components but {variant.Constant} takes {lanes}");

        var value = kind switch
        {
            FieldKind.String => $"\"{d}\"",
            FieldKind.Bool => d is "1" or "true" ? "true" : "false",
            FieldKind.Int => d,
            FieldKind.Float => CDouble(parts[0]),
            _ => "{ " + string.Join(", ", parts.Select(p => CDouble(p) + "f")) + " }",
        };
        return $"{{ {variant.Constant}, {{ {variant.Member} = {value} }} }}";
    }

    private static string NullVariant(FieldTableConvention table) => $"{{ {table.Variants[FieldKind.Null].Constant}, {{ 0 }} }}";

    /// <summary>A C floating literal: "5" is not one, "5.0" is.</summary>
    private static string CDouble(string raw) => raw.Contains('.') ? raw : raw + ".0";

    private static bool Describes(ApiModel model, ApiField f, FieldTableConvention table) =>
        !f.Has("output") && VariantOf(model, f, table) is not null;

    /// <summary>
    /// The <c>ke_variant_type</c> a field is addressed as, or null when the field
    /// has no scene-file spelling — a derived matrix or an opaque handle is
    /// produced by a system, never written down.
    /// </summary>
    private static FieldKind? VariantOf(ApiModel model, ApiField f, FieldTableConvention table)
    {
        if (f.Has("bool")) return FieldKind.Bool;
        var type = Base(f.Type);
        if (model.Enums.Any(e => e.Name == type)) return FieldKind.Int;
        if (model.VectorOf(type) is { } vector)
            return vector.Managed == "Quaternion" ? FieldKind.Quat : vector.Lanes.Length switch { 2 => FieldKind.Vec2, 3 => FieldKind.Vec3, _ => FieldKind.Vec4 };
        return type switch
        {
            "float" or "double"                        => FieldKind.Float,
            "bool" or "_Bool"                          => FieldKind.Bool,
            "int8_t" or "int16_t" or "int32_t" or "int64_t" => FieldKind.Int,
            "uint8_t" or "uint16_t" or "uint32_t" or "uint64_t" => FieldKind.Int,
            "int" or "unsigned" or "unsigned int"      => FieldKind.Int,
            var t when t.StartsWith("char[")           => FieldKind.String,
            "float[2]"                                 => FieldKind.Vec2,
            "float[3]"                                 => FieldKind.Vec3,
            "float[4]"                                 => FieldKind.Vec4,
            _                                          => null,
        };
    }

    private static string Base(string cType) =>
        cType.Replace("const ", "").Replace("struct ", "").Trim();
}
