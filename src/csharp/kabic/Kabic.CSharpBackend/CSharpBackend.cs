
namespace Kabic.CSharp;

using System.Text.RegularExpressions;
using Kabic;

public static class CSharpBackend
{
    const string Header = "// <auto-generated/>\n// Derived from ke_api.json. Do not edit; edit the C header instead.\n";

    static string XmlDoc(string indent, string? summary, Convention convention, IEnumerable<(string Name, string? Doc)>? pars = null,
        string? ret = null, bool throwsOnFail = false)
    {
        var lines = new List<string>();
        if (!string.IsNullOrEmpty(summary)) lines.Add($"{indent}/// <summary>{Escape(summary)}</summary>");
        foreach (var (n, d) in pars ?? [])
            if (!string.IsNullOrEmpty(d)) lines.Add($"{indent}/// <param name=\"{n}\">{Escape(d)}</param>");
        if (!string.IsNullOrEmpty(ret)) lines.Add($"{indent}/// <returns>{Escape(ret)}</returns>");
        if (throwsOnFail) lines.Add($"{indent}/// <exception cref=\"{convention.ErrorHelperClass}\">The native call failed.</exception>");
        return lines.Count > 0 ? string.Join('\n', lines) + '\n' : "";
    }

    static string Escape(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    /// Emits the `fixed` pinning prologue encoding every [utf8] parameter as a
    /// NUL-terminated byte buffer, returning the lines and the number of braces
    /// the caller must close.
    static (List<string> Lines, int Depth) Utf8Prologue(IEnumerable<ApiParam> ps, string indent)
    {
        var lines = new List<string>();
        var depth = 0;
        foreach (var p in ps.Where(x => x.Has("utf8")))
        {
            var n = Idioms.Ident(p.Name!);
            lines.Add($"{indent}var {n}Bytes = System.Text.Encoding.UTF8.GetBytes({n} + '\\0');");
            lines.Add($"{indent}fixed (byte* {n}Ptr = {n}Bytes)");
            lines.Add($"{indent}{{");
            depth++;
        }
        return (lines, depth);
    }

    /// Emits the pinning prologue for every pointer+count pair, returning the lines and the
    /// number of blocks the caller must close. Composes with the [utf8] prologue: both only
    /// open blocks, in whatever order the caller emits them. A sequence of <c>[borrowed]</c>
    /// structs opens two -- the <c>try</c> its pins are released from, and the <c>fixed</c>
    /// over the native elements built from them -- which is what <see cref="SequenceClosers"/>
    /// closes.
    static (List<string> Lines, int Depth) SequencePrologue(ApiModel model,
        IEnumerable<SequencePair> seqs, string indent, Convention convention)
    {
        var lines = new List<string>();
        var depth = 0;
        foreach (var s in seqs)
        {
            var n = Idioms.Ident(s.Seq.Name!);
            var at = indent + new string(' ', depth * 4);
            if (BorrowedOf(model, s.Seq) is { } borrowed)
            {
                var native = CsType(model, CTypes.Deref(s.Seq.Type), convention);
                lines.Add($"{at}var {n}Pins = new System.Buffers.MemoryHandle[{n}.Length];");
                lines.Add($"{at}var {n}Native = new {native}[{n}.Length];");
                lines.Add($"{at}try");
                lines.Add($"{at}{{");
                foreach (var l in BorrowedFill(model, borrowed, n, convention))
                    lines.Add($"{at}    {l}");
                lines.Add($"{at}    fixed ({native}* {n}Ptr = {n}Native)");
                lines.Add($"{at}    {{");
                depth += 2;
                continue;
            }
            lines.Add($"{at}fixed ({SequenceElement(model, s, convention)}* {n}Ptr = {n})");
            lines.Add($"{at}{{");
            depth++;
        }
        return (lines, depth);
    }

    /// The blocks <see cref="SequencePrologue"/> opened, outermost first, each as the lines
    /// that close it. A pin is released where the <c>try</c> ends, so a call that threw lets
    /// go of what it held exactly as one that returned does.
    static List<string[]> SequenceClosers(ApiModel model, IEnumerable<SequencePair> seqs)
    {
        var closers = new List<string[]>();
        foreach (var s in seqs)
        {
            if (BorrowedOf(model, s.Seq) is null) { closers.Add(["}"]); continue; }

            var n = Idioms.Ident(s.Seq.Name!);
            closers.Add([
                "}", "finally", "{",
                $"    for (var {n}At = 0; {n}At < {n}Pins.Length; {n}At++) {n}Pins[{n}At].Dispose();",
                "}"]);
            closers.Add(["}"]);
        }
        return closers;
    }

    /// Closes every block a call's prologues opened, innermost first. The blocks from
    /// <paramref name="seqAt"/> on are the sequences', which may end in more than a brace.
    static void CloseScopes(List<string> o, int depth, int seqAt, IReadOnlyList<string[]> sequences)
    {
        for (var d = depth; d > 0; d--)
        {
            var pad = new string(' ', 4 + d * 4);
            var inSeq = d - 1 - seqAt;
            var lines = inSeq >= 0 && inSeq < sequences.Count ? sequences[inSeq] : ["}"];
            foreach (var l in lines) o.Add(pad + l);
        }
    }

    /// The <c>[borrowed]</c> struct a sequence's elements are, or null for any other element.
    static ApiStruct? BorrowedOf(ApiModel model, ApiParam seq)
    {
        if (!CTypes.IsPointer(seq.Type)) return null;
        var element = StripQualifiers(CTypes.Deref(seq.Type)).Trim();
        return model.Structs.FirstOrDefault(v => v.Name == element && IsBorrowed(v));
    }

    /// The loop building a native element out of each managed one: its memory pinned for
    /// the call, the pointer and the count taken from the memory, so the two cannot disagree.
    static IEnumerable<string> BorrowedFill(ApiModel model, ApiStruct b, string n, Convention convention)
    {
        var at = $"{n}At";
        yield return $"for (var {at} = 0; {at} < {n}.Length; {at}++)";
        yield return "{";
        foreach (var f in b.Fields)
        {
            var native = $"{n}Native[{at}].{f.Name}";
            var mirror = $"{n}[{at}].{Idioms.Pascal(f.Name)}";
            if (f.Has("array_of"))
            {
                var count = b.Fields.First(x => x.Name == f.TagValue("array_of"));
                yield return $"    {n}Pins[{at}] = {mirror}.Pin();";
                yield return $"    {native} = ({CsType(model, f.Type, convention)}){n}Pins[{at}].Pointer;";
                yield return $"    {n}Native[{at}].{count.Name} = ({CsType(model, count.Type, convention)}){mirror}.Length;";
            }
            else if (!b.Fields.Any(x => x.TagValue("array_of") == f.Name))
                yield return $"    {native} = {mirror};";
        }
        yield return "}";
    }

    /// The element type a sequence parameter is spelled with. A <c>[value]</c> element
    /// takes its managed mirror, so a caller composes the span out of the projection it
    /// already holds rather than the native spelling of the same bytes.
    static string SequenceElement(ApiModel model, SequencePair s, Convention convention) =>
        ValueTypeName(model, StripQualifiers(CTypes.Deref(s.Seq.Type)), convention);

    /// The pinned pointer a sequence parameter hands the vtable. A <c>[value]</c> element is
    /// pinned as its managed mirror, which the slot takes under the native spelling of the
    /// same bytes -- so the cast is between two projections of one declaration, not between
    /// a generated type and a hand-written guess at its layout.
    static string SequenceArg(ApiModel model, SequencePair s, Convention convention)
    {
        var n = Idioms.Ident(s.Seq.Name!);
        if (BorrowedOf(model, s.Seq) is not null) return $"{n}Ptr";
        var native = CsType(model, CTypes.Deref(s.Seq.Type), convention);
        return SequenceElement(model, s, convention) == native ? $"{n}Ptr" : $"({native}*){n}Ptr";
    }

    /// <summary>
    /// The value a <c>[default:...]</c> parameter takes when the caller leaves it out. The
    /// header is where the default belongs: a params-bag field that documents "or 0 to let
    /// any wave thread take it" is describing an optional parameter, and spelling that 0 a
    /// second time in a hand-written overload is how the two come to disagree.
    /// </summary>
    static string DefaultLiteral(ApiModel model, ClassifiedSlot cs, ApiParam p, ApiSlot slot, Convention convention)
    {
        var v = p.TagValue("default")!.Trim();
        if (p.Has("closure"))
            return v is "none"
                ? "null"
                : throw new InvalidOperationException(
                    $"{slot.Name}.{p.Name}: a handler the caller may leave out is an absent one, so"
                    + $" [default:none] is the only default it takes -- got \"{v}\".");

        if (cs.Sequences.Any(s => s.Seq == p))
            return v is "empty"
                ? "default"
                : throw new InvalidOperationException(
                    $"{slot.Name}.{p.Name}: a sequence the caller may leave out is the empty one, so"
                    + $" [default:empty] is the only default it takes -- got \"{v}\".");

        if (convention.BooleanReturnTypes.Contains(p.Type.Trim()) || p.Has("bool"))
            return v is "true" or "false"
                ? v
                : throw new InvalidOperationException(
                    $"{slot.Name}.{p.Name}: a boolean default is true or false -- got \"{v}\".");

        if (model.Enums.FirstOrDefault(e => e.Name == p.Type.Trim()) is { } e)
            return e.Values.Any(ev => ev.Name == v)
                ? $"{Idioms.TypeName(e.Name, convention)}.{Idioms.EnumMember(v, e.Name)}"
                : throw new InvalidOperationException(
                    $"{slot.Name}.{p.Name}: [default:{v}] is not a value of {e.Name}.");

        return long.TryParse(v, out _)
            ? v
            : throw new InvalidOperationException(
                $"{slot.Name}.{p.Name}: [default:{v}] is not a literal this projection can spell."
                + " A default has to be a constant the caller sees, not an expression.");
    }

    static string StripQualifiers(string cType)
    {
        var t = cType.Trim();
        if (t.StartsWith("const ", StringComparison.Ordinal)) t = t["const ".Length..];
        if (t.StartsWith("struct ", StringComparison.Ordinal)) t = t["struct ".Length..];
        return t.Trim();
    }

    /// A C type mapped to C#. Typedef aliases resolve first; pointers recurse so
    /// `const`/`struct` qualifiers are dropped and the pointee receives the same
    /// mapping as any other type. An opaque `void *` maps to `nint`.
    static string CsType(ApiModel model, string cType, Convention convention)
    {
        var t = cType.Trim();
        if (t is "void *" or "void*") return "nint";
        if (CTypes.IsPointer(t))
        {
            var inner = CTypes.Deref(t).Trim();
            if (inner.StartsWith("const ")) inner = inner["const ".Length..];
            if (inner.StartsWith("struct ")) inner = inner["struct ".Length..];
            return CsType(model, inner, convention) + "*";
        }
        var resolved = model.ResolveAlias(t);
        return FunctionPointerType(model, resolved, convention) ?? Idioms.CsPrimitive(resolved, convention);
    }

    /// A C function-pointer type (`void (*)(ke_ecs *, void *)`) as a C# function
    /// pointer. The C name is only ever an alias, so leaving it verbatim emits an
    /// identifier that resolves to nothing; the callable type has to be spelled out.
    static string? FunctionPointerType(ApiModel model, string cType, Convention convention)
    {
        var m = Regex.Match(cType.Trim(), @"^(.+?)\s*\(\s*\*\s*\)\s*\((.*)\)$");
        if (!m.Success) return null;

        var returns = CsType(model, m.Groups[1].Value, convention);
        var paramList = m.Groups[2].Value.Trim();
        var parameters = paramList is "" or "void"
            ? []
            : paramList.Split(',').Select(p => CsType(model, p, convention)).ToList();

        return $"delegate* unmanaged[Cdecl]<{string.Join(", ", parameters.Append(returns))}>";
    }

    /// The element type a returned sequence is spelled with, taking a <c>[value]</c>
    /// element's managed mirror for the same reason a sequence parameter does: the caller
    /// reads the bytes through the projection it already holds.
    static string ReturnElement(ApiModel model, ApiSlot slot, Convention convention) =>
        ValueTypeName(model, StripQualifiers(CTypes.Deref(slot.Returns)), convention);

    /// <summary>
    /// What a parameter the callee writes holds, once the indirection carrying it back is
    /// gone. A declared <c>[enum]</c> is the managed spelling here as much as anywhere else:
    /// the pointer type alone only says which bytes are written, not which type names them.
    /// </summary>
    /// <summary>
    /// What a slot answers with, as its caller reads it. A declared enum names its own
    /// values, and a parameter of that type is already projected by the name -- a return of
    /// the same type staying the ABI's integer would make one declaration mean two things
    /// depending on which side of the slot it sits on.
    /// </summary>
    static string ReturnType(ApiModel model, string cType, Convention convention) =>
        model.Enums.Any(e => e.Name == cType.Trim())
            ? Idioms.TypeName(cType.Trim(), convention)
            : PointerToView(model, cType, convention) ?? CsType(model, cType, convention);

    /// <summary>
    /// The cast carrying the ABI's answer into what <see cref="ReturnType"/> spells, or
    /// nothing where the two already agree.
    /// </summary>
    static string ReturnCast(ApiModel model, string cType, Convention convention) =>
        model.Enums.Any(e => e.Name == cType.Trim())
            ? $"({Idioms.TypeName(cType.Trim(), convention)})"
            : PointerToView(model, cType, convention) is { } view ? $"({view})"
            : "";

    /// <summary>
    /// The projection a pointer reaches, where what it points at is declared a
    /// <c>[view]</c> -- or nothing, for any other pointee. A view and the declaration it
    /// stands for occupy the same bytes, because both are laid out sequentially from the one
    /// field list the header gives; so naming the projection at the boundary is what lets a
    /// caller hold the reading instead of reinterpreting the ABI spelling itself, which is
    /// the cast a view exists to stop being written.
    /// </summary>
    static string? PointerToView(ApiModel model, string cType, Convention convention)
    {
        if (!CTypes.IsPointer(cType)) return null;
        var element = StripQualifiers(CTypes.Deref(cType)).Trim();
        return model.Structs.Any(s => s.Name == element && !s.IsVtable && s.Has("view"))
            ? Idioms.TypeName(element, convention) + "*"
            : null;
    }

    /// <summary>
    /// A pointer the provider hands out and later takes back, projected as the object that
    /// answers when it is given back. A <c>[view]</c> alone says how to read the memory, not
    /// who releases it, and reading it as a value loses the pointer the release slot needs --
    /// so a caller handed the bare pointer has to keep it beside the reading and remember to
    /// pass it back, which is the bookkeeping this form exists to stop being written. The
    /// release slot is the one thing that names the pairing, so it carries the tag.
    /// </summary>
    internal sealed record OwnedProjection(string TypeName, string Element, string View,
        ApiSlot Release, ApiParam Released)
    {
        /// <summary>Whether a slot answers with the pointer this projection owns.</summary>
        public bool Answers(string cType) =>
            CTypes.IsPointer(cType) && StripQualifiers(CTypes.Deref(cType)).Trim() == Element;
    }

    /// <summary>
    /// The one owned projection a vtable declares, read off the slot tagged
    /// <c>[releases:&lt;name&gt;]</c>.
    /// </summary>
    static OwnedProjection? OwnedOf(ApiModel model, ApiStruct vtable, Convention convention)
    {
        var release = vtable.Slots.FirstOrDefault(s => s.Has("releases"));
        if (release is null) return null;

        var typeName = release.TagValue("releases")
            ?? throw new InvalidOperationException(
                $"{release.Name}: [releases] must name the projection that owns what this slot takes"
                + " back, as [releases:<name>]");

        var released = release.Params.Where(p => !p.Has("self")).ToList();
        if (released.Count != 1)
            throw new InvalidOperationException(
                $"{release.Name}: [releases:{typeName}] releases the one pointer this slot takes back,"
                + $" and it takes {released.Count} parameter(s) besides the provider itself");

        var view = PointerToView(model, released[0].Type, convention)
            ?? throw new InvalidOperationException(
                $"{release.Name}: [releases:{typeName}] hands back {released[0].Type.Trim()}, and a"
                + " projection can only own memory some struct declares how to read -- the pointee"
                + " has to be tagged [view]");

        return new OwnedProjection(typeName, StripQualifiers(CTypes.Deref(released[0].Type)).Trim(),
            view, release, released[0]);
    }

    /// <summary>
    /// The object a provider hands out instead of the pointer it owns: the reading the
    /// <c>[view]</c> gives, and the one answer about when the memory goes back.
    /// </summary>
    static void RenderOwned(List<string> o, OwnedProjection owned, string ownerType, string releaseName)
    {
        var view = owned.View.TrimEnd('*');
        o.Add("/// <summary>");
        o.Add($"/// Keeps the <see cref=\"{ownerType}\"/>-owned memory behind one {view} alive for as long");
        o.Add("/// as a caller holds it, and gives it back on dispose. Everything it says about itself is");
        o.Add($"/// read through <see cref=\"Data\"/>, which stays valid only until then.");
        o.Add("/// </summary>");
        o.Add($"public unsafe sealed class {owned.TypeName} : IDisposable");
        o.Add("{");
        o.Add($"    private readonly {ownerType} _owner;");
        o.Add($"    private {owned.View} _native;");
        o.Add("");
        o.Add($"    internal {owned.TypeName}({ownerType} owner, {owned.View} native)");
        o.Add("    {");
        o.Add("        _owner = owner;");
        o.Add("        _native = native;");
        o.Add("    }");
        o.Add("");
        o.Add("    /// <summary>The reading of the memory this instance is keeping alive.</summary>");
        o.Add($"    public {view} Data => _native is null");
        o.Add($"        ? throw new ObjectDisposedException(nameof({owned.TypeName}))");
        o.Add("        : *_native;");
        o.Add("");
        o.Add($"    /// <summary>Gives the memory back to the {ownerType.ToLowerInvariant()} that produced it.</summary>");
        o.Add("    public void Dispose()");
        o.Add("    {");
        o.Add("        if (_native is null) return;");
        o.Add("        var native = _native;");
        o.Add("        _native = null;");
        o.Add($"        _owner.{releaseName}(native);");
        o.Add("    }");
        o.Add("}");
        o.Add("");
    }

    /// <summary>
    /// What to call a parameter the callee writes. A leading <c>out_</c> is how C marks the
    /// direction, and the projection already marks it -- as <c>out</c>, as a tuple element,
    /// or by returning it -- so carrying the prefix across would spell it twice.
    /// </summary>
    static string WrittenName(ApiParam p) =>
        p.Name!.StartsWith("out_", StringComparison.Ordinal) && p.Name!.Length > "out_".Length
            ? p.Name!["out_".Length..]
            : p.Name!;

    /// <summary>
    /// The type parameter standing for an opaque payload. Named after the parameter it
    /// carries, so a slot taking two payloads spells which is which instead of leaving the
    /// caller to count positions.
    /// </summary>
    static string BlobTypeParam(ApiParam p) => "T" + Idioms.Pascal(p.Name!);

    /// <summary>
    /// The pinned payload and the byte count derived from it. The count is the size of the
    /// type the caller passed, which is the whole reason the pair travels as one value.
    /// </summary>
    static (List<string> Lines, int Depth) BlobPrologue(IEnumerable<BlobPair> blobs, string indent)
    {
        var lines = new List<string>();
        var depth = 0;
        foreach (var b in blobs)
        {
            var n = Idioms.Ident(b.Blob.Name!);
            var at = indent + new string(' ', depth * 4);
            lines.Add($"{at}fixed ({BlobTypeParam(b.Blob)}* {n}Ptr = &{n})");
            lines.Add($"{at}{{");
            depth++;
        }
        return (lines, depth);
    }

    /// <summary>
    /// How a written-back parameter reads to the caller. A <c>[rooted]</c> one is the handle
    /// the rooting side allocated coming back, and the only reason it crossed as an opaque
    /// pointer was that the native side stores it without ever looking inside -- so what the
    /// caller gets back is the object it handed over, not the number standing for it.
    /// </summary>
    static string OutElement(ApiModel model, ApiParam p, Convention convention) =>
        p.Has("rooted") ? "object?" : OutLocal(model, p, convention);

    /// <summary>
    /// The local the call writes through, spelled as the ABI declares it. This is the type
    /// whose address the slot takes, which is not always the type the caller reads.
    /// </summary>
    static string OutLocal(ApiModel model, ApiParam p, Convention convention) =>
        p.TagValue("enum") is { } named
            ? Idioms.TypeName(named, convention)
            : CsType(model, CTypes.Deref(p.Type), convention);

    /// <summary>
    /// The local read back as the caller's type. Everything but a rooted handle reads as
    /// itself; a rooted one resolves to the object, with a null pointer meaning no object
    /// rather than a handle to reconstruct.
    /// </summary>
    static string OutRead(ApiParam p, string local) =>
        p.Has("rooted")
            ? $"{local} == 0 ? null : System.Runtime.InteropServices.GCHandle.FromIntPtr({local}).Target"
            : local;

    /// <summary>
    /// A pointer type as the native side spells it. <see cref="CsType"/> answers <c>nint</c>
    /// for an opaque pointer, which is what a caller should hold but not what the vtable
    /// field declares -- so the address of one is the address of the wrong type as far as
    /// the compiler is concerned.
    /// </summary>
    static string NativePointerType(ApiModel model, string cType, Convention convention)
    {
        var t = cType.Trim();
        if (!CTypes.IsPointer(t)) return CsType(model, t, convention);
        var inner = CTypes.Deref(t).Trim();
        if (inner.StartsWith("const ", StringComparison.Ordinal)) inner = inner["const ".Length..];
        if (inner.StartsWith("struct ", StringComparison.Ordinal)) inner = inner["struct ".Length..];
        return (inner is "void" ? "void" : NativePointerType(model, inner, convention)) + "*";
    }

    /// <summary>
    /// The address of the local standing in for an <c>out</c> parameter, cast back to what
    /// the ABI declares wherever the managed spelling of it differs.
    /// </summary>
    static string OutAddress(ApiModel model, ApiParam p, Convention convention, string local)
    {
        var native = NativePointerType(model, p.Type, convention);
        return native == OutLocal(model, p, convention) + "*" ? $"&{local}" : $"({native})&{local}";
    }

    /// <summary>
    /// What a parameter carrying another domain's vtable is asked for as: the interface
    /// that domain's own projection hands its pointer out through. The pointer is what
    /// the ABI needs and the one thing a game-facing signature must not name, and a
    /// caller already holding the projection should not have to open it to comply --
    /// so the parameter asks for the projection and the call does the opening.
    /// </summary>
    static string ProviderInterface(ApiParam p, Convention convention)
    {
        if (!CTypes.IsPointer(p.Type))
            throw new InvalidOperationException(
                $"{p.Name}: [provider] names another domain's vtable, which reaches this one as a"
                + $" pointer, and this parameter is {p.Type.Trim()}");
        return "INative" + Idioms.TypeName(StripQualifiers(CTypes.Deref(p.Type)).Trim(), convention);
    }

    static string CsParamType(ApiModel model, ApiParam p, Convention convention)
    {
        if (p.Has("provider")) return ProviderInterface(p, convention);
        var tagEnum = p.TagValue("enum");
        if (tagEnum is not null)
        {
            var named = Idioms.TypeName(tagEnum, convention);
            return CTypes.IsPointer(p.Type) ? named + "*" : named;
        }
        if (p.Has("utf8")) return "string";
        if (p.Has("rooted")) return "object";
        if (p.Has("opaque")) return "void*";
        if (p.Has("ctx")) return "nint";
        if (model.Enums.Any(e => e.Name == p.Type.Trim()))
            return Idioms.TypeName(p.Type.Trim(), convention);
        return PointerToView(model, p.Type, convention) ?? CsType(model, p.Type, convention);
    }

    /// <summary>
    /// Emits only the declaration a game-facing node type needs: the
    /// <see cref="GeneratedNodeComponentAttribute"/> marker, the partial property
    /// signatures, and the constructor seeding <c>[default:]</c> values. Accessor bodies,
    /// the backing field, and <c>OnBind</c> are <c>KernelEngine.SourceGenerators</c>'s job —
    /// the same generator a game-authored node type with no header uses, so this type and
    /// a hand-written one are indistinguishable to it once both compile down to a
    /// <c>partial</c> class with <c>partial</c> properties.
    /// </summary>
    public static string RenderNodeType(ApiModel model, ApiStruct component, string ns,
        IEnumerable<string> extraUsings, Convention convention)
    {
        var nodeName = component.TagValue("node") ?? throw new InvalidOperationException($"{component.Name} has no [node:] tag");
        var stateType = Idioms.TypeName(component.Name, convention);
        var componentName = convention.ComponentNameFor(component.Name);

        var baseName = BaseNodeOf(model, component) ?? "Node";

        var o = new List<string> { Header, "using System.Numerics;" };
        foreach (var u in extraUsings) o.Add($"using {u};");
        o.Add("");
        o.Add($"namespace {ns};\n");
        o.Add(component.Doc is not null ? XmlDoc("", component.Doc, convention).TrimEnd()
            : $"/// <summary>Mirrors <c>{component.Name}</c>.</summary>");
        o.Add($"[GeneratedNodeComponent(typeof({stateType}), \"{componentName}\")]");
        o.Add($"public partial class {nodeName} : {baseName}");
        o.Add("{");

        var slots = new List<ApiStruct> { component };

        o.Add($"    public {nodeName}()");
        o.Add("    {");
        for (var i = 0; i < slots.Count; i++)
            foreach (var line in ComponentInit(slots[i], i, convention)) o.Add($"        {line}");
        o.Add("    }");

        foreach (var c in slots)
            foreach (var line in ComponentSurface(model, c, convention)) o.Add(line);

        o.Add("}");
        return string.Join('\n', o);
    }

    /// <summary>
    /// Emits the one call that registers every node type this domain renders, so a
    /// scene naming any of them resolves without a hand-kept list.
    /// </summary>
    public static string RenderNodeTypeRegistrar(string registrarName, IEnumerable<string> nodeNames, string ns)
    {
        var o = new List<string>
        {
            Header,
            "using Microsoft.Extensions.DependencyInjection;",
            "",
            $"namespace {ns};",
            "",
            $"/// <summary>Registers every node type generated for this domain.</summary>",
            $"public static class {registrarName}",
            "{",
            $"    /// <summary>Registers this domain's node types with the scene node registry.</summary>",
            $"    public static IServiceCollection Add{registrarName}(this IServiceCollection services)",
            "    {",
        };
        foreach (var n in nodeNames) o.Add($"        services.AddNodeType<{n}>();");
        o.Add("        return services;");
        o.Add("    }");
        o.Add("}");
        return string.Join('\n', o);
    }

    /// <summary>
    /// The node type this one extends, or null when it extends <c>Node</c> itself.
    /// </summary>
    static string? BaseNodeOf(ApiModel model, ApiStruct component)
    {
        var spec = component.TagValue("base");
        if (spec is null) return null;
        if (spec.Contains('+'))
            throw new InvalidOperationException($"{component.Name}: [base:] names one node type, not '{spec}'");
        _ = model.Structs.FirstOrDefault(x => x.TagValue("node") == spec)
            ?? throw new InvalidOperationException(
                $"{component.Name} extends '{spec}', which no [node:] struct in this domain declares; "
                + "add its header to the domain's composeHeaders");
        return spec;
    }

    /// <summary>
    /// The <c>[default:]</c> seeding for one component, targeting its own backing slot. The
    /// values are not spelled again here: the state the node holds is the component's own
    /// projection, so the neutral surface it starts on is the one that projection already
    /// declares.
    /// </summary>
    static IEnumerable<string> ComponentInit(ApiStruct c, int index, Convention convention)
    {
        if (!c.Fields.Any(f => f.TagValue("default") is not null)) yield break;
        yield return $"_generatedState{index} = {Idioms.TypeName(c.Name, convention)}.Default;";
    }

    /// <summary>
    /// One component's contribution to the node's flat property surface. Every property
    /// names the component it belongs to, so the Roslyn generator routes it without having
    /// to resolve a field name that two composed components could both declare.
    /// </summary>
    static IEnumerable<string> ComponentSurface(ApiModel model, ApiStruct c, Convention convention)
    {
        foreach (var f in c.Fields)
        {
            if (f.Has("idiom")) continue;

            var propName = Idioms.Pascal(f.TagValue("name") ?? f.Name);
            var propType = NodePropertyType(model, f, convention);
            yield return "";
            if (!string.IsNullOrEmpty(f.Doc)) yield return $"    /// <summary>{Escape(f.Doc)}</summary>";
            yield return $"    [NativeField(\"{Idioms.Pascal(f.Name)}\", Component = "
                + $"typeof({Idioms.TypeName(c.Name, convention)}))]";
            yield return $"    public partial {propType} {propName} {{ get; set; }}";
        }
    }

    static int? VectorArity(string cType)
    {
        var m = System.Text.RegularExpressions.Regex.Match(cType.Trim(), @"^float\s*\[(\d+)\]$");
        return m.Success && int.Parse(m.Groups[1].Value) is >= 2 and <= 4 ? int.Parse(m.Groups[1].Value) : null;
    }

    static bool IsCharArray(string cType) =>
        System.Text.RegularExpressions.Regex.IsMatch(cType.Trim(), @"^(const\s+)?char\s*\[\d+\]$");

    static string NodePropertyType(ApiModel model, ApiField f, Convention convention) =>
        IsCharArray(f.Type) ? "string" :
        convention.HandleTypes.TryGetValue(f.Type.Trim(), out var h) ? h :
        VectorArity(f.Type) is int n ? $"Vector{n}"
        : convention.VectorTypes.TryGetValue(f.Type.Trim(), out var v) ? v.Managed
        : model.Enums.Any(e => e.Name == f.Type.Trim()) ? Idioms.TypeName(f.Type.Trim(), convention)
        : f.Has("bool") ? "bool" : CsType(model, f.Type, convention);

    public static string RenderEnums(ApiModel model, string ns, Convention convention)
    {
        var o = new List<string> { Header, $"namespace {ns};\n" };
        foreach (var e in model.Enums.Where(e => !e.External))
        {
            o.Add(e.Doc is not null
                ? XmlDoc("", e.Doc, convention).TrimEnd()
                : $"/// <summary>Mirrors <c>{e.Name}</c>.</summary>");
            o.Add($"public enum {Idioms.TypeName(e.Name, convention)}");
            o.Add("{");
            foreach (var v in e.Values)
            {
                if (!string.IsNullOrEmpty(v.Doc)) o.Add($"    /// <summary>{Escape(v.Doc)}</summary>");
                var name = Idioms.EnumMember(v.Name, e.Name);
                var val = v.IsInt ? v.RawValue : Idioms.EnumMember(v.RawValue, e.Name);
                o.Add($"    {name} = {val},");
            }
            o.Add("}");
            o.Add("");
        }
        return string.Join('\n', o);
    }

    /// <summary>
    /// Emits the structs a header marked <c>[value]</c>: plain data a caller holds and hands
    /// back, as opposed to the handles, parameter bags and vtables that are the ABI's own
    /// plumbing. The alternative in this codebase has been a second hand-written spelling
    /// plus a reinterpret cast between the two, where the only thing asserting the layouts
    /// agree is the sentence next to the cast.
    /// </summary>
    public static string RenderStruct(ApiModel model, ApiStruct s, string ns,
        IEnumerable<string> extraUsings, Convention convention)
    {
        var needsNumerics = s.Fields.Any(f => ValueFieldType(model, s, f, convention)
            is var t && (t.StartsWith("Vector", StringComparison.Ordinal)
                || t is "Quaternion" or "Matrix4x4"));
        var inlineArrays = s.Fields
            .Select(f => (Field: f, Array: ValueArray(model, s, f, convention)))
            .Where(x => x.Array is not null)
            .Select(x => (x.Field, Array: x.Array!.Value))
            .ToList();

        var borrowsAType = s.Fields.Any(f => NamesForeignDeclaration(model, f));

        var o = new List<string> { Header };
        if (needsNumerics) o.Add("using System.Numerics;");
        if (inlineArrays.Count > 0) o.Add("using System.Runtime.CompilerServices;");
        o.Add("using System.Runtime.InteropServices;");
        if (borrowsAType) foreach (var u in extraUsings) o.Add($"using {u};");
        o.Add("");
        o.Add($"namespace {ns};\n");
        o.Add(s.Doc is not null
            ? XmlDoc("", s.Doc, convention).TrimEnd()
            : $"/// <summary>Mirrors <c>{s.Name}</c>.</summary>");
        o.Add("[StructLayout(LayoutKind.Sequential)]");
        o.Add($"public partial struct {Idioms.TypeName(s.Name, convention)}");
        o.Add("{");
        if (convention.IsComponentType(s.Name))
        {
            o.Add("    /// <summary>The name this component is registered under, which is its only"
                + " identity across languages. Derived from the struct the ABI declares, so a caller"
                + " naming the component and the storage holding it cannot come to disagree.</summary>");
            o.Add($"    public const string Name = \"{convention.ComponentNameFor(s.Name)}\";");
            o.Add("");
        }
        foreach (var (f, array) in inlineArrays)
        {
            o.Add($"    /// <summary>Elements <c>{Idioms.Pascal(f.Name)}</c> has room for, as the ABI"
                + " fixes it. A caller composing the field from a set it does not control checks this"
                + " first -- there is no element past it to write.</summary>");
            o.Add($"    public const int {Idioms.Pascal(f.Name)}Capacity = {array.Arity};");
            o.Add("");
        }
        foreach (var f in s.Fields)
        {
            if (!string.IsNullOrEmpty(f.Doc)) o.Add($"    /// <summary>{Escape(f.Doc)}</summary>");
            o.Add($"    public {ValueFieldType(model, s, f, convention)} {Idioms.Pascal(f.Name)};");
        }

        var seeded = s.Fields.Where(f => f.TagValue("default") is not null).ToList();
        if (seeded.Count > 0)
        {
            var typeName = Idioms.TypeName(s.Name, convention);
            o.Add("");
            o.Add($"    /// <summary>The value every <c>[default:]</c> field of <c>{s.Name}</c> declares."
                + " A zero-initialized instance is not the same thing: zero is a value the ABI reads as"
                + " itself, so a field whose neutral value is not zero has to be seeded.</summary>");
            o.Add($"    public static {typeName} Default => new()");
            o.Add("    {");
            foreach (var f in seeded) o.Add($"        {ValueDefault(model, s, f, convention)}");
            o.Add("    };");
        }

        foreach (var (f, array) in inlineArrays)
        {
            o.Add("");
            o.Add($"    /// <summary>The <c>{f.Type.Trim()}</c> of <c>{Idioms.Pascal(f.Name)}</c> laid"
                + " out inline, so the field occupies the bytes the ABI reads it from.</summary>");
            o.Add($"    [InlineArray({Idioms.Pascal(f.Name)}Capacity)]");
            o.Add($"    public partial struct {array.Buffer}");
            o.Add("    {");
            o.Add($"        public {array.Element} Element;");
            o.Add("    }");
        }
        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

    /// <summary>
    /// Emits the span each <c>[array_of:]</c> field of a struct reads as, onto the struct the
    /// ABI declares rather than a second type beside it. A pointer and the count bounding it
    /// are one value wherever they sit: a slot answering with the pair already hands out a
    /// span, and a caller reaching the same pair through a field otherwise re-derives the
    /// bounds the declaration had already given.
    /// </summary>
    public static string RenderStructSpans(ApiModel model, ApiStruct s, string nativeNs, Convention convention)
    {
        var o = new List<string> { Header };
        o.Add($"namespace {nativeNs};\n");
        o.Add($"/// <summary>The counted pointers of <c>{s.Name}</c>, read as the sequences they"
            + " bound.</summary>");
        o.Add($"public unsafe partial struct {s.Name}");
        o.Add("{");

        var first = true;
        foreach (var f in s.Fields.Where(x => x.Has("array_of")))
        {
            if (!first) o.Add("");
            first = false;

            if (!CTypes.IsPointer(f.Type))
                throw new InvalidOperationException(
                    $"{s.Name}.{f.Name}: [array_of] bounds the elements a pointer reaches, and "
                    + $"{f.Type.Trim()} is not one");

            var countName = f.TagValue("array_of");
            var count = s.Fields.FirstOrDefault(x => x.Name == countName)
                ?? throw new InvalidOperationException(
                    $"{s.Name}.{f.Name}: [array_of:{countName}] names a length field the struct "
                    + "does not declare");

            var element = ValueTypeName(model, StripQualifiers(CTypes.Deref(f.Type)), convention);
            o.Add(!string.IsNullOrEmpty(f.Doc)
                ? $"    /// <summary>{Escape(f.Doc)}</summary>"
                : $"    /// <summary>The <c>{count.Name}</c> elements <c>{f.Name}</c> reaches.</summary>");
            o.Add($"    public readonly ReadOnlySpan<{element}> {Idioms.Pascal(f.Name)} => {f.Name} == null"
                + $" ? default : new ReadOnlySpan<{element}>({f.Name}, (int){count.Name});");
        }

        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

    /// <summary>
    /// Whether a struct is projected as a reading of memory someone else owns.
    /// <c>[value]</c> answers a different question and refuses this one on purpose: it
    /// describes data a caller holds, so a pointer field there would make the lifetime of
    /// what it reaches someone else's question. A <c>[view]</c> never owns its bytes, so a
    /// pointer is exactly what it is built to read -- bounded by the count the header
    /// already names, and reached only through the sequence it stands for.
    /// </summary>
    public static bool IsView(ApiStruct s) => !s.External && !s.IsVtable && s.Has("view");

    /// <summary>
    /// The element a <c>[view]</c> hands out for a pointer field. A projection occupies the
    /// same bytes as the declaration it stands for, so the pointer is declared as reaching
    /// the projection rather than the ABI spelling: the sequence then needs no cast, and a
    /// reading that would otherwise reinterpret one type as another stops asserting a layout
    /// the compiler was never shown.
    /// </summary>
    static string ViewElement(ApiModel model, string cType, Convention convention) =>
        model.Structs.Any(v => v.Name == cType.Trim() && !v.IsVtable
            && (v.Has("value") || v.Has("node") || v.Has("view")))
            ? Idioms.TypeName(cType.Trim(), convention)
            : ValueTypeName(model, cType, convention);

    /// <summary>
    /// Whether a field of a <c>[view]</c> is read as a type some other domain declares,
    /// pointer or not. A counted pointer is the one shape where the element is named after
    /// dereferencing, so asking the field's own spelling would miss exactly the case the
    /// projection exists to compose.
    /// </summary>
    static bool ViewNamesForeignDeclaration(ApiModel model, ApiField f)
    {
        if (NamesForeignDeclaration(model, f)) return true;
        if (!CTypes.IsPointer(f.Type)) return false;
        var element = StripQualifiers(CTypes.Deref(f.Type)).Trim();
        return model.Structs.Any(v => v.Name == element && v.External);
    }

    /// <summary>
    /// Emits the projection a <c>[view]</c> struct is read through. Every field is private:
    /// a pointer and the count bounding it are one sequence, and a caller given the pair
    /// re-derives bounds the declaration had already stated, while a fixed char array read
    /// as its bytes is text spelled as storage. The struct still occupies the bytes the ABI
    /// lays out, which is what lets a sequence of these stand directly on native memory.
    /// </summary>
    public static string RenderView(ApiModel model, ApiStruct s, string ns,
        IEnumerable<string> extraUsings, Convention convention)
    {
        var counts = s.Fields.Where(f => f.Has("array_of"))
            .Select(f => f.TagValue("array_of")).ToHashSet();

        var o = new List<string> { Header };
        o.Add("using System.Runtime.InteropServices;");
        if (s.Fields.Any(f => ViewNamesForeignDeclaration(model, f)))
            foreach (var u in extraUsings) o.Add($"using {u};");
        o.Add("");
        o.Add($"namespace {ns};\n");
        o.Add(s.Doc is not null
            ? XmlDoc("", s.Doc, convention).TrimEnd()
            : $"/// <summary>Reads <c>{s.Name}</c>.</summary>");
        o.Add("[StructLayout(LayoutKind.Sequential)]");
        o.Add($"public unsafe partial struct {Idioms.TypeName(s.Name, convention)}");
        o.Add("{");

        foreach (var f in s.Fields) o.Add($"    {ViewField(model, s, f, convention)}");

        foreach (var f in s.Fields)
        {
            if (counts.Contains(f.Name)) continue;
            o.Add("");
            if (!string.IsNullOrEmpty(f.Doc)) o.Add($"    /// <summary>{Escape(f.Doc)}</summary>");
            foreach (var line in ViewAccessor(model, s, f, convention)) o.Add($"    {line}");
        }

        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

    /// <summary>
    /// One field of a <c>[view]</c> as it is stored. A fixed char array stays the bytes the
    /// ABI reads it from rather than becoming a reference of another size, so the text is
    /// read through the storage instead of replacing it.
    /// </summary>
    static string ViewField(ApiModel model, ApiStruct s, ApiField f, Convention convention)
    {
        if (CTypes.FixedArray(f.Type) is { } arr)
        {
            var element = Idioms.CsPrimitive(StripQualifiers(arr.Element), convention);
            if (element is "sbyte" or "byte" or "short" or "ushort" or "int" or "uint"
                or "long" or "ulong" or "float" or "double")
                return $"private fixed {element} {f.Name}[{arr.Extent}];";
            throw new InvalidOperationException(
                $"{s.Name}.{f.Name}: a [view] reads an inline array through the bytes it occupies,"
                + $" and {arr.Element.Trim()} is not a type those bytes can be spelled as.");
        }

        if (!CTypes.IsPointer(f.Type))
            return $"private readonly {ValueTypeName(model, f.Type, convention)} {f.Name};";

        if (!f.Has("array_of"))
            throw new InvalidOperationException(
                $"{s.Name}.{f.Name}: a [view] reads a pointer as the sequence it bounds, so the"
                + " field has to name the count bounding it with [array_of:<field>]. A pointer"
                + " with no extent is a reading nobody can make safely.");

        return $"private readonly {ViewElement(model, StripQualifiers(CTypes.Deref(f.Type)), convention)}"
            + $"* {f.Name};";
    }

    /// <summary>
    /// The reading one field of a <c>[view]</c> is surfaced as. A counted pointer answers
    /// with the sequence it bounds, a fixed char array with the text its bytes spell, and
    /// anything else with itself.
    /// </summary>
    static IEnumerable<string> ViewAccessor(ApiModel model, ApiStruct s, ApiField f,
        Convention convention)
    {
        var name = Idioms.Pascal(f.Name);

        if (f.Has("array_of"))
        {
            var countName = f.TagValue("array_of");
            var count = s.Fields.FirstOrDefault(x => x.Name == countName)
                ?? throw new InvalidOperationException(
                    $"{s.Name}.{f.Name}: [array_of:{countName}] names a length field the struct"
                    + " does not declare");
            var element = ViewElement(model, StripQualifiers(CTypes.Deref(f.Type)), convention);
            return [$"public readonly ReadOnlySpan<{element}> {name} => {f.Name} == null"
                + $" ? default : new ReadOnlySpan<{element}>({f.Name}, (int){count.Name});"];
        }

        if (CTypes.FixedArray(f.Type) is { } arr)
        {
            var element = Idioms.CsPrimitive(StripQualifiers(arr.Element), convention);
            if (element is "sbyte")
                return
                [
                    $"public readonly string {name}",
                    "{",
                    $"    get {{ fixed (sbyte* p = {f.Name}) return Marshal.PtrToStringUTF8((nint)p) ?? \"\"; }}",
                    "}",
                ];
            return
            [
                $"public readonly ReadOnlySpan<{element}> {name}",
                "{",
                $"    get {{ fixed ({element}* p = {f.Name}) return new ReadOnlySpan<{element}>(p, {arr.Extent}); }}",
                "}",
            ];
        }

        return [$"public readonly {ValueTypeName(model, f.Type, convention)} {name} => {f.Name};"];
    }

    /// <summary>
    /// Whether a field is spelled with a type some other domain declares. The domain
    /// composing the type emits nothing for it -- the one that owns it already does -- so
    /// the projection reaches it by name, and only a struct that actually names one needs
    /// the namespaces the domain composes from.
    /// </summary>
    static bool NamesForeignDeclaration(ApiModel model, ApiField f)
    {
        var t = StripQualifiers(CTypes.FixedArray(f.Type)?.Element ?? f.Type).Trim();
        return model.Enums.Any(e => e.Name == t && e.External)
            || model.Structs.Any(v => v.Name == t && v.External);
    }

    /// <summary>
    /// Whether a struct is projected as a managed mirror occupying the same bytes.
    /// <c>[node:]</c> answers this as much as <c>[value]</c> does: the node's backing state
    /// is one of these structs, and a node whose state were the raw binding type would be
    /// asserting a layout instead of naming one.
    /// </summary>
    public static bool IsValue(ApiStruct s) =>
        !s.External && !s.IsVtable && (s.Has("value") || s.Has("node"));

    /// <summary>
    /// Whether a struct is one a caller builds and the native side only reads while a call
    /// lasts. <c>[value]</c> refuses a pointer field because it would make the lifetime of what
    /// it reaches someone else's question; here the lifetime is stated -- the call -- so the
    /// pointer is projected as memory the caller keeps alive for it.
    /// </summary>
    public static bool IsBorrowed(ApiStruct s) => !s.External && !s.IsVtable && s.Has("borrowed");

    /// <summary>
    /// Emits the managed side of a <c>[borrowed]</c> struct: each counted pointer is memory
    /// whose length is the count, and the count itself is not a field -- it is read off the
    /// memory when the call is made, so it cannot disagree with what it bounds.
    /// </summary>
    public static string RenderBorrowed(ApiModel model, ApiStruct s, string ns,
        IEnumerable<string> extraUsings, Convention convention)
    {
        var counts = new HashSet<string>();
        var fields = new List<string>();
        foreach (var f in s.Fields)
        {
            if (!CTypes.IsPointer(f.Type)) continue;

            var countName = f.TagValue("array_of")
                ?? throw new InvalidOperationException(
                    $"{s.Name}.{f.Name}: a pointer in a [borrowed] struct is memory the call reads, and"
                    + " one that names no count has no extent to read -- tag it [array_of:<count field>].");
            var count = s.Fields.FirstOrDefault(x => x.Name == countName)
                ?? throw new InvalidOperationException(
                    $"{s.Name}.{f.Name}: [array_of:{countName}] names a length field the struct does not declare");
            counts.Add(count.Name);

            var element = ValueTypeName(model, StripQualifiers(CTypes.Deref(f.Type)), convention);
            if (!string.IsNullOrEmpty(f.Doc)) fields.Add($"    /// <summary>{Escape(f.Doc)}</summary>");
            fields.Add($"    public ReadOnlyMemory<{element}> {Idioms.Pascal(f.Name)};");
        }

        foreach (var f in s.Fields.Where(x => !CTypes.IsPointer(x.Type) && !counts.Contains(x.Name)))
        {
            var type = ValueFieldType(model, s, f, convention);
            if (type != CsType(model, f.Type, convention))
                throw new InvalidOperationException(
                    $"{s.Name}.{f.Name}: a [borrowed] struct is rebuilt field by field into the native one,"
                    + $" so a scalar has to be spelled the same on both sides and {type} is not {CsType(model, f.Type, convention)}.");
            if (!string.IsNullOrEmpty(f.Doc)) fields.Add($"    /// <summary>{Escape(f.Doc)}</summary>");
            fields.Add($"    public {type} {Idioms.Pascal(f.Name)};");
        }

        var borrowsAType = s.Fields.Any(f =>
        {
            var named = StripQualifiers(CTypes.IsPointer(f.Type) ? CTypes.Deref(f.Type) : f.Type).Trim();
            return model.Enums.Any(e => e.Name == named && e.External)
                || model.Structs.Any(v => v.Name == named && v.External);
        });

        var o = new List<string> { Header, "using System;" };
        if (borrowsAType) foreach (var u in extraUsings) o.Add($"using {u};");
        o.Add("");
        o.Add($"namespace {ns};\n");
        o.Add(s.Doc is not null
            ? XmlDoc("", s.Doc, convention).TrimEnd()
            : $"/// <summary>Mirrors <c>{s.Name}</c>, for the length of one call.</summary>");
        o.Add($"public partial struct {Idioms.TypeName(s.Name, convention)}");
        o.Add("{");
        o.AddRange(fields);
        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

    /// <summary>
    /// The fixed-size array a <c>[value]</c> field describes, or null when it describes a
    /// single element. A managed struct cannot spell <c>T[8]</c> inline for a <c>T</c> that
    /// is itself a struct, so the arity moves into an <c>[InlineArray]</c> wrapper that
    /// occupies the same bytes -- the alternative being a field that silently stands for
    /// one element where the ABI reads several.
    /// </summary>
    static (string Buffer, string Element, int Arity)? ValueArray(ApiModel model, ApiStruct s, ApiField f,
        Convention convention)
    {
        if (CTypes.FixedArray(f.Type) is not { } arr || VectorArity(f.Type) is not null) return null;

        var element = arr.Element;
        if (CTypes.IsPointer(element))
            throw new InvalidOperationException(
                $"{s.Name}.{f.Name}: [value] describes data a caller holds, and an array of"
                + " pointers makes the lifetime of what they reach someone else's question.");

        return ($"{Idioms.Pascal(f.Name)}Buffer", ValueTypeName(model, element, convention),
            arr.Extent);
    }

    /// <summary>
    /// A C type named inside a <c>[value]</c> struct or handed out as a sequence of one.
    /// Another <c>[value]</c> struct resolves to its own managed mirror rather than the
    /// native spelling, so the two projections compose instead of a caller holding one
    /// type whose fields are the other.
    /// </summary>
    static string ValueTypeName(ApiModel model, string cType, Convention convention) =>
        convention.MatrixTypes.TryGetValue(cType.Trim(), out var mat) ? mat
        : convention.HandleTypes.TryGetValue(cType.Trim(), out var handle) ? handle
        : model.Structs.Any(v => v.Name == cType.Trim() && (IsValue(v) || IsBorrowed(v)))
        || model.Enums.Any(e => e.Name == cType.Trim())
            ? Idioms.TypeName(cType.Trim(), convention)
            : CsType(model, cType, convention);

    /// <summary>
    /// The type one field of a <c>[value]</c> struct takes. Every answer here has to occupy
    /// the same bytes as the field it stands for, because the struct is handed to native code
    /// as itself rather than marshalled field by field. That rules out the conveniences a
    /// node property affords: a fixed char array reads far better as a string, but a string
    /// is a reference of another size, so the field stays the bytes it is and the text is
    /// read through them.
    /// </summary>
    static string ValueFieldType(ApiModel model, ApiStruct s, ApiField f, Convention convention)
    {
        if (CTypes.IsPointer(f.Type))
            throw new InvalidOperationException(
                $"{s.Name}.{f.Name}: [value] describes data a caller holds, and a pointer"
                + " field makes the lifetime of that data someone else's question. Describe"
                + " the pointer as a sequence on the slot that hands it out instead, or, when"
                + " it only has to outlive the call that takes the struct, declare the struct"
                + " [borrowed].");

        if (VectorArity(f.Type) is int n) return $"Vector{n}";
        if (convention.VectorTypes.TryGetValue(f.Type.Trim(), out var v)) return v.Managed;
        if (ValueArray(model, s, f, convention) is { } array) return array.Buffer;
        return ValueTypeName(model, f.Type, convention);
    }

    /// <summary>
    /// One field's seeding inside a <c>[value]</c> struct's <c>Default</c>. The header states
    /// the neutral value per field, and it is the same statement the node constructor and the
    /// scene loader read -- spelling it again beside a hand-written mirror is how the two come
    /// to describe different neutral surfaces.
    /// </summary>
    static string ValueDefault(ApiModel model, ApiStruct s, ApiField f, Convention convention)
    {
        var d = f.TagValue("default")!.Trim();
        var name = Idioms.Pascal(f.Name);
        var parts = d.Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);

        var lanes = VectorArity(f.Type) is int n ? n
            : convention.VectorTypes.TryGetValue(f.Type.Trim(), out var v) ? v.Lanes.Length
            : 1;
        if (lanes > 1)
        {
            if (parts.Length != lanes)
                throw new InvalidOperationException(
                    $"{s.Name}.{f.Name}: [default:{d}] has {parts.Length} components but the field"
                    + $" holds {lanes}.");
            return $"{name} = new {ValueFieldType(model, s, f, convention)}"
                + $"({string.Join(", ", parts.Select(p => p + "f"))}),";
        }

        if (ValueArray(model, s, f, convention) is not null)
            throw new InvalidOperationException(
                $"{s.Name}.{f.Name}: [default:{d}] states one value and the field holds an array of"
                + " them. A default a caller can read is a single value, not a fill.");

        var type = ValueFieldType(model, s, f, convention);
        if (model.Enums.Any(e => e.Name == f.Type.Trim()))
            return $"{name} = {type}.{Idioms.EnumMember(d, f.Type.Trim())},";
        return $"{name} = {d}{(type is "float" ? "f" : "")},";
    }

    /// <summary>
    /// Emits one borrow wrapper per value of an enum that names where a borrow looks.
    /// The engine asks one question with the region as a parameter, so a projection
    /// that hands borrows to a script body needs one type per region and nothing else
    /// varying between them; writing them out by hand is copying the same struct once
    /// per enum value and letting the copies drift.
    /// </summary>
    public static string RenderBorrowWrappers(ApiEnum kinds, string ns, Convention convention)
    {
        var enumType = Idioms.TypeName(kinds.Name, convention);
        var o = new List<string> { Header, $"namespace {ns};\n" };

        o.Add("/// <summary>");
        o.Add($"/// Marks a borrow wrapper with the <c>{enumType}</c> it resolves with, so a");
        o.Add("/// projection recognises a borrow parameter by what it means rather than by a list");
        o.Add("/// of type names kept in step by hand.");
        o.Add("/// </summary>");
        o.Add("[AttributeUsage(AttributeTargets.Struct)]");
        o.Add("public sealed class NodeBorrowAttribute : Attribute");
        o.Add("{");
        o.Add("    /// <summary>Where this wrapper's borrow looks for the node it names.</summary>");
        o.Add($"    public {enumType} Reach {{ get; }}");
        o.Add("");
        o.Add("    /// <param name=\"reach\">Where this wrapper's borrow looks for the node it names.</param>");
        o.Add($"    public NodeBorrowAttribute({enumType} reach) => Reach = reach;");
        o.Add("}");
        o.Add("");

        foreach (var v in kinds.Values)
        {
            var member = Idioms.EnumMember(v.Name, kinds.Name);
            o.Add("/// <summary>");
            o.Add($"/// {Escape(v.Doc ?? $"A borrow resolved with {member}.")} Obtained as a parameter rather");
            o.Add("/// than stored in a field: re-resolved each time it is handed over, so it can never");
            o.Add("/// dangle, and its type is what puts <typeparamref name=\"T\"/>'s components into the");
            o.Add("/// borrowing body's access list.");
            o.Add("/// </summary>");
            o.Add($"[NodeBorrow({enumType}.{member})]");
            o.Add($"public readonly ref struct {member}<T> where T : class");
            o.Add("{");
            o.Add("    private readonly T? _node;");
            o.Add("");
            o.Add("    /// <summary>The borrowed node, or null when none matched.</summary>");
            o.Add("    public T? Node => _node;");
            o.Add("");
            o.Add("    /// <summary>True when a node matched this borrow.</summary>");
            o.Add("    public bool IsBound => _node is not null;");
            o.Add("");
            o.Add("    /// <param name=\"node\">The node this borrow resolved to, or null when none matched.</param>");
            o.Add($"    public {member}(T? node) => _node = node;");
            o.Add("");
            o.Add("    /// <summary>Unwraps the borrow, throwing when nothing matched.</summary>");
            o.Add("    public T Value => _node ?? throw new InvalidOperationException(");
            o.Add($"        $\"No node of type {{typeof(T).Name}} is bound for this {member.ToLowerInvariant()} borrow.\");");
            o.Add("}");
            o.Add("");
        }
        return string.Join('\n', o);
    }

    /// <summary>
    /// Emits the type-to-id cache for a slot that interns a type under its name and
    /// payload size. The engine identifies the thing by those two values precisely so
    /// that two languages agree on it; what a language then needs is the trip back to
    /// its own type system, and every binding runtime would otherwise write the same
    /// pair of dictionaries by hand.
    /// </summary>
    static void RenderInterning(List<string> o, ApiSlot slot, ApiModel model, Convention convention)
    {
        var name = Idioms.Pascal(slot.Name);
        var nameParam = slot.Params.FirstOrDefault(p => p.Has("type_name"));
        var sizeParam = slot.Params.FirstOrDefault(p => p.Has("type_size"));
        if (nameParam is null || sizeParam is null) return;

        var ids = $"_{Idioms.Ident(slot.Name)}Ids";
        var types = $"_{Idioms.Ident(slot.Name)}Types";

        o.Add($"    private readonly Dictionary<Type, uint> {ids} = new();");
        o.Add($"    private readonly Dictionary<uint, Type> {types} = new();");
        o.Add("");
        o.Add($"    /// <summary>The id <typeparamref name=\"T\"/> interns to, registering it on first use.</summary>");
        o.Add($"    public uint {name}Of<T>() where T : unmanaged");
        o.Add("    {");
        o.Add($"        if ({ids}.TryGetValue(typeof(T), out var cached)) return cached;");
        o.Add($"        var resolved = {name}(typeof(T).Name, (uint)sizeof(T));");
        o.Add($"        {ids}[typeof(T)] = resolved;");
        o.Add($"        {types}[resolved] = typeof(T);");
        o.Add("        return resolved;");
        o.Add("    }");
        o.Add("");
        o.Add("    /// <summary>");
        o.Add($"    /// The type <paramref name=\"id\"/> was interned for, or null when this runtime never");
        o.Add("    /// interned one. Null is a normal answer rather than a failure: an id another");
        o.Add("    /// language registered is real, and simply has no type here to name it.");
        o.Add("    /// </summary>");
        o.Add($"    public Type? {name}TypeOf(uint id) => {types}.TryGetValue(id, out var t) ? t : null;");
        o.Add("");
    }

    /// <summary>
    /// The class projecting a vtable, and -- where the vtable declares one -- the contract
    /// naming what it can do. The two are separate units because the contract is what a
    /// caller depends on and the class is what satisfies it: emitting them together puts
    /// the contract in whichever assembly holds the native call, so depending on the
    /// capability drags the implementation along with it.
    /// </summary>
    public readonly record struct ProviderSource(string Class, string? Contract);

    public static ProviderSource RenderProvider(ApiModel model, ApiStruct vtable, ClassifiedModel classified,
        string ns, string nativeNs, IReadOnlyList<string> extraUsings, Convention convention)
    {
        var typeName = Idioms.TypeName(vtable.Name, convention);
        var slots = classified.SlotsByVtable[vtable.Name];
        var plan = classified.Constructors[vtable.Name];

        var o = new List<string>
        {
            Header,
            "using System.Runtime.CompilerServices;",
            "using System.Runtime.InteropServices;",
            $"using {convention.CommonManagedNamespace};",
            $"using {convention.CommonBindingsNamespace};",
            $"using {nativeNs};",
        };
        if (HasVectorParams(vtable)) o.Add("using System.Numerics;");
        foreach (var u in extraUsings) o.Add($"using {u};");
        o.Add("");
        o.Add($"namespace {ns};");
        o.Add("");

        var nativeIface = "INative" + Idioms.Pascal(convention.StripPrefix(vtable.Name));
        o.Add($"/// <summary>Exposes the raw native {typeName.ToLowerInvariant()} pointer for cross-domain composition wiring.</summary>");
        o.Add($"public unsafe interface {nativeIface}");
        o.Add("{");
        o.Add($"    {vtable.Name}* Native {{ get; }}");
        o.Add("}");
        o.Add("");

        var domainIface = vtable.Has("interface") ? "I" + typeName : null;
        var decls = domainIface is null ? null : new List<MemberDecl>();

        var contractNamesForeignProjections = vtable.Slots
            .Any(s => s.Params.Any(p => p.Has("provider")));

        var contract = domainIface is null ? null : new List<string> { Header };
        if (contract is not null)
        {
            if (HasVectorParams(vtable)) contract.Add("using System.Numerics;");
            contract.Add($"using {convention.CommonManagedNamespace};");
            if (contractNamesForeignProjections)
                foreach (var u in extraUsings) contract.Add($"using {u};");
            contract.Add("");
            contract.Add($"namespace {ns};");
            contract.Add("");
        }

        var closures = VtableClosures(model, slots, convention);
        var closureGroups = VtableClosureGroups(model, slots, typeName, convention);
        foreach (var cb in closures.DistinctBy(c => c.Delegate))
            RenderClosureDelegate(model, contract ?? o, cb, domainIface ?? typeName, convention);

        var owned = OwnedOf(model, vtable, convention);
        if (owned is not null)
            RenderOwned(o, owned, typeName, SlotName(owned.Release));

        o.Add(XmlDoc("", vtable.Doc, convention).TrimEnd());
        o.Add($"public unsafe partial class {typeName} : IDisposable, {nativeIface}"
            + (domainIface is null ? "" : $", {domainIface}"));
        o.Add("{");
        o.Add($"    private {vtable.Name}* _native;");
        o.Add($"    private readonly delegate* unmanaged[Cdecl]<{vtable.Name}*, void> _destroy;");
        o.Add("    private readonly bool _borrowed;");

        var rootedKey = vtable.Slots
            .SelectMany(s => s.Params.Where(p => p.Has("rooted")).Select(p => (Slot: s, Param: p)))
            .Select(x => x.Slot.Params.FirstOrDefault(k => k.Name == x.Param.TagValue("rooted")))
            .FirstOrDefault(k => k is not null);

        if (rootedKey is not null)
        {
            o.Add("");
            o.Add("    /// <summary>");
            o.Add("    /// Keeps alive every managed object handed to the native side as an opaque");
            o.Add("    /// pointer. The engine stores the pointer and never dereferences it, so nothing");
            o.Add("    /// over there stops the collector from moving or reclaiming the object; the");
            o.Add("    /// handle is what makes the pointer mean anything by the time it comes back.");
            o.Add("    /// </summary>");
            o.Add($"    private readonly System.Collections.Concurrent.ConcurrentDictionary<{CsType(model, rootedKey.Type, convention)}, GCHandle> _rooted = new();");
        }

        foreach (var cg in closureGroups.Where(c => c.Lifetime == ClosureLifetime.Retained))
        {
            o.Add("");
            o.Add("    /// <summary>");
            o.Add(cg.Keyed
                ? "    /// Keeps every registered handler reachable, one per key the slot registers"
                    + " against."
                : cg.Shared
                    ? "    /// Keeps the registered handlers reachable, all of them through the one"
                        + " context they share."
                    : "    /// Keeps the registered handler reachable.");
            o.Add("    /// The engine holds only an opaque pointer to it, which stops nothing on this");
            o.Add("    /// side from collecting or moving the object before the engine calls back into it.");
            o.Add("    /// </summary>");
            o.Add(cg.Keyed
                ? $"    private readonly Dictionary<{cg.KeyType ?? CsType(model, cg.RetainKey!.Type, convention)}, GCHandle>"
                    + $" {cg.Retained} = new();"
                : $"    private GCHandle {cg.Retained};");
        }

        if (closures.Any(c => c.ErrorLane is null))
        {
            o.Add("");
            o.Add("    /// <summary>");
            o.Add("    /// Where a managed exception waits out the native frames. A handler runs");
            o.Add("    /// underneath engine code that has no way to carry an exception, so throwing");
            o.Add("    /// through it would tear down the process; the trampoline parks it here and");
            o.Add("    /// the call rethrows once the native stack has unwound. Per-thread, because");
            o.Add("    /// a handler runs on whichever thread the engine called it from.");
            o.Add("    /// </summary>");
            o.Add("    [ThreadStatic]");
            o.Add("    private static Exception? s_parkedCallbackException;");
        }

        if (closureGroups.Any(c => c.Pairs.Any(c.Queues)))
        {
            o.Add("");
            o.Add("    /// <summary>");
            o.Add("    /// What retained handlers of this provider have thrown and not yet been told");
            o.Add("    /// about. A retained handler outlives the call that registered it, so there is");
            o.Add("    /// no call left to rethrow at; it reports failure through its own channel and");
            o.Add("    /// leaves the exception here for whichever call observes that failure. A handler");
            o.Add("    /// may run on any thread the engine calls it from, and may fail more than once");
            o.Add("    /// before anyone asks, so nothing here is ever discarded unread.");
            o.Add("    /// </summary>");
            o.Add("    private readonly System.Collections.Concurrent.ConcurrentQueue<Exception>"
                + " _callbackFailures = new();");
            o.Add("");
            o.Add("    /// <summary>");
            o.Add("    /// Throws what retained handlers have reported since the last drain, as they");
            o.Add("    /// threw it, or returns when none have. More than one may have failed before");
            o.Add("    /// anyone asked, so they are reported together rather than the last one winning.");
            o.Add("    /// </summary>");
            o.Add("    private void DrainCallbackFailures()");
            o.Add("    {");
            o.Add("        var collected = new List<Exception>();");
            o.Add("        while (_callbackFailures.TryDequeue(out var failure)) collected.Add(failure);");
            o.Add("        if (collected.Count == 0) return;");
            o.Add("        throw new InvalidOperationException(\"A handler registered with this"
                + " provider threw\",");
            o.Add("            collected.Count == 1 ? collected[0] : new AggregateException(collected));");
            o.Add("    }");
        }
        o.Add("");
        o.Add($"    private {vtable.Name}* Handle => _native != null ? _native");
        o.Add($"        : throw new ObjectDisposedException(nameof({typeName}));");
        o.Add("");
        o.Add($"    {vtable.Name}* {nativeIface}.Native => Handle;");
        o.Add("");

        classified.LifecycleInit.TryGetValue(vtable.Name, out var initSlot);
        classified.LifecycleShutdown.TryGetValue(vtable.Name, out var shutdownSlot);
        var initCall = initSlot is not null
            ? $"        {{ {convention.ErrorType}* err2 = null; {convention.ErrorHelperClass}.ThrowIfFailed(_native->{initSlot}(_native, &err2), err2, \"{initSlot}\"); }}"
            : null;

        if (plan.Kind == ConstructorKind.FromFactory)
        {
            var factory = plan.Factory!;
            var fparams = factory.Params.Where(p => !convention.IsErrorOutParam(p)).ToList();
            var sig = string.Join(", ", fparams.Select(p => $"{Idioms.CsForeignType(p.Type, convention)} {Idioms.Ident(p.Name!)}"));
            var call = string.Join(", ", fparams.Select(p => Idioms.Ident(p.Name!)));
            o.Add(XmlDoc("    ", factory.Doc, convention, fparams.Select(p => (Idioms.Ident(p.Name!), p.Doc)),
                throwsOnFail: true).TrimEnd());
            o.Add($"    {(plan.NeedsWrapper ? "internal" : "public")} {typeName}({sig})");
            o.Add("    {");
            o.Add($"        {convention.ErrorType}* err = null;");
            o.Add($"        var handle = {nativeNs}.NativeMethods.{convention.StripPrefix(factory.Name)}({(call.Length > 0 ? call + ", " : "")}&err);");
            o.Add($"        if (handle.@ref == null) throw {convention.ErrorHelperClass}.FromNative(err, \"{factory.Name}\");");
            o.Add("        _native = handle.@ref;");
            o.Add("        _destroy = handle.destroy;");
            if (initCall is not null) o.Add(initCall);
            o.Add("    }");
            o.Add("");
        }
        else if (plan.Kind == ConstructorKind.FromHandle)
        {
            var handleType = plan.HandleTypeName!;
            o.Add($"    /// <summary>Wraps an owner <c>{handleType}</c> and runs {typeName.ToLowerInvariant()}'s startup lifecycle hook.</summary>");
            if (initCall is not null) o.Add($"    /// <exception cref=\"{convention.ErrorHelperClass}\">The native call failed.</exception>");
            o.Add($"    public {typeName}({handleType} handle)");
            o.Add("    {");
            o.Add("        if (handle.@ref == null) throw new ArgumentNullException(nameof(handle));");
            o.Add("        _native = handle.@ref;");
            o.Add("        _destroy = handle.destroy;");
            if (initCall is not null) o.Add(initCall);
            o.Add("    }");
            o.Add("");
        }

        o.Add($"    /// <summary>Wraps a <c>{vtable.Name}*</c> owned elsewhere. Disposing the result does not destroy it.</summary>");
        o.Add($"    public static {typeName} Borrow({vtable.Name}* native) => new(native, borrowed: true);");
        o.Add("");
        o.Add($"    private {typeName}({vtable.Name}* native, bool borrowed)");
        o.Add("    {");
        o.Add("        _native = native;");
        o.Add("        _destroy = null;");
        o.Add("        _borrowed = borrowed;");
        o.Add("    }");
        o.Add("");

        foreach (var cs in slots)
        {
            if (!Projected(cs)) continue;
            if (cs.PublicParams.Any(p => !p.Has("closure") && !p.Has("completion")
                    && classified.Callbacks.Any(c => c.Name == p.Type.Trim())))
            {
                RenderCallbackMethod(o, decls, vtable, cs, classified, typeName, convention);
                continue;
            }
            RenderSlotMethod(model, o, decls, cs, convention, typeName, Drains(model, slots, convention), owned);
        }

        foreach (var slot in vtable.Slots.Where(s => s.Has("interns")))
            RenderInterning(o, slot, model, convention);

        var teardownParks = closureGroups.Any(g => g.Pairs.Any(p => p.Teardown && p.Parks));

        o.Add(teardownParks
            ? $"    /// <summary>Releases the native {typeName.ToLowerInvariant()}, and rethrows"
                + " whatever a teardown handler threw once the native stack has unwound.</summary>"
            : $"    /// <summary>Releases the native {typeName.ToLowerInvariant()}.</summary>");
        o.Add("    public void Dispose()");
        o.Add("    {");
        o.Add("        OnDispose();");
        o.Add("        if (_native == null) return;");
        if (rootedKey is not null)
        {
            o.Add("        foreach (var rooted in _rooted.Values) rooted.Free();");
            o.Add("        _rooted.Clear();");
        }
        var retainedGroups = closureGroups.Where(c => c.Lifetime == ClosureLifetime.Retained).ToList();
        var survivors = retainedGroups.Where(c => c.Pairs.Any(p => p.Teardown)).ToList();

        void FreeRetained(IEnumerable<ClosureGroup> gs, string ind = "        ")
        {
            foreach (var cg in gs)
            {
                if (cg.Keyed)
                {
                    o.Add($"{ind}foreach (var retained in {cg.Retained}.Values) retained.Free();");
                    o.Add($"{ind}{cg.Retained}.Clear();");
                }
                else
                    o.Add($"{ind}if ({cg.Retained}.IsAllocated) {cg.Retained}.Free();");
            }
        }

        FreeRetained(retainedGroups.Except(survivors));
        if (survivors.Count > 0)
        {
            o.Add("        if (_borrowed)");
            o.Add("        {");
            FreeRetained(survivors, "            ");
            o.Add("            _native = null;");
            o.Add("            return;");
            o.Add("        }");
        }
        else
            o.Add("        if (_borrowed) { _native = null; return; }");
        if (shutdownSlot is not null)
            o.Add($"        _native->{shutdownSlot}(_native, null);");
        if (teardownParks) o.Add("        s_parkedCallbackException = null;");
        o.Add("        _destroy(_native);");
        o.Add("        _native = null;");
        FreeRetained(survivors);
        if (teardownParks)
        {
            o.Add("        if (s_parkedCallbackException is { } parked)");
            o.Add("        {");
            o.Add("            s_parkedCallbackException = null;");
            o.Add("            throw parked;");
            o.Add("        }");
        }
        o.Add("    }");
        o.Add("");
        o.Add("    partial void OnDispose();");
        o.Add("}");
        o.Add("");

        if (contract is null) return new ProviderSource(string.Join('\n', o), null);

        contract.Add($"/// <summary>The {typeName.ToLowerInvariant()} contract game code depends on, so a caller"
            + $" names a capability rather than the <see cref=\"{typeName}\"/> that carries it.</summary>");
        contract.Add($"public {PointerModifier(decls!.Select(m => m.Decl))}interface {domainIface} : IDisposable");
        contract.Add("{");
        foreach (var m in decls!)
        {
            if (m.Doc.Length > 0) contract.Add(m.Doc);
            contract.Add($"    {m.InterfaceLine}");
        }
        contract.Add("}");
        contract.Add("");

        var text = string.Join('\n', contract);
        var code = string.Join('\n', contract.Where(l => !l.TrimStart().StartsWith("///", StringComparison.Ordinal)));
        var native = model.Structs.Select(s => s.Name)
            .Concat(model.Enums.Where(e => e.External).Select(e => e.Name))
            .FirstOrDefault(n => Regex.IsMatch(code, $@"\b{Regex.Escape(n)}\b"));
        if (native is not null)
            throw new InvalidOperationException(
                $"{vtable.Name}: {domainIface} names {native}, which is the ABI's own spelling rather"
                + " than a managed projection of it. A contract stands apart from the call that"
                + " satisfies it, so every type it mentions has to be one a caller can reach without"
                + " the native layer.");

        return new ProviderSource(string.Join('\n', o), text);
    }

    /// <summary>
    /// The lane each parameter occupies in a vector a run of consecutive parameters
    /// spells out. A C ABI has no vector type, so a position arrives as two floats and
    /// every language that does have one re-groups them; doing that by hand is an
    /// overload per slot whose only content is which argument goes where.
    /// </summary>
    static Dictionary<ApiParam, (string Vector, string Lane, int Arity, bool Leads)> VectorLanes(IReadOnlyList<ApiParam> ps)
    {
        var map = new Dictionary<ApiParam, (string, string, int, bool)>();
        for (var i = 0; i < ps.Count; i++)
        {
            var arity = ps[i].Has("vector2") ? 2 : ps[i].Has("vector3") ? 3 : 0;
            if (arity == 0) continue;
            var vector = ps[i].TagValue($"vector{arity}")
                ?? throw new InvalidOperationException(
                    $"{ps[i].Name}: [vector{arity}] must name the vector, as [vector{arity}:<name>]");
            if (i + arity > ps.Count)
                throw new InvalidOperationException(
                    $"{ps[i].Name}: [vector{arity}:{vector}] needs {arity} consecutive parameters, "
                    + $"but only {ps.Count - i} follow");
            for (var lane = 0; lane < arity; lane++)
                map[ps[i + lane]] = (vector, "XYZ"[lane].ToString(), arity, lane == 0);
            i += arity - 1;
        }
        return map;
    }

    /// <summary>Whether any slot on the vtable groups parameters into a vector.</summary>
    static bool HasVectorParams(ApiStruct vtable) =>
        vtable.Slots.Any(s => s.Params.Any(p => p.Has("vector2") || p.Has("vector3")));

    /// <summary>
    /// How long the managed handler must stay reachable after the call that registered it.
    /// <see cref="Scoped"/> dies with the call; <see cref="Retained"/> lives until the
    /// object is disposed or another handler replaces it. A retained closure the slot
    /// registers against a key keeps one handler per key value rather than one in total.
    /// </summary>
    internal enum ClosureLifetime { Scoped, Retained }

    /// <summary>
    /// A function-pointer parameter and the opaque context parameter that travels with
    /// it, projected as one delegate. The pair is how a C ABI carries a closure: the
    /// context is the closure's captured state and the function pointer is its body.
    /// Every lane of the function-pointer type except the context and the outbound error
    /// channel becomes a parameter of the delegate.
    /// </summary>
    internal sealed record CallbackPair(ApiParam Fn, ApiParam Ctx, ClosureLifetime Lifetime,
        string Delegate, string Trampoline, ApiCallback Callback,
        int CtxLane, int? ErrorLane, ApiParam? RetainKey, bool RetainByReturn, bool Teardown)
    {
        /// <summary>
        /// Whether a throwing handler has to wait out the native frames in the parking
        /// field instead of reporting through a lane of its own.
        /// </summary>
        public bool Parks => ErrorLane is null;
    }

    /// <summary>
    /// The name a callback typedef projects to. The typedef is where the ABI already
    /// named the concept, so two slots taking the same one share a delegate instead of
    /// each inventing a name from the slot it appears in.
    /// </summary>
    static string DelegateName(ApiCallback callback, Convention convention)
    {
        var n = callback.Name;
        if (n.StartsWith(convention.SymbolPrefix, StringComparison.Ordinal)) n = n[convention.SymbolPrefix.Length..];
        if (n.EndsWith("_func", StringComparison.Ordinal)) n = n[..^5];
        else if (n.EndsWith("_fn", StringComparison.Ordinal)) n = n[..^3];
        return Idioms.Pascal(n);
    }

    /// <summary>
    /// What <c>[retained:&lt;key&gt;]</c> writes when the value telling one registration from
    /// another is the slot's return rather than anything the caller passed in.
    /// </summary>
    const string ReturnKey = "return";

    /// <summary>Whether a C type spells a boolean.</summary>
    static bool IsBoolType(string type, Convention convention) => convention.BooleanReturnTypes.Contains(type.Trim());

    /// <summary>
    /// How a lane is spelled where the unmanaged entry point declares it: pointer depth
    /// preserved and typedefs resolved to what they alias, so the pointer matches the
    /// function-pointer type the vtable slot declares, depth for depth.
    /// </summary>
    static string BlittableLane(ApiModel model, string type, Convention convention)
    {
        var t = type.Trim().Replace("const ", "").Replace("struct ", "").Trim();
        var stars = t.Count(c => c == '*');
        var basis = model.ResolveAlias(t.TrimEnd('*', ' '));
        if (stars == 0 && IsBoolType(basis, convention)) return "bool";
        return Idioms.CsForeignType(basis, convention) + new string('*', stars);
    }

    /// <summary>How a lane is spelled in the delegate the caller implements.</summary>
    static string ManagedLane(ApiModel model, ApiParam lane, string selfType, Convention convention) =>
        lane.Has("self") ? selfType
        : lane.Has("ctx") ? "nint"
        : lane.Has("utf8") ? "string"
        : IsBoolType(lane.Type, convention) ? "bool"
        : CsType(model, lane.Type, convention);

    /// <summary>
    /// What a handler returns on the managed side. A callback reporting failure through
    /// an error channel says it in managed code by throwing, so the boolean it returns
    /// natively carries nothing a caller could still answer: the trampoline reports
    /// success for a handler that returned at all, and failure for one that threw.
    /// </summary>
    static string ManagedReturn(ApiModel model, ApiCallback callback, int? errorLane, Convention convention) =>
        errorLane is not null && IsBoolType(callback.Returns, convention)
            ? "void"
            : ManagedLane(model, new ApiParam(null, callback.Returns, [], null), "", convention);

    static IReadOnlyList<CallbackPair> CallbackPairs(ApiModel model, ClassifiedSlot cs, Convention convention)
    {
        var slot = cs.Slot;
        var scope = cs.PublicParams;
        var pairs = new List<CallbackPair>();
        foreach (var fn in scope.Where(p => p.Has("closure") && !p.Has("completion")))
        {
            var ctxName = fn.TagValue("closure")
                ?? throw new InvalidOperationException(
                    $"{slot.Name}.{fn.Name}: [closure] must name the context parameter, as [closure:<name>]");
            var ctx = scope.FirstOrDefault(p => p.Name == ctxName)
                ?? throw new InvalidOperationException(
                    $"{slot.Name}.{fn.Name}: [closure:{ctxName}] names no parameter of this slot");

            var callback = model.CallbackOf(fn.Type)
                ?? throw new InvalidOperationException(
                    $"{slot.Name}.{fn.Name}: [closure] needs a function-pointer typedef, but {fn.Type.Trim()} is not one");

            var ctxLane = callback.Lanes.Select((l, i) => (l, i))
                .Where(x => x.l.Has("context"))
                .Select(x => (int?)x.i).FirstOrDefault()
                ?? throw new InvalidOperationException(
                    $"{slot.Name}.{fn.Name}: [closure:{ctxName}] hands the context to {callback.Name}, "
                    + "which declares no lane to receive it — a lane's type says nothing about which one "
                    + "carries the context, so the typedef has to mark it [context]");
            if (callback.Lanes[ctxLane].Type.Replace(" ", "") != "void*")
                throw new InvalidOperationException(
                    $"{slot.Name}.{fn.Name}: {callback.Name}'s [context] lane is "
                    + $"{callback.Lanes[ctxLane].Type.Trim()}, and a context travels as void*");

            int? errorLane = callback.Lanes.Select((l, i) => (l, i))
                .Where(x => x.l.Type.Replace(" ", "") == $"{convention.ErrorType}**")
                .Select(x => (int?)x.i).FirstOrDefault();

            var lifetime = fn.Has("retained") ? ClosureLifetime.Retained : ClosureLifetime.Scoped;
            ApiParam? retainKey = null;
            var retainByReturn = false;
            if (fn.TagValue("retained") is { } keyName)
            {
                if (keyName == ReturnKey)
                {
                    if (slot.Returns.Trim() is "void")
                        throw new InvalidOperationException(
                            $"{slot.Name}.{fn.Name}: [retained:{ReturnKey}] keys the registration on what the "
                            + "slot returns, and this one returns nothing");
                    retainByReturn = true;
                }
                else
                    retainKey = scope.FirstOrDefault(p => p.Name == keyName)
                        ?? throw new InvalidOperationException(
                            $"{slot.Name}.{fn.Name}: [retained:{keyName}] names no parameter of this slot");
            }
            var teardown = fn.Has("teardown");
            if (teardown && lifetime != ClosureLifetime.Retained)
                throw new InvalidOperationException(
                    $"{slot.Name}.{fn.Name}: [teardown] says the engine calls this handler while the "
                    + "provider is being destroyed, which only a [retained] closure survives to see");
            if (lifetime == ClosureLifetime.Retained && errorLane is null && !teardown)
                throw new InvalidOperationException(
                    $"{slot.Name}.{fn.Name}: a retained closure outlives the call that registered it, so a "
                    + $"handler that throws has nowhere to report; {callback.Name} needs a {convention.ErrorType}** lane, "
                    + "or [teardown] if the engine only calls it from the destroy this object drives");
            if (errorLane is not null && !IsBoolType(callback.Returns, convention))
                throw new InvalidOperationException(
                    $"{slot.Name}.{fn.Name}: {callback.Name} has a {convention.ErrorType}** lane but returns "
                    + $"{callback.Returns}, so the caller cannot tell that it failed");

            pairs.Add(new CallbackPair(fn, ctx, lifetime, DelegateName(callback, convention),
                TrampolineName(slot, fn),
                callback, ctxLane, errorLane, retainKey, retainByReturn, teardown));
        }
        return pairs;
    }

    /// <summary>
    /// Names the unmanaged entry point for one closure. Both the slot and the parameter
    /// identify it, because a slot may take more than one — but a slot whose name already
    /// ends in the parameter's would only stutter it back.
    /// </summary>
    static string TrampolineName(ApiSlot slot, ApiParam fn) =>
        slot.Name.EndsWith("_" + fn.Name, StringComparison.Ordinal) || slot.Name == fn.Name
            ? $"{Idioms.Pascal(slot.Name)}Trampoline"
            : $"{Idioms.Pascal(slot.Name)}{Idioms.Pascal(fn.Name!)}Trampoline";

    /// <summary>
    /// Whether a lane receives a failure rather than reporting one. The engine carries every
    /// failure as a <c>ke_error</c>, and the direction is the pointer depth: a lane written
    /// through (<c>ke_error**</c>) is where a callback says it failed, while one handed the
    /// error itself (<c>const ke_error*</c>) is where a callback is told that something else
    /// did. Nothing but the depth distinguishes them, so nothing else decides.
    /// </summary>
    static bool ReceivesFailure(string type, Convention convention) =>
        type.Replace("const ", "").Replace(" ", "") == $"{convention.ErrorType}*";

    /// <summary>
    /// A callback the provider calls exactly once, after the call that took it has already
    /// returned, to say how the operation that call started ended. It is the operation's
    /// answer rather than a handler the caller supplies, which is why the caller never
    /// passes it: the managed spelling of an answer that arrives later is a <c>Task</c>,
    /// and a caller handed one has nothing left to register.
    /// </summary>
    internal sealed record Completion(ApiParam Fn, ApiParam Ctx, ApiCallback Callback,
        int CtxLane, int ErrorLane, ApiParam? Result, int ResultLane,
        string? ResultType, OwnedProjection? Owned, string StateType, string Trampoline)
    {
        /// <summary>The source the call keeps and the trampoline answers.</summary>
        public string SourceType => ResultType is null
            ? "TaskCompletionSource" : $"TaskCompletionSource<{ResultType}>";

        /// <summary>What the call hands back in place of the answer it does not have yet.</summary>
        public string TaskType => ResultType is null ? "Task" : $"Task<{ResultType}>";

        /// <summary>Whether the trampoline has to reach the provider to build its answer.</summary>
        public bool NeedsOwner => Owned is not null;
    }

    /// <summary>
    /// The one completion a slot declares, read off the parameter tagged
    /// <c>[completion:&lt;context&gt;]</c>.
    /// </summary>
    static Completion? CompletionOf(ApiModel model, ClassifiedSlot cs, Convention convention,
        OwnedProjection? owned)
    {
        var slot = cs.Slot;
        var fn = slot.Params.FirstOrDefault(p => p.Has("completion"));
        if (fn is null) return null;

        var ctxName = fn.TagValue("completion")
            ?? throw new InvalidOperationException(
                $"{slot.Name}.{fn.Name}: [completion] must name the context parameter it travels"
                + " with, as [completion:<name>]");
        var ctx = slot.Params.FirstOrDefault(p => p.Name == ctxName)
            ?? throw new InvalidOperationException(
                $"{slot.Name}.{fn.Name}: [completion:{ctxName}] names no parameter of this slot");

        var callback = model.CallbackOf(fn.Type)
            ?? throw new InvalidOperationException(
                $"{slot.Name}.{fn.Name}: [completion] needs a function-pointer typedef, but"
                + $" {fn.Type.Trim()} is not one");

        var ctxLane = callback.Lanes.Select((l, i) => (l, i)).Where(x => x.l.Has("context"))
            .Select(x => (int?)x.i).FirstOrDefault()
            ?? throw new InvalidOperationException(
                $"{slot.Name}.{fn.Name}: [completion:{ctxName}] hands the context to {callback.Name},"
                + " which declares no lane to receive it — the typedef has to mark it [context]");

        var errorLane = callback.Lanes.Select((l, i) => (l, i))
            .Where(x => ReceivesFailure(x.l.Type, convention)).Select(x => (int?)x.i).FirstOrDefault()
            ?? throw new InvalidOperationException(
                $"{slot.Name}.{fn.Name}: a completion is how the operation says it ended, and it can"
                + $" only say it failed through a lane handed the error itself; {callback.Name}"
                + $" declares no const {convention.ErrorType}* lane");

        if (callback.Returns.Trim() != "void")
            throw new InvalidOperationException(
                $"{slot.Name}.{fn.Name}: {callback.Name} returns {callback.Returns.Trim()}, and a"
                + " completion runs after the call it answers has returned -- there is nobody left"
                + " to read it");

        if (slot.Returns.Trim() != "void" && !CTypes.IsPointer(slot.Returns))
            throw new InvalidOperationException(
                $"{slot.Name}: the Task the completion projects to is the one thing a caller waits"
                + $" on, so the slot's own {slot.Returns.Trim()} is dropped -- and a value is not"
                + " something this form may drop. Only a handle to the work is.");

        var results = Enumerable.Range(0, callback.Lanes.Count)
            .Where(i => i != ctxLane && i != errorLane).ToList();
        if (results.Count > 1)
            throw new InvalidOperationException(
                $"{slot.Name}.{fn.Name}: {callback.Name} carries {results.Count} values besides the"
                + " failure, and a Task answers with one");

        var resultLane = results.Count == 0 ? -1 : results[0];
        var result = resultLane < 0 ? null : callback.Lanes[resultLane];
        string? resultType = null;
        OwnedProjection? resultOwned = null;
        if (result is not null)
        {
            if (owned is not null && owned.Answers(result.Type))
            {
                resultOwned = owned;
                resultType = owned.TypeName;
            }
            else
            {
                resultType = ManagedLane(model, result, "", convention);
                if (resultType.Contains('*', StringComparison.Ordinal))
                    throw new InvalidOperationException(
                        $"{slot.Name}.{fn.Name}: {callback.Name} answers with {result.Type.Trim()}, and"
                        + " a Task cannot answer with a pointer -- whoever owns that memory has to say"
                        + " so with [releases:<name>] so there is an object to hand over instead");
            }
        }

        return new Completion(fn, ctx, callback, ctxLane, errorLane, result, resultLane,
            resultType, resultOwned, $"{Idioms.Pascal(slot.Name)}Completion",
            TrampolineName(slot, fn));
    }

    /// <summary>The field that keeps a retained closure reachable for as long as the engine holds it.</summary>
    /// <summary>
    /// Every closure reached through one context parameter. A context is a single
    /// pointer, so the closures sharing it have to share the one object it points at:
    /// allocating a handle per closure would hand each trampoline whichever handle the
    /// call happened to write last. A group of one needs no such object and keeps the
    /// delegate as the handle's target directly.
    /// </summary>
    internal sealed record ClosureGroup(ApiParam Ctx, IReadOnlyList<CallbackPair> Pairs, string StateType,
        string ReturnType, string Owner, bool OwnerDrains)
    {
        public bool Shared => Pairs.Count > 1;

        /// <summary>
        /// Whether the trampoline has to reach the provider that registered the closure.
        /// A retained handler reporting through a lane of its own outlives the call that
        /// registered it, so the exception it threw has nowhere to be rethrown at that
        /// call; it is queued on the provider instead, and the slot that observes the
        /// failure raises it. Reaching the provider means the context must point at an
        /// object holding it rather than at the bare delegate.
        /// </summary>
        public bool NeedsOwner => HandsBackProvider || Pairs.Any(Queues);

        /// <summary>
        /// Whether this handler's exception is the kind that has to wait on the provider:
        /// one that outlives the call registering it, reports failure through a channel of
        /// its own, and has a slot declared to answer for it. A handler running inside the
        /// registering call is rethrown there instead, and needs no queue.
        /// </summary>
        public bool Queues(CallbackPair pair) => OwnerDrains
            && pair.Lifetime == ClosureLifetime.Retained && pair.ErrorLane is not null;

        /// <summary>
        /// Whether a handler of this group is called with the provider that registered it.
        /// The ABI spells that lane as a pointer to the same object the call was made on,
        /// which managed code already holds a wrapper for; handing the wrapper back is the
        /// only projection that keeps the handler on the managed surface.
        /// </summary>
        public bool HandsBackProvider => Pairs.Any(p => p.Callback.Lanes.Any(l => l.Has("self")));

        /// <summary>Whether the context points at a generated state object rather than the delegate itself.</summary>
        public bool UsesState => Shared || NeedsOwner;

        string Basis => (Shared ? Ctx.Name : Pairs[0].Fn.Name)!;

        /// <summary>The local holding the one GC root this group's context points at.</summary>
        public string Handle => $"{Idioms.Ident(Basis)}Handle";

        /// <summary>The field keeping that root reachable for as long as the engine may call back.</summary>
        public string Retained => $"_retained{Idioms.Pascal(Basis)}";

        /// <summary>
        /// How long the shared object has to stay reachable: as long as its longest-lived
        /// member, since freeing it at the first member's end would leave the others
        /// pointing at collected memory.
        /// </summary>
        public ClosureLifetime Lifetime => Pairs.Any(p => p.Lifetime == ClosureLifetime.Retained)
            ? ClosureLifetime.Retained
            : ClosureLifetime.Scoped;

        /// <summary>
        /// The parameter whose value tells one registration's root from another's, when the
        /// slot registers against a key it was handed rather than replacing a single handler.
        /// </summary>
        public ApiParam? RetainKey => Pairs.Select(p => p.RetainKey).FirstOrDefault(k => k is not null);

        /// <summary>
        /// Whether the identity distinguishing one registration from another is what the
        /// slot returns, the case when nothing the caller passed names the registration.
        /// </summary>
        public bool RetainByReturn => Pairs.Any(p => p.RetainByReturn);

        /// <summary>Whether this group keeps a root per registration rather than one in total.</summary>
        public bool Keyed => RetainKey is not null || RetainByReturn;

        /// <summary>How the dictionary of roots is keyed, when the group keeps one per registration.</summary>
        public string? KeyType => RetainByReturn ? ReturnType : null;

        /// <summary>How the state object names the slot holding one of the grouped delegates.</summary>
        public static string Field(CallbackPair pair) => Idioms.Pascal(pair.Fn.Name!);
    }

    static IReadOnlyList<ClosureGroup> ClosureGroups(ApiModel model, ApiSlot slot, IReadOnlyList<CallbackPair> pairs,
        string owner, bool ownerDrains, Convention convention)
    {
        var groups = pairs
            .GroupBy(p => p.Ctx)
            .Select(g => new ClosureGroup(g.Key, g.ToList(), $"{Idioms.Pascal(slot.Name)}Closures",
                CsType(model, slot.Returns, convention), owner, ownerDrains))
            .ToList();

        foreach (var g in groups.Where(x => x.Shared))
        {
            if (g.Pairs.Any(p => p.RetainKey is not null))
                throw new InvalidOperationException(
                    $"{slot.Name}: a closure sharing the context '{g.Ctx.Name}' is keyed by [retained:<key>], "
                    + "which needs a root per key while the context has exactly one");
        }
        return groups;
    }

    static IReadOnlyList<ClosureGroup> VtableClosureGroups(ApiModel model, IEnumerable<ClassifiedSlot> slots,
        string owner, Convention convention)
    {
        var drains = Drains(model, slots, convention);
        return slots.Where(Projected)
            .SelectMany(s => ClosureGroups(model, s.Slot, CallbackPairs(model, s, convention), owner, drains, convention))
            .ToList();
    }

    /// <summary>
    /// Whether any slot of the vtable is declared as the one that answers for a retained
    /// handler's failure. Without one there is no call to raise the exception at, so the
    /// provider keeps no queue and the handler's own error channel stays its only report.
    /// </summary>
    static bool Drains(ApiModel model, IEnumerable<ClassifiedSlot> slots, Convention convention)
    {
        var all = slots.ToList();
        return all.Any(s => s.Slot.Has("drains"))
            && all.SelectMany(s => CallbackPairs(model, s, convention))
                .Any(p => p.Lifetime == ClosureLifetime.Retained && p.ErrorLane is not null);
    }

    /// <summary>
    /// Whether the slot gets a managed method at all. A slot whose shape has no
    /// ABI-derivable managed answer, or whose name is already taken by a deliberately
    /// different hand-written member, is left whole to the idiom layer.
    /// </summary>
    static bool Projected(ClassifiedSlot cs) =>
        !cs.Slot.Has("sink") && !cs.Slot.Has("lifecycle") && !cs.Slot.Has("raw_callback")
        && !cs.Slot.Has("idiom") && !cs.PublicParams.Any(p => p.Has("raw_callback"));

    /// <summary>
    /// Every closure a vtable projects. Only the slots that are projected count: a
    /// typedef reached solely by a slot left to the idiom layer has no managed surface,
    /// and declaring its delegate anyway puts a name in the namespace that nothing calls
    /// -- which is how <c>ke_task_func</c> came to declare a <c>Task</c> next to the one
    /// the framework already means by that word.
    /// </summary>
    static IReadOnlyList<CallbackPair> VtableClosures(ApiModel model, IEnumerable<ClassifiedSlot> slots, Convention convention) =>
        slots.Where(Projected).SelectMany(s => CallbackPairs(model, s, convention)).ToList();

    /// <summary>Lanes the delegate carries: everything but the context and the error channel.</summary>
    static IEnumerable<int> CarriedLanes(CallbackPair pair) =>
        Enumerable.Range(0, pair.Callback.Lanes.Count)
            .Where(i => i != pair.CtxLane && i != pair.ErrorLane);

    /// <summary>
    /// How the callback's function pointer is spelled where the vtable slot expects it.
    /// A <see langword="null"/> handler has to pass a null pointer, and a conditional
    /// has no common type between a null literal and a function pointer, so the typed
    /// branch has to say what it is.
    /// </summary>
    static string NativeFnPtr(ApiModel model, ApiCallback callback, Convention convention) =>
        $"delegate* unmanaged[Cdecl]<{string.Join(", ", callback.Lanes.Select(l => BlittableLane(model, l.Type, convention)))}"
        + $", {BlittableLane(model, callback.Returns, convention)}>";

    /// <summary>
    /// The delegate a projected closure asks the caller for. Declared beside the class
    /// rather than as an <c>Action</c>, because a lane can be a pointer and a generic
    /// type argument cannot.
    /// </summary>
    static void RenderClosureDelegate(ApiModel model, List<string> o, CallbackPair pair, string selfType, Convention convention)
    {
        var ps = CarriedLanes(pair).Select(i => pair.Callback.Lanes[i])
            .Select((l, n) => $"{ManagedLane(model, l, selfType, convention)} {Idioms.Ident(l.Name ?? $"arg{n}")}")
            .ToList();
        var ret = ManagedReturn(model, pair.Callback, pair.ErrorLane, convention);
        var doc = pair.Callback.Lanes
            .Where(l => l.Name is not null && l.Doc is not null)
            .Where(l => CarriedLanes(pair).Any(i => pair.Callback.Lanes[i] == l))
            .Select(l => (Idioms.Ident(l.Name!), l.Doc));
        o.Add(XmlDoc("", pair.Callback.Doc ?? pair.Fn.Doc, convention, doc).TrimEnd());
        o.Add($"public {PointerModifier(ps.Append(ret))}delegate {ret} "
            + $"{pair.Delegate}({string.Join(", ", ps)});");
        o.Add("");
    }

    /// <summary>
    /// The trampoline a <see cref="CallbackPair"/> needs: the unmanaged entry point the
    /// engine calls, which unwraps the handle back into the delegate. A managed exception
    /// cannot cross the native frame. Where the callback declares an error channel it is
    /// translated into one and reported as a failure; where it does not, it is parked and
    /// rethrown by the call site once the native stack has unwound, which only holds
    /// because a closure without a channel is never allowed to outlive its call.
    /// </summary>
    /// <summary>
    /// The object a shared context points at: one field per closure reached through it,
    /// so a single GC root answers for all of them.
    /// </summary>
    static void RenderClosureState(List<string> o, ClosureGroup group)
    {
        o.Add(group.Shared
            ? "    /// <summary>The handlers reached through one shared context pointer.</summary>"
            : "    /// <summary>The handler, and the provider a failure of it is reported to.</summary>");
        o.Add($"    private sealed class {group.StateType}");
        o.Add("    {");
        if (group.NeedsOwner) o.Add($"        public required {group.Owner} Owner;");
        foreach (var p in group.Pairs)
            o.Add($"        public {p.Delegate}? {ClosureGroup.Field(p)};");
        o.Add("    }");
        o.Add("");
    }

    static void RenderTrampoline(ApiModel model, List<string> o, CallbackPair pair, ClosureGroup group, Convention convention)
    {
        var lanes = pair.Callback.Lanes;
        var ps = lanes.Select((l, i) => i == pair.CtxLane
            ? "void* ctx"
            : $"{BlittableLane(model, l.Type, convention)} arg{i}");
        var args = string.Join(", ", CarriedLanes(pair).Select(i => lanes[i].Has("self")
            ? "state.Owner"
            : lanes[i].Has("utf8")
            ? $"Marshal.PtrToStringUTF8((nint)arg{i}) ?? \"\""
            : ManagedLane(model, lanes[i], group.Owner, convention) != BlittableLane(model, lanes[i].Type, convention)
                ? $"({ManagedLane(model, lanes[i], group.Owner, convention)})arg{i}"
            : $"arg{i}"));
        var returns = IsBoolType(pair.Callback.Returns, convention);
        var handlerAnswers = ManagedReturn(model, pair.Callback, pair.ErrorLane, convention) != "void";
        var nativeReturn = BlittableLane(model, pair.Callback.Returns, convention);

        o.Add("    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]");
        o.Add($"    private static {nativeReturn} {pair.Trampoline}({string.Join(", ", ps)})");
        o.Add("    {");
        o.Add("        try");
        o.Add("        {");
        o.Add(group.UsesState
            ? $"            if (GCHandle.FromIntPtr((nint)ctx).Target is {group.StateType} state"
                + $" && state.{ClosureGroup.Field(pair)} is {{ }} handler)"
            : $"            if (GCHandle.FromIntPtr((nint)ctx).Target is {pair.Delegate} handler)");
        if (returns && !handlerAnswers)
        {
            o.Add("            {");
            o.Add($"                handler({args});");
            o.Add("                return true;");
            o.Add("            }");
        }
        else
            o.Add($"                {(returns ? $"return handler({args});" : $"handler({args});")}");
        if (returns) o.Add("            return false;");
        o.Add("        }");
        o.Add("        catch (Exception ex)");
        o.Add("        {");
        if (pair.ErrorLane is { } errLane)
        {
            if (group.Queues(pair))
            {
                o.Add("            if (GCHandle.FromIntPtr((nint)ctx).Target is"
                    + $" {group.StateType} failed)");
                o.Add("                failed.Owner._callbackFailures.Enqueue(ex);");
            }
            o.Add($"            {convention.ErrorHelperClass}.ToNative(arg{errLane}, ex, \"{pair.Callback.Name}\");");
            if (returns) o.Add("            return false;");
        }
        else
        {
            o.Add("            s_parkedCallbackException ??= ex;");
            if (returns) o.Add("            return false;");
        }
        o.Add("        }");
        o.Add("    }");
        o.Add("");
    }

    /// <summary>
    /// What one pending operation has to keep reachable until its completion fires: the
    /// source that answers, and -- where the answer is memory the provider owns -- the
    /// provider that will be asked to take it back.
    /// </summary>
    static void RenderCompletionState(List<string> o, Completion completion, string owner)
    {
        o.Add("    /// <summary>What one operation in flight answers when it finishes.</summary>");
        o.Add($"    private sealed class {completion.StateType}");
        o.Add("    {");
        if (completion.NeedsOwner) o.Add($"        public required {owner} Owner;");
        o.Add($"        public required {completion.SourceType} Source;");
        o.Add("    }");
        o.Add("");
    }

    /// <summary>
    /// The unmanaged entry point the provider calls when the operation finishes. It owns
    /// the handle the call allocated -- the completion fires exactly once, so freeing it
    /// here is what stops a pending operation from leaking one root per call. Nothing is
    /// allowed to leave it: an exception crossing a native frame tears the process down,
    /// and one that stayed behind would leave the Task pending forever, so every path
    /// ends by answering the source.
    /// </summary>
    static void RenderCompletionTrampoline(ApiModel model, List<string> o, Completion completion,
        ApiSlot slot, Convention convention)
    {
        var lanes = completion.Callback.Lanes;
        var ps = lanes.Select((l, i) => i == completion.CtxLane
            ? "void* ctx"
            : $"{BlittableLane(model, l.Type, convention)} arg{i}");
        var err = $"arg{completion.ErrorLane}";

        string Answer()
        {
            if (completion.Result is null) return "state.Source.TrySetResult();";
            var value = completion.Owned is not null
                ? $"new {completion.Owned.TypeName}(state.Owner, ({completion.Owned.View})arg{completion.ResultLane})"
                : $"arg{completion.ResultLane}";
            return $"state.Source.TrySetResult({value});";
        }

        var failed = completion.Owned is not null
            ? $"{err} != null || arg{completion.ResultLane} == null"
            : $"{err} != null";

        o.Add("    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]");
        o.Add($"    private static void {completion.Trampoline}({string.Join(", ", ps)})");
        o.Add("    {");
        o.Add("        var pending = GCHandle.FromIntPtr((nint)ctx);");
        o.Add($"        if (pending.Target is not {completion.StateType} state) return;");
        o.Add("        pending.Free();");
        o.Add("        try");
        o.Add("        {");
        o.Add($"            if ({failed})");
        o.Add($"                state.Source.TrySetException({convention.ErrorHelperClass}.FromNative({err}, \"{slot.Name}\"));");
        o.Add("            else");
        o.Add($"                {Answer()}");
        o.Add("        }");
        o.Add("        catch (Exception ex)");
        o.Add("        {");
        o.Add("            state.Source.TrySetException(ex);");
        o.Add("        }");
        o.Add("    }");
        o.Add("");
    }

    /// <summary>
    /// One public member as the provider class declares it: the documentation block and the
    /// signature, with no <c>public</c> keyword and no body. The domain interface is rendered
    /// from these, so a signature the class emits and the signature the interface promises are
    /// the same string rather than two renderings of the same intent.
    /// </summary>
    sealed record MemberDecl(string Doc, string Decl, bool Property)
    {
        /// <summary>How the interface spells this member: a method ends the declaration, a property opens a getter.</summary>
        public string InterfaceLine => Property ? $"{Decl} {{ get; }}" : $"{Decl};";
    }

    /// <summary>
    /// The <c>unsafe</c> keyword, but only for a declaration that actually spells a pointer.
    /// Emitting it unconditionally makes every project holding such a declaration turn
    /// <c>AllowUnsafeBlocks</c> on, which is a real permission -- a contract naming nothing but
    /// managed types should not ask its consumers for it.
    /// </summary>
    static string PointerModifier(IEnumerable<string> signatures) =>
        signatures.Any(s => s.Contains('*', StringComparison.Ordinal)) ? "unsafe " : "";

    static void Declare(List<string> o, List<MemberDecl>? decls, string doc, string decl,
        bool property = false, string access = "public")
    {
        o.Add(doc);
        o.Add($"    {access} {decl}");
        if (access == "public") decls?.Add(new MemberDecl(doc, decl, property));
    }

    /// <summary>What a slot is called where the provider projects it.</summary>
    static string SlotName(ApiSlot slot) =>
        (slot.TagValue("name") ?? Idioms.Pascal(slot.Name)) + (slot.Has("raw") ? "Raw" : "");

    static void RenderSlotMethod(ApiModel model, List<string> o, List<MemberDecl>? decls,
        ClassifiedSlot cs, Convention convention, string owner, bool ownerDrains,
        OwnedProjection? owned = null)
    {
        var slot = cs.Slot;
        var name = SlotName(slot);
        var access = owned is not null && owned.Release == slot ? "internal" : "public";
        var ownedReturn = owned is not null && owned.Answers(slot.Returns) ? owned : null;
        var lanes = VectorLanes(slot.Params);
        var callbacks = CallbackPairs(model, cs, convention);
        var groups = ClosureGroups(model, slot, callbacks, owner, ownerDrains, convention);
        var completion = CompletionOf(model, cs, convention, owned);

        if (callbacks.Count > 0 && cs.Shape is not SlotShape.Fallible)
            throw new InvalidOperationException(
                $"{slot.Name}: [closure] is only projected on a fallible slot so far, not {cs.Shape}");

        if (slot.Has("property"))
        {
            if (cs.PublicParams.Count > 0 || cs.Shape is not SlotShape.Plain)
                throw new InvalidOperationException(
                    $"{slot.Name}: [property] needs a slot that only answers -- no parameters and no"
                    + $" failure channel, so there is nothing for a getter to drop. Got {cs.Shape}"
                    + $" with {cs.PublicParams.Count} parameter(s).");

            var pType = slot.Returns == convention.ByteBoolType ? "bool" : ReturnType(model, slot.Returns, convention);
            Declare(o, decls, XmlDoc("    ", slot.Doc ?? slot.ReturnDoc, convention).TrimEnd(),
                $"{pType} {name}", property: true);
            o.Add("    {");
            o.Add($"        get => {(slot.Returns == convention.ByteBoolType ? "" : ReturnCast(model, slot.Returns, convention))}Handle->{slot.Name}(Handle)"
                + (slot.Returns == convention.ByteBoolType ? " != 0" : "") + ";");
            o.Add("    }");
            o.Add("");
            return;
        }

        string Sig(IEnumerable<ApiParam> ps) => string.Join(", ", SigParts(ps));

        IEnumerable<ApiParam> NativeParams() => cs.Slot.Params
            .Where(p => !cs.Fallible || p != cs.Slot.Params[^1]);

        IEnumerable<(string, string?)> DocParams(IEnumerable<ApiParam> ps) => ps
            .Where(p => callbacks.All(c => c.Ctx != p))
            .Select(p => (Idioms.Ident(p.Name!), p.Doc));

        IEnumerable<string> SigParts(IEnumerable<ApiParam> ps)
        {
            var parts = ps
                .Where(p => !lanes.TryGetValue(p, out var l) || l.Leads)
                .Where(p => callbacks.All(c => c.Ctx != p))
                .Select(p => (Param: p, Text: lanes.TryGetValue(p, out var l)
                    ? $"Vector{l.Arity} {Idioms.Ident(l.Vector)}"
                    : callbacks.FirstOrDefault(c => c.Fn == p) is { } cb
                        ? $"{cb.Delegate}? {Idioms.Ident(p.Name!)}"
                    : cs.Sequences.FirstOrDefault(s => s.Seq == p) is { } asSpan
                        ? $"Span<{SequenceElement(model, asSpan, convention)}> {Idioms.Ident(p.Name!)}"
                    : cs.Blobs.Any(b => b.Blob == p)
                        ? $"in {BlobTypeParam(p)} {Idioms.Ident(p.Name!)}"
                    : cs.TrailingOuts.Contains(p)
                        ? $"out {OutElement(model, p, convention)} {Idioms.Ident(WrittenName(p))}"
                        : $"{CsParamType(model, p, convention)} {Idioms.Ident(p.Name!)}"))
                .ToList();

            var optionalFrom = parts.FindIndex(x => x.Param.Has("default"));
            if (optionalFrom >= 0 && parts.Skip(optionalFrom).Any(x => !x.Param.Has("default")))
                throw new InvalidOperationException(
                    $"{slot.Name}: a parameter carrying [default] is one the caller may leave out, so"
                    + " every parameter after it must carry one too. Reorder the fields so the ones"
                    + $" with a default come last -- {string.Join(", ", parts.Skip(optionalFrom)
                        .Where(x => !x.Param.Has("default")).Select(x => x.Param.Name))} has none.");

            return parts.Select(x => x.Param.Has("default")
                ? $"{x.Text} = {DefaultLiteral(model, cs, x.Param, slot, convention)}"
                : x.Text);
        }

        if (completion is not null)
        {
            if (cs.Shape is not SlotShape.Plain)
                throw new InvalidOperationException(
                    $"{slot.Name}: the completion is where this operation reports how it ended, so the"
                    + $" call that starts it has nothing left to report -- got {cs.Shape}");

            var ins = cs.PublicParams.Where(p => p != completion.Fn && p != completion.Ctx).ToList();
            var inits = string.Join(", ", new[] { completion.NeedsOwner ? "Owner = this" : null,
                "Source = source" }.Where(x => x is not null));

            Declare(o, decls, XmlDoc("    ", slot.Doc, convention, DocParams(ins), completion.Result?.Doc).TrimEnd(),
                $"{completion.TaskType} {name}({Sig(ins)})");
            o.Add("    {");
            o.Add($"        var source = new {completion.SourceType}"
                + "(TaskCreationOptions.RunContinuationsAsynchronously);");
            o.Add($"        var completion = GCHandle.Alloc(new {completion.StateType} {{ {inits} }});");
            var (cPro, cDepth) = Utf8Prologue(ins, new string(' ', 8));
            o.AddRange(cPro);
            var cInd = new string(' ', 8 + cDepth * 4);
            o.Add($"{cInd}try");
            o.Add($"{cInd}{{");
            o.Add($"{cInd}    Handle->{slot.Name}(Handle"
                + string.Concat(NativeParams().Select(p => ", " + CallArg(p))) + ");");
            o.Add($"{cInd}}}");
            o.Add($"{cInd}catch");
            o.Add($"{cInd}{{");
            o.Add($"{cInd}    completion.Free();");
            o.Add($"{cInd}    throw;");
            o.Add($"{cInd}}}");
            for (var d = cDepth; d > 0; d--) o.Add(new string(' ', 4 + d * 4) + "}");
            o.Add("        return source.Task;");
            o.Add("    }");
            o.Add("");
            RenderCompletionState(o, completion, owner);
            RenderCompletionTrampoline(model, o, completion, slot, convention);
            return;
        }

        switch (cs.Shape)
        {
            case SlotShape.ReturnsOutParam:
            {
                var ret = OutElement(model, cs.OutParam!, convention);
                var ins = cs.PublicParams.Where(p => p != cs.OutParam).ToList();
                var sig = Sig(ins);
                var nativeArgs = string.Concat(NativeParams().Select(p =>
                    ", " + (p == cs.OutParam ? OutAddress(model, p, convention, "result") : CallArg(p))));

                Declare(o, decls, XmlDoc("    ", slot.Doc, convention, ins.Select(p => (Idioms.Ident(p.Name!), p.Doc)),
                    slot.ReturnDoc, cs.Fallible).TrimEnd(), $"{ret} {name}({sig})");
                o.Add("    {");
                var (roPro, roDepth) = Utf8Prologue(ins, new string(' ', 8));
                var (roSeq, roSeqDepth) = SequencePrologue(model, cs.Sequences,
                    new string(' ', 8 + roDepth * 4), convention);
                o.AddRange(roPro);
                o.AddRange(roSeq);
                var roSeqAt = roDepth;
                roDepth += roSeqDepth;
                var roClosers = SequenceClosers(model, cs.Sequences);
                var roInd = new string(' ', 8 + roDepth * 4);
                o.Add($"{roInd}{OutLocal(model, cs.OutParam!, convention)} result;");
                if (cs.Fallible)
                {
                    o.Add($"{roInd}{convention.ErrorType}* err = null;");
                    o.Add($"{roInd}{convention.ErrorHelperClass}.ThrowIfFailed(Handle->{slot.Name}(Handle{nativeArgs}, &err), err, \"{slot.Name}\");");
                }
                else
                {
                    o.Add($"{roInd}Handle->{slot.Name}(Handle{nativeArgs});");
                }
                o.Add($"{roInd}return {OutRead(cs.OutParam!, "result")};");
                CloseScopes(o, roDepth, roSeqAt, roClosers);
                o.Add("    }");
                o.Add("");
                return;
            }
            case SlotShape.TupleOutParams:
            {
                var ins = cs.PublicParams.Where(p => !cs.OutParams.Contains(p)).ToList();
                var sig = Sig(ins);
                var names = cs.OutParams.Select(p => Idioms.Pascal(WrittenName(p))).ToList();
                var types = cs.OutParams.Select(p => OutElement(model, p, convention)).ToList();
                var retTuple = string.Join(", ", types.Zip(names, (t, n) => $"{t} {n}"));
                var locals = cs.OutParams.Select(p => Idioms.Ident(WrittenName(p))).ToList();
                var nativeArgs = NativeParams()
                    .Select(p => cs.OutParams.Contains(p)
                        ? OutAddress(model, p, convention, Idioms.Ident(WrittenName(p))) : CallArg(p));
                var callArgs = string.Concat(nativeArgs.Select(a => ", " + a));

                Declare(o, decls, XmlDoc("    ", slot.Doc, convention, ins.Select(p => (Idioms.Ident(p.Name!), p.Doc)),
                    throwsOnFail: cs.Fallible).TrimEnd(), $"({retTuple}) {name}({sig})");
                o.Add("    {");
                var (tuPro, tuDepth) = Utf8Prologue(ins, new string(' ', 8));
                var (tuSeq, tuSeqDepth) = SequencePrologue(model, cs.Sequences,
                    new string(' ', 8 + tuDepth * 4), convention);
                o.AddRange(tuPro);
                o.AddRange(tuSeq);
                var tuSeqAt = tuDepth;
                tuDepth += tuSeqDepth;
                var tuClosers = SequenceClosers(model, cs.Sequences);
                var tuInd = new string(' ', 8 + tuDepth * 4);
                foreach (var (p, n) in cs.OutParams.Zip(locals))
                    o.Add($"{tuInd}{OutLocal(model, p, convention)} {n};");
                if (cs.Fallible)
                {
                    o.Add($"{tuInd}{convention.ErrorType}* err = null;");
                    o.Add($"{tuInd}{convention.ErrorHelperClass}.ThrowIfFailed(Handle->{slot.Name}(Handle{callArgs}, &err), err, \"{slot.Name}\");");
                }
                else
                {
                    o.Add($"{tuInd}Handle->{slot.Name}(Handle{callArgs});");
                }
                o.Add($"{tuInd}return ({string.Join(", ", cs.OutParams.Zip(locals, OutRead))});");
                CloseScopes(o, tuDepth, tuSeqAt, tuClosers);
                o.Add("    }");
                o.Add("");
                return;
            }
            case SlotShape.Try:
            {
                var ins = cs.PublicParams.Where(p => !p.Has("out")).ToList();
                var outs = cs.OutParams;
                var sigParts = SigParts(ins)
                    .Concat(outs.Select(p => $"out {OutElement(model, p, convention)} {Idioms.Ident(WrittenName(p))}"));

                var tryName = name.StartsWith("Try") ? name : $"Try{name}";
                Declare(o, decls, XmlDoc("    ", slot.Doc, convention,
                    cs.PublicParams.Select(p =>
                        (Idioms.Ident(outs.Contains(p) ? WrittenName(p) : p.Name!), p.Doc)), slot.ReturnDoc).TrimEnd(),
                    $"bool {tryName}({string.Join(", ", sigParts)})");
                o.Add("    {");
                foreach (var op in outs) o.Add($"        {OutLocal(model, op, convention)} {Idioms.Ident(WrittenName(op))}Local;");
                var (tPro, tDepth) = Utf8Prologue(ins, new string(' ', 8));
                var (tSeq, tSeqDepth) = SequencePrologue(model, cs.Sequences,
                    new string(' ', 8 + tDepth * 4), convention);
                o.AddRange(tPro);
                o.AddRange(tSeq);
                var tSeqAt = tDepth;
                tDepth += tSeqDepth;
                var tClosers = SequenceClosers(model, cs.Sequences);
                var tInd = new string(' ', 8 + tDepth * 4);
                var tryArgs = NativeParams()
                    .Select(p => outs.Contains(p)
                        ? OutAddress(model, p, convention, $"{Idioms.Ident(WrittenName(p))}Local") : CallArg(p));
                var tryCall = $"Handle->{slot.Name}(Handle, {string.Join(", ", tryArgs)}"
                    + (cs.Fallible ? ", null)" : ")")
                    + (slot.Returns == convention.ByteBoolType ? " != 0" : "");
                o.Add($"{tInd}var found = {tryCall};");
                foreach (var op in outs)
                    o.Add($"{tInd}{Idioms.Ident(WrittenName(op))} = "
                        + $"{OutRead(op, $"{Idioms.Ident(WrittenName(op))}Local")};");
                o.Add($"{tInd}return found;");
                CloseScopes(o, tDepth, tSeqAt, tClosers);
                o.Add("    }");
                o.Add("");
                return;
            }
            case SlotShape.Fallible:
            {
                var args = cs.PublicParams;
                var byReturn = convention.SignalsFailureByReturn(slot.Returns);
                var retType = byReturn ? "void"
                    : ownedReturn is not null ? ownedReturn.TypeName
                    : ReturnType(model, slot.Returns, convention);
                var sig = Sig(args);
                var bagLocal = cs.ExpandedParam is null ? null : Idioms.Ident(cs.ExpandedParam.Name!);
                var call = string.Concat(NativeParams()
                    .Select(p => ", " + (p == cs.ExpandedParam ? $"&{bagLocal}" : CallArg(p))));
                var fGenerics = cs.Blobs.Count == 0 ? ""
                    : "<" + string.Join(", ", cs.Blobs.Select(bl => BlobTypeParam(bl.Blob))) + ">";
                var fConstraints = string.Concat(cs.Blobs
                    .Select(bl => $" where {BlobTypeParam(bl.Blob)} : unmanaged"));
                Declare(o, decls, XmlDoc("    ", slot.Doc, convention, DocParams(args),
                    byReturn ? null : slot.ReturnDoc, throwsOnFail: true).TrimEnd(),
                    $"{retType} {name}{fGenerics}({sig}){fConstraints}");
                o.Add("    {");
                var (fPro, fDepth) = Utf8Prologue(args, new string(' ', 8));
                var (fSeq, fSeqDepth) = SequencePrologue(model, cs.Sequences,
                    new string(' ', 8 + fDepth * 4), convention);
                var (fBlob, fBlobDepth) = BlobPrologue(cs.Blobs,
                    new string(' ', 8 + (fDepth + fSeqDepth) * 4));
                o.AddRange(fPro);
                o.AddRange(fSeq);
                o.AddRange(fBlob);
                var fSeqAt = fDepth;
                fDepth += fSeqDepth + fBlobDepth;
                var fClosers = SequenceClosers(model, cs.Sequences);
                var fInd = new string(' ', 8 + fDepth * 4);
                var rooted = args.Where(p => p.Has("rooted")).ToList();
                foreach (var rp in rooted)
                    o.Add($"{fInd}var {Idioms.Ident(rp.Name!)}Handle = System.Runtime.InteropServices.GCHandle.Alloc({Idioms.Ident(rp.Name!)});");

                void BuildBag()
                {
                    if (bagLocal is null) return;
                    o.Add($"{fInd}{cs.ExpandedStruct!.Name} {bagLocal} = default;");
                    foreach (var f in cs.ExpandedStruct.Fields)
                    {
                        var arg = args.FirstOrDefault(a => a.Name == f.Name)
                            ?? cs.Sequences.Select(s => s.Count).First(c => c.Name == f.Name);
                        o.Add($"{fInd}{bagLocal}.{f.Name} = {CallArg(arg)};");
                    }
                }

                if (callbacks.Count > 0)
                {
                    var scoped = groups.Where(g => g.Lifetime == ClosureLifetime.Scoped).ToList();
                    var parks = callbacks.Any(c => c.Parks && !c.Teardown);
                    foreach (var g in groups)
                    {
                        if (!g.UsesState)
                        {
                            var fn = Idioms.Ident(g.Pairs[0].Fn.Name!);
                            o.Add($"{fInd}var {g.Handle} = {fn} is null ? default : GCHandle.Alloc({fn});");
                            continue;
                        }
                        var inits = string.Join(", ", g.Pairs
                            .Select(p => $"{ClosureGroup.Field(p)} = {Idioms.Ident(p.Fn.Name!)}")
                            .Prepend(g.NeedsOwner ? "Owner = this" : null)
                            .Where(x => x is not null));
                        var allNull = string.Join(" && ", g.Pairs.Select(p =>
                            $"{Idioms.Ident(p.Fn.Name!)} is null"));
                        o.Add($"{fInd}var {g.Handle} = {allNull}");
                        o.Add($"{fInd}    ? default");
                        o.Add($"{fInd}    : GCHandle.Alloc(new {g.StateType} {{ {inits} }});");
                    }
                    BuildBag();
                    if (parks) o.Add($"{fInd}s_parkedCallbackException = null;");
                    var signalsOk = IsBoolType(slot.Returns, convention);
                    var capture = signalsOk ? "ok" : retType == "void" ? null : "result";
                    var failed = signalsOk ? "!ok" : "err != null";
                    o.Add($"{fInd}{convention.ErrorType}* err = null;");
                    if (signalsOk) o.Add($"{fInd}bool ok;");
                    else if (capture is not null) o.Add($"{fInd}{retType} {capture};");
                    o.Add($"{fInd}try");
                    o.Add($"{fInd}{{");
                    o.Add($"{fInd}    {(capture is null ? "" : capture + " = ")}"
                        + $"{(signalsOk ? "" : ReturnCast(model, slot.Returns, convention))}"
                        + $"Handle->{slot.Name}(Handle{call}, &err)"
                        + (slot.Returns == convention.ByteBoolType ? " != 0" : "") + ";");
                    o.Add($"{fInd}}}");
                    if (scoped.Count > 0)
                    {
                        o.Add($"{fInd}finally");
                        o.Add($"{fInd}{{");
                        foreach (var g in scoped)
                            o.Add($"{fInd}    if ({g.Handle}.IsAllocated) {g.Handle}.Free();");
                        o.Add($"{fInd}}}");
                    }
                    else
                    {
                        o.Add($"{fInd}catch");
                        o.Add($"{fInd}{{");
                        foreach (var g in groups)
                            o.Add($"{fInd}    if ({g.Handle}.IsAllocated) {g.Handle}.Free();");
                        o.Add($"{fInd}    throw;");
                        o.Add($"{fInd}}}");
                    }
                    if (parks)
                    {
                        o.Add($"{fInd}if (s_parkedCallbackException is {{ }} parked)");
                        o.Add($"{fInd}{{");
                        o.Add($"{fInd}    s_parkedCallbackException = null;");
                        o.Add($"{fInd}    throw parked;");
                        o.Add($"{fInd}}}");
                    }
                    var retained = groups.Where(g => g.Lifetime == ClosureLifetime.Retained).ToList();
                    if (retained.Count == 0 && signalsOk)
                        o.Add($"{fInd}{convention.ErrorHelperClass}.ThrowIfFailed(ok, err, \"{slot.Name}\");");
                    else if (retained.Count == 0)
                    {
                        o.Add($"{fInd}if ({failed}) throw {convention.ErrorHelperClass}.FromNative(err, \"{slot.Name}\");");
                    }
                    else
                    {
                        o.Add($"{fInd}if ({failed})");
                        o.Add($"{fInd}{{");
                        foreach (var g in retained)
                            o.Add($"{fInd}    if ({g.Handle}.IsAllocated) {g.Handle}.Free();");
                        o.Add($"{fInd}    throw {convention.ErrorHelperClass}.FromNative(err, \"{slot.Name}\");");
                        o.Add($"{fInd}}}");
                        foreach (var g in retained)
                        {
                            var field = g.Retained;
                            if (g.RetainByReturn)
                                o.Add($"{fInd}if ({g.Handle}.IsAllocated) {field}[{capture}] = {g.Handle};");
                            else if (g.RetainKey is { } key)
                            {
                                var k = Idioms.Ident(key.Name!);
                                var replaced = $"replaced{Idioms.Pascal(g.Pairs[0].Fn.Name!)}";
                                o.Add($"{fInd}if ({field}.Remove({k}, out var {replaced})) {replaced}.Free();");
                                o.Add($"{fInd}{field}[{k}] = {g.Handle};");
                            }
                            else
                            {
                                o.Add($"{fInd}if ({field}.IsAllocated) {field}.Free();");
                                o.Add($"{fInd}{field} = {g.Handle};");
                            }
                        }
                    }
                    if (capture == "result") o.Add($"{fInd}return result;");
                    CloseScopes(o, fDepth, fSeqAt, fClosers);
                    o.Add("    }");
                    o.Add("");
                    foreach (var g in groups.Where(x => x.UsesState)) RenderClosureState(o, g);
                    foreach (var g in groups)
                        foreach (var cb in g.Pairs)
                            RenderTrampoline(model, o, cb, g, convention);
                    return;
                }
                BuildBag();
                o.Add($"{fInd}{convention.ErrorType}* err = null;");
                if (byReturn && rooted.Count > 0)
                {
                    var boolCall = $"Handle->{slot.Name}(Handle{call}, &err)"
                        + (slot.Returns == convention.ByteBoolType ? " != 0" : "");
                    o.Add($"{fInd}if (!{boolCall})");
                    o.Add($"{fInd}{{");
                    foreach (var rp in rooted)
                        o.Add($"{fInd}    {Idioms.Ident(rp.Name!)}Handle.Free();");
                    o.Add($"{fInd}    throw {convention.ErrorHelperClass}.FromNative(err, \"{slot.Name}\");");
                    o.Add($"{fInd}}}");
                    foreach (var rp in rooted)
                        o.Add($"{fInd}_rooted[{Idioms.Ident(rp.TagValue("rooted")!)}] = {Idioms.Ident(rp.Name!)}Handle;");
                }
                else if (byReturn && ownerDrains && slot.Has("drains"))
                {
                    var boolCall = $"Handle->{slot.Name}(Handle{call}, &err)"
                        + (slot.Returns == convention.ByteBoolType ? " != 0" : "");
                    o.Add($"{fInd}if (!{boolCall} && _callbackFailures.IsEmpty)");
                    o.Add($"{fInd}    throw {convention.ErrorHelperClass}.FromNative(err, \"{slot.Name}\");");
                    o.Add($"{fInd}DrainCallbackFailures();");
                }
                else if (byReturn)
                {
                    var boolCall = $"Handle->{slot.Name}(Handle{call}, &err)"
                        + (slot.Returns == convention.ByteBoolType ? " != 0" : "");
                    o.Add($"{fInd}{convention.ErrorHelperClass}.ThrowIfFailed({boolCall}, err, \"{slot.Name}\");");
                }
                else
                {
                    o.Add($"{fInd}var result = {(ownedReturn is not null ? $"({ownedReturn.View})" : ReturnCast(model, slot.Returns, convention))}"
                        + $"Handle->{slot.Name}(Handle{call}, &err);");
                    if (CTypes.IsPointer(slot.Returns))
                        o.Add($"{fInd}if (result == null) throw {convention.ErrorHelperClass}.FromNative(err, \"{slot.Name}\");");
                    else
                        o.Add($"{fInd}if (err != null) throw {convention.ErrorHelperClass}.FromNative(err, \"{slot.Name}\");");
                    o.Add($"{fInd}return {(ownedReturn is null ? "result" : $"new {ownedReturn.TypeName}(this, result)")};");
                }
                CloseScopes(o, fDepth, fSeqAt, fClosers);
                o.Add("    }");
                o.Add("");
                return;
            }
            default:
            {
                var args = cs.PublicParams;
                var sig = Sig(args);
                var call = string.Concat(NativeParams().Select(p => ", " + CallArg(p)));
                var spanElement = cs.ReturnCount is null ? null : ReturnElement(model, slot, convention);
                if (ownedReturn is not null)
                    throw new InvalidOperationException(
                        $"{slot.Name}: answers with the memory [releases:{ownedReturn.TypeName}] owns, and"
                        + " has no failure channel -- so a caller handed nothing back is never told why."
                        + $" The slot needs a {convention.ErrorType}** parameter.");
                var retType = spanElement is not null ? $"ReadOnlySpan<{spanElement}>"
                    : slot.Returns == convention.ByteBoolType ? "bool"
                    : ReturnType(model, slot.Returns, convention);
                var needsCast = retType == "nint" ? "(nint)"
                    : spanElement is null && slot.Returns != convention.ByteBoolType
                        ? ReturnCast(model, slot.Returns, convention) : "";
                var generics = cs.Blobs.Count == 0 ? ""
                    : "<" + string.Join(", ", cs.Blobs.Select(b => BlobTypeParam(b.Blob))) + ">";
                var constraints = string.Concat(cs.Blobs
                    .Select(b => $" where {BlobTypeParam(b.Blob)} : unmanaged"));
                Declare(o, decls,
                    XmlDoc("    ", slot.Doc, convention, args.Select(p =>
                        (Idioms.Ident(cs.TrailingOuts.Contains(p) ? WrittenName(p) : p.Name!), p.Doc)),
                        slot.ReturnDoc).TrimEnd(),
                    $"{retType} {name}{generics}({sig}){constraints}", access: access);
                o.Add("    {");
                var (pPro, pDepth) = Utf8Prologue(args, new string(' ', 8));
                var (pSeq, pSeqDepth) = SequencePrologue(model, cs.Sequences,
                    new string(' ', 8 + pDepth * 4), convention);
                var (pBlob, pBlobDepth) = BlobPrologue(cs.Blobs,
                    new string(' ', 8 + (pDepth + pSeqDepth) * 4));
                o.AddRange(pPro);
                o.AddRange(pSeq);
                o.AddRange(pBlob);
                var pSeqAt = pDepth;
                pDepth += pSeqDepth + pBlobDepth;
                var pClosers = SequenceClosers(model, cs.Sequences);
                var pInd = new string(' ', 8 + pDepth * 4);
                foreach (var op in cs.TrailingOuts)
                    o.Add($"{pInd}{OutLocal(model, op, convention)} {Idioms.Ident(WrittenName(op))}Local;");
                var pCall = $"Handle->{slot.Name}(Handle{call})"
                    + (slot.Returns == convention.ByteBoolType ? " != 0" : "");
                var pHolds = cs.TrailingOuts.Count > 0;
                if (spanElement is not null)
                {
                    var countLocal = $"{Idioms.Ident(WrittenName(cs.ReturnCount!))}Local";
                    var native = CsType(model, CTypes.Deref(slot.Returns), convention);
                    var front = spanElement == native ? "front" : $"({spanElement}*)front";
                    o.Add($"{pInd}{CsType(model, CTypes.Deref(cs.ReturnCount!.Type), convention)} {countLocal} = 0;");
                    o.Add($"{pInd}var front = {pCall};");
                    o.Add($"{pInd}{(pHolds ? "var result =" : "return")} front == null ? default"
                        + $" : new ReadOnlySpan<{spanElement}>({front}, (int){countLocal});");
                }
                else if (retType == "void")
                {
                    o.Add($"{pInd}{pCall};");
                    if (slot.TagValue("unroots") is string freedKey)
                    {
                        o.Add($"{pInd}if (_rooted.TryRemove({Idioms.Ident(freedKey)}, out var freed)) freed.Free();");
                    }
                }
                else if (pHolds)
                    o.Add($"{pInd}var result = {needsCast}{pCall};");
                else
                    o.Add($"{pInd}return {needsCast}{pCall};");
                foreach (var op in cs.TrailingOuts)
                    o.Add($"{pInd}{Idioms.Ident(WrittenName(op))} = "
                        + $"{OutRead(op, $"{Idioms.Ident(WrittenName(op))}Local")};");
                if (retType != "void" && pHolds) o.Add($"{pInd}return result;");
                CloseScopes(o, pDepth, pSeqAt, pClosers);
                o.Add("    }");
                o.Add("");
                return;
            }
        }

        string CallArg(ApiParam p) =>
            callbacks.FirstOrDefault(c => c.Fn == p) is { } fnOf
                ? $"{Idioms.Ident(p.Name!)} is null ? null : ({NativeFnPtr(model, fnOf.Callback, convention)})&{fnOf.Trampoline}"
            : completion is not null && completion.Fn == p
                ? $"({NativeFnPtr(model, completion.Callback, convention)})&{completion.Trampoline}"
            : completion is not null && completion.Ctx == p
                ? "(void*)GCHandle.ToIntPtr(completion)"
            : groups.FirstOrDefault(g => g.Ctx == p) is { } ctxOf
                ? $"(void*)GCHandle.ToIntPtr({ctxOf.Handle})"
            : cs.Sequences.FirstOrDefault(s => s.Seq == p) is { } asSeq
                ? SequenceArg(model, asSeq, convention)
            : cs.Blobs.FirstOrDefault(b => b.Blob == p) is { } asBlob
                ? $"({NativePointerType(model, p.Type, convention)}){Idioms.Ident(p.Name!)}Ptr"
            : cs.Blobs.FirstOrDefault(b => b.Size == p) is { } asSize
                ? $"({CsType(model, asSize.Size.Type, convention)})sizeof({BlobTypeParam(asSize.Blob)})"
            : p == cs.ReturnCount ? OutAddress(model, p, convention, $"{Idioms.Ident(WrittenName(p))}Local")
            : cs.TrailingOuts.Contains(p)
                ? OutAddress(model, p, convention, $"{Idioms.Ident(WrittenName(p))}Local")
            : cs.Sequences.FirstOrDefault(s => s.Count == p) is { } asCount
                ? $"({CsType(model, asCount.Count.Type, convention)}){Idioms.Ident(asCount.Seq.Name!)}.Length"
            : lanes.TryGetValue(p, out var lane) ? $"{Idioms.Ident(lane.Vector)}.{lane.Lane}"
            : p.Has("provider") ? $"{Idioms.Ident(p.Name!)}.Native"
            : p.Has("rooted") ? $"(void*)System.Runtime.InteropServices.GCHandle.ToIntPtr({Idioms.Ident(p.Name!)}Handle)"
            : p.Has("ctx") ? $"({CTypes.Normalize(p.Type)}){Idioms.Ident(p.Name!)}"
            : p.Has("utf8") ? $"(sbyte*){Idioms.Ident(p.Name!)}Ptr"
            : p.Type.Trim() == convention.ByteBoolType ? $"{Idioms.Ident(p.Name!)} ? (byte)1 : (byte)0"
            : model.Enums.Any(e => e.Name == p.Type.Trim()) ? $"({p.Type.Trim()}){Idioms.Ident(p.Name!)}"
            : p.Has("enum") && CTypes.IsPointer(p.Type) ? $"({p.Type.Trim()}){Idioms.Ident(p.Name!)}"
            : p.Has("enum") ? $"({Idioms.CsPrimitive(p.Type, convention)}){Idioms.Ident(p.Name!)}"
            : PointerToView(model, p.Type, convention) is not null
                ? $"({NativePointerType(model, p.Type, convention)}){Idioms.Ident(p.Name!)}"
            : UntypedPointer(p.Type) is string cast ? $"({cast}){Idioms.Ident(p.Name!)}"
            : Idioms.Ident(p.Name!);
    }

    /// <summary>
    /// The native spelling an untyped pointer parameter has to be cast back to at the
    /// call. The public surface takes <c>nint</c>, which is the idiomatic way for a
    /// caller to hold a pointer the engine never dereferences, but the vtable slot is
    /// still declared in the ABI's own terms — a return value already makes this trip
    /// in the other direction.
    /// </summary>
    static string? UntypedPointer(string type)
    {
        var t = type.Replace(" ", "");
        return t switch
        {
            "void*" => "void*",
            "void**" => "void**",
            _ => null,
        };
    }

    static void RenderCallbackMethod(List<string> o, List<MemberDecl>? decls, ApiStruct vtable,
        ClassifiedSlot cs, ClassifiedModel classified, string ownerType, Convention convention)
    {
        var slot = cs.Slot;
        var cbParam = cs.PublicParams.First(p => classified.Callbacks.Any(c => c.Name == p.Type.Trim()));
        var cbType = classified.Callbacks.First(c => c.Name == cbParam.Type.Trim());
        var ifaceName = "I" + Idioms.TypeName(cbType.Name, convention) + "Native";
        var hasLevel = classified.CallbackHasLevel.GetValueOrDefault(cbType.Name);
        var handlesField = $"_{Idioms.Camel(slot.Name)}Handles";
        var otherParams = cs.PublicParams.Where(p => p != cbParam).ToList();

        o.Add($"    private readonly List<GCHandle> {handlesField} = [];");
        o.Add("");
        var lvlArg = hasLevel ? ", int minLevel = 0" : "";
        var otherArgs = string.Concat(otherParams.Select(p => $", {CsParamType2(p)} {Idioms.Ident(p.Name!)}"));
        Declare(o, decls,
            XmlDoc("    ", slot.Doc, convention, [(Idioms.Ident(cbParam.Name!), cbParam.Doc)], throwsOnFail: true).TrimEnd(),
            $"void {Idioms.Pascal(slot.Name)}({ifaceName} {Idioms.Ident(cbParam.Name!)}{otherArgs}{lvlArg})");
        o.Add("    {");
        o.Add($"        var gch = GCHandle.Alloc({Idioms.Ident(cbParam.Name!)});");
        o.Add($"        {handlesField}.Add(gch);");
        o.Add($"        var native = new {cbType.Name}");
        o.Add("        {");
        o.Add("            handle = GCHandle.ToIntPtr(gch).ToPointer(),");
        if (hasLevel) o.Add("            min_level = minLevel,");
        foreach (var s in cbType.Slots)
            o.Add($"            {s.Name} = &{Idioms.Pascal(s.Name)}Trampoline,");
        o.Add("        };");
        o.Add($"        {convention.ErrorType}* err = null;");
        var extraCall = string.Concat(otherParams.Select(p => ", " + Idioms.Ident(p.Name!)));
        o.Add($"        {convention.ErrorHelperClass}.ThrowIfFailed(Handle->{slot.Name}(Handle, native{extraCall}, &err), err, \"{slot.Name}\");");
        o.Add("    }");
        o.Add("");

        var cbParamCsType = CTypes.Deref(cbParam.Type);
        Declare(o, decls,
            $"    /// <summary>{slot.Doc} Takes an already-built <c>{cbType.Name}</c> value directly — for one produced by a native factory, not a managed <see cref=\"{ifaceName}\"/>.</summary>\n"
            + XmlDoc("    ", null, convention, otherParams.Select(p => (Idioms.Ident(p.Name!), p.Doc)), throwsOnFail: true).TrimEnd(),
            $"void {Idioms.Pascal(slot.Name)}Raw({cbParamCsType} {Idioms.Ident(cbParam.Name!)}{otherArgs})");
        o.Add("    {");
        o.Add($"        {convention.ErrorType}* err = null;");
        o.Add($"        {convention.ErrorHelperClass}.ThrowIfFailed(Handle->{slot.Name}(Handle, {Idioms.Ident(cbParam.Name!)}{extraCall}, &err), err, \"{slot.Name}\");");
        o.Add("    }");
        o.Add("");

        foreach (var s in cbType.Slots)
        {
            var trampParams = s.Params.Select(p =>
                (CTypes.IsPointer(p.Type) ? $"{CTypes.Deref(p.Type)}*" : Idioms.CsPrimitive(p.Type, convention)) + " " + Idioms.Ident(p.Name!));
            var sig = string.Join(", ", new[] { $"{cbType.Name}* self" }.Concat(trampParams));
            o.Add("    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]");
            o.Add($"    private static {Idioms.CsPrimitive(s.Returns, convention)} {Idioms.Pascal(s.Name)}Trampoline({sig})");
            o.Add("    {");
            if (s.Name == "destroy")
            {
                o.Add("        GCHandle.FromIntPtr((nint)self->handle).Free();");
            }
            else
            {
                var callArgs = string.Concat(s.Params.Select(p =>
                    ", " + (CTypes.IsPointer(p.Type) ? $"in *{Idioms.Ident(p.Name!)}" : Idioms.Ident(p.Name!))));
                o.Add($"        var target = ({ifaceName})GCHandle.FromIntPtr((nint)self->handle).Target!;");
                o.Add($"        target.{Idioms.Pascal(s.Name)}({callArgs.TrimStart(',', ' ')});");
            }
            o.Add("    }");
            o.Add("");
        }

        string CsParamType2(ApiParam p) => p.Has("enum") ? Idioms.TypeName(p.TagValue("enum")!, convention) : Idioms.CsPrimitive(p.Type, convention);
    }

    public static string RenderCallbackInterface(ApiStruct cbType, string ns, string nativeNs, Convention convention)
    {
        var ifaceName = "I" + Idioms.TypeName(cbType.Name, convention) + "Native";
        var owned = cbType.Slots.Where(s => s.Name != "destroy").ToList();

        var o = new List<string>
        {
            Header,
            $"using {nativeNs};",
            "",
            $"namespace {ns};",
            "",
        };
        o.Add(XmlDoc("", cbType.Doc, convention).TrimEnd());
        o.Add($"public unsafe interface {ifaceName}");
        o.Add("{");
        foreach (var s in owned)
        {
            o.Add(XmlDoc("    ", s.Doc, convention).TrimEnd());
            var ps = string.Join(", ", s.Params.Select(p =>
                (CTypes.IsPointer(p.Type) ? $"in {CTypes.Deref(p.Type)}" : Idioms.CsPrimitive(p.Type, convention)) + " " + Idioms.Ident(p.Name!)));
            o.Add($"    {Idioms.CsPrimitive(s.Returns, convention)} {Idioms.Pascal(s.Name)}({ps});");
        }
        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

    /// <summary>
    /// One free function as a projected method. A receiver declared <c>[ctx]</c> is the
    /// opaque token its callers already hold, so it is passed along rather than pinned;
    /// anything else is a value and has to be pinned to be addressed. What the function
    /// writes and what it returns are read from the same classification a vtable slot
    /// gets, so a tag means one thing wherever the header puts it.
    /// </summary>
    static void RenderFreeFunction(ApiModel model, List<string> o, GroupedFunction g, string prefix,
        Convention convention)
    {
        var f = g.Fn;
        var cs = g.Classified;
        var self = g.SelfParam;
        var rest = self is not null ? f.Params.Skip(1).ToList() : f.Params.ToList();
        var methodName = Idioms.Pascal(f.Name.StartsWith(prefix) ? f.Name[prefix.Length..]
            : convention.StripPrefix(f.Name));

        var selfIsCtx = self is not null && self.Has("ctx");
        var selfSig = self is null ? null
            : selfIsCtx ? $"nint {Idioms.Ident(self.Name!)}"
            : $"in {CsType(model, CTypes.Deref(self.Type), convention)} {Idioms.Ident(self.Name!)}";
        var selfArg = self is null ? null
            : selfIsCtx ? $"({NativePointerType(model, self.Type, convention)}){Idioms.Ident(self.Name!)}" : "p";

        var tupleOuts = cs.Shape is SlotShape.TupleOutParams ? cs.OutParams : [];
        var writes = cs.TrailingOuts.Concat(tupleOuts)
            .Concat(cs.OutParam is null ? [] : new[] { cs.OutParam }).ToList();

        if (cs.ReturnCount is not null || writes.Count > 0)
        {
            if (cs.Shape is SlotShape.Try || cs.Fallible || cs.ExpandedParam is not null || cs.Sequences.Count > 0)
                throw new InvalidOperationException(
                    $"{f.Name}: a free function that writes or answers with a sequence is projected"
                    + $" plainly, and this one also declares {cs.Shape}"
                    + (cs.Fallible ? " with a failure channel" : "")
                    + " -- which of them the caller reads first is a choice, not something to infer here.");
            if (cs.ReturnCount is not null && writes.Count > 0)
                throw new InvalidOperationException(
                    $"{f.Name}: the return carries the sequence, and {string.Join(", ", writes.Select(p => p.Name))}"
                    + " is written besides -- two answers reached by one call, and the sequence is"
                    + " the one the return already spells, so the other has nowhere to go.");
        }

        var ins = cs.PublicParams
            .Where(p => !tupleOuts.Contains(p) && p != cs.OutParam).ToList();
        var spanElement = cs.ReturnCount is null ? null : ReturnElement(model, cs.Slot, convention);
        var retType = spanElement is not null ? $"ReadOnlySpan<{spanElement}>"
            : cs.OutParam is not null ? OutElement(model, cs.OutParam, convention)
            : tupleOuts.Count > 0
                ? "(" + string.Join(", ", tupleOuts.Select(p =>
                    $"{OutElement(model, p, convention)} {Idioms.Pascal(WrittenName(p))}")) + ")"
            : f.Returns == convention.ByteBoolType ? "bool" : ReturnType(model, f.Returns, convention);

        string Local(ApiParam p) => Idioms.Ident(writes.Contains(p) || p == cs.ReturnCount
            ? WrittenName(p) : p.Name!)
            + (cs.TrailingOuts.Contains(p) || p == cs.ReturnCount ? "Local" : "");

        var args = (self is null ? [] : new[] { selfArg! }).Concat(rest.Select(p =>
            p == cs.ReturnCount || writes.Contains(p) ? OutAddress(model, p, convention, Local(p))
            : cs.Blobs.FirstOrDefault(b => b.Blob == p) is { } asBlob
                ? $"({NativePointerType(model, p.Type, convention)}){Idioms.Ident(p.Name!)}Ptr"
            : cs.Blobs.FirstOrDefault(b => b.Size == p) is { } asSize
                ? $"({CsType(model, asSize.Size.Type, convention)})sizeof({BlobTypeParam(asSize.Blob)})"
            : p.Has("enum") ? $"(int){Idioms.Ident(p.Name!)}"
            : Idioms.Ident(p.Name!)));
        var call = $"{(cs.ReturnCount is null ? ReturnCast(model, f.Returns, convention) : "")}"
            + $"Native.{f.Name}({string.Join(", ", args)})"
            + (f.Returns == convention.ByteBoolType ? " != 0" : "");

        var sigParts = (selfSig is null ? [] : new[] { selfSig }).Concat(ins.Select(p =>
            cs.Blobs.Any(b => b.Blob == p)
                ? $"in {BlobTypeParam(p)} {Idioms.Ident(p.Name!)}"
            : cs.TrailingOuts.Contains(p)
                ? $"out {OutElement(model, p, convention)} {Idioms.Ident(WrittenName(p))}"
                : $"{CsParamType(model, p, convention)} {Idioms.Ident(p.Name!)}"));

        var generics = cs.Blobs.Count == 0 ? ""
            : "<" + string.Join(", ", cs.Blobs.Select(b => BlobTypeParam(b.Blob))) + ">";
        var constraints = string.Concat(cs.Blobs
            .Select(b => $" where {BlobTypeParam(b.Blob)} : unmanaged"));

        o.Add(XmlDoc("    ", f.Doc, convention, ins.Select(p =>
            (Idioms.Ident(cs.TrailingOuts.Contains(p) ? WrittenName(p) : p.Name!), p.Doc))).TrimEnd());
        o.Add($"    public static {retType} {methodName}{generics}({string.Join(", ", sigParts)}){constraints}");
        o.Add("    {");

        var needsFixed = self is not null && !selfIsCtx;
        var body = new List<string>();
        foreach (var p in writes)
            body.Add($"{OutLocal(model, p, convention)} {Local(p)};");
        if (cs.ReturnCount is not null)
        {
            var native = CsType(model, CTypes.Deref(f.Returns), convention);
            var front = spanElement == native ? "front" : $"({spanElement}*)front";
            body.Add($"{CsType(model, CTypes.Deref(cs.ReturnCount.Type), convention)} {Local(cs.ReturnCount)} = 0;");
            body.Add($"var front = {call};");
            body.Add($"return front == null ? default"
                + $" : new ReadOnlySpan<{spanElement}>({front}, (int){Local(cs.ReturnCount)});");
        }
        else if (writes.Count == 0)
            body.Add((retType == "void" ? "" : "return ") + call + ";");
        else
        {
            body.Add($"{call};");
            foreach (var p in cs.TrailingOuts)
                body.Add($"{Idioms.Ident(WrittenName(p))} = {OutRead(p, Local(p))};");
            body.Add(cs.OutParam is not null
                ? $"return {OutRead(cs.OutParam, Local(cs.OutParam))};"
                : $"return ({string.Join(", ", tupleOuts.Select(p => OutRead(p, Local(p))))});");
        }

        var pins = new List<string>();
        if (needsFixed)
            pins.Add($"fixed ({CsType(model, CTypes.Deref(self!.Type), convention)}* p = &{Idioms.Ident(self.Name!)})");
        foreach (var b in cs.Blobs)
            pins.Add($"fixed ({BlobTypeParam(b.Blob)}* {Idioms.Ident(b.Blob.Name!)}Ptr"
                + $" = &{Idioms.Ident(b.Blob.Name!)})");

        var braced = pins.Count > 1 || (pins.Count == 1 && body.Count > 1);
        for (var i = 0; i < pins.Count; i++)
        {
            var at = new string(' ', 8 + i * 4);
            o.Add(at + pins[i]);
            if (braced) o.Add(at + "{");
        }
        var indent = new string(' ', 8 + pins.Count * 4);
        foreach (var line in body) o.Add(indent + line);
        if (braced) for (var i = pins.Count - 1; i >= 0; i--) o.Add(new string(' ', 8 + i * 4) + "}");
        o.Add("    }");
        o.Add("");
    }

    public static string RenderFreeFunctions(ApiModel model, string owner, List<GroupedFunction> fns, string ns, string nativeNs,
        IReadOnlyList<string> extraUsings, string libraryName, Convention convention)
    {
        var ownerCs = Idioms.TypeName(owner, convention);
        var prefix = owner + "_";

        var o = new List<string>
        {
            Header,
            "using System.Runtime.InteropServices;",
            $"using {convention.CommonBindingsNamespace};",
            $"using {nativeNs};",
        };
        foreach (var u in extraUsings) o.Add($"using {u};");
        o.AddRange([
            "",
            $"namespace {ns};",
            "",
            $"/// <summary>Free-function operations on <see cref=\"{owner}\"/>.</summary>",
            $"public unsafe partial class {ownerCs}",
            "{",
        ]);

        foreach (var g in fns) RenderFreeFunction(model, o, g, prefix, convention);

        o.Add("    private static unsafe class Native");
        o.Add("    {");
        foreach (var g in fns)
        {
            var f = g.Fn;
            var rest = (g.SelfParam is not null ? f.Params.Skip(1) : f.Params)
                .Select(p => $"{(p.Has("enum") ? "int" : CsType(model, p.Type, convention))} {Idioms.Ident(p.Name!)}").ToList();
            var selfParamSig = g.SelfParam is not null ? $"{CsType(model, CTypes.Deref(f.Params[0].Type), convention)}* {Idioms.Ident(f.Params[0].Name!)}" : null;
            var nativeSig = string.Join(", ", (selfParamSig is not null ? [selfParamSig] : Array.Empty<string>()).Concat(rest));
            o.Add($"        [DllImport(\"{libraryName}\", CallingConvention = CallingConvention.Cdecl,");
            o.Add($"                   EntryPoint = \"{f.Name}\", ExactSpelling = true)]");
            o.Add($"        public static extern {(f.Returns == convention.ByteBoolType ? "byte" : CsType(model, f.Returns, convention))} {f.Name}({nativeSig});");
            o.Add("");
        }
        o.Add("    }");
        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

