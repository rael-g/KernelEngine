
namespace Kabic.CSharp;

using Kabic;

public static class CSharpBackend
{
    const string Header = "// <auto-generated/>\n// Derived from ke_api.json. Do not edit; edit the C header instead.\n";

    static string XmlDoc(string indent, string? summary, IEnumerable<(string Name, string? Doc)>? pars = null,
        string? ret = null, bool throwsOnFail = false)
    {
        var lines = new List<string>();
        if (!string.IsNullOrEmpty(summary)) lines.Add($"{indent}/// <summary>{Escape(summary)}</summary>");
        foreach (var (n, d) in pars ?? [])
            if (!string.IsNullOrEmpty(d)) lines.Add($"{indent}/// <param name=\"{n}\">{Escape(d)}</param>");
        if (!string.IsNullOrEmpty(ret)) lines.Add($"{indent}/// <returns>{Escape(ret)}</returns>");
        if (throwsOnFail) lines.Add($"{indent}/// <exception cref=\"KernelError\">The native call failed.</exception>");
        return lines.Count > 0 ? string.Join('\n', lines) + '\n' : "";
    }

    static string Escape(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    /// Emits the `fixed` pinning prologue encoding every [utf8] parameter as a
    /// NUL-terminated byte buffer, returning the lines and the number of braces
    /// the caller must close.
    static (List<string> Lines, int Depth) Utf8Prologue(IEnumerable<ApiParam> ps, string indent)
    {
        var lines = new List<string>();
        var depth = 0;
        foreach (var p in ps.Where(x => x.Has("utf8")))
        {
            var n = Idioms.Ident(p.Name!);
            lines.Add($"{indent}var {n}Bytes = System.Text.Encoding.UTF8.GetBytes({n} + '\\0');");
            lines.Add($"{indent}fixed (byte* {n}Ptr = {n}Bytes)");
            lines.Add($"{indent}{{");
            depth++;
        }
        return (lines, depth);
    }

    /// A C type mapped to C#. Typedef aliases resolve first; pointers recurse so
    /// `const`/`struct` qualifiers are dropped and the pointee receives the same
    /// mapping as any other type. An opaque `void *` maps to `nint`.
    static string CsType(ApiModel model, string cType)
    {
        var t = cType.Trim();
        if (t is "void *" or "void*") return "nint";
        if (CTypes.IsPointer(t))
        {
            var inner = CTypes.Deref(t).Trim();
            if (inner.StartsWith("const ")) inner = inner["const ".Length..];
            if (inner.StartsWith("struct ")) inner = inner["struct ".Length..];
            return CsType(model, inner) + "*";
        }
        return Idioms.CsPrimitive(model.ResolveAlias(t));
    }

    static string CsParamType(ApiModel model, ApiParam p, Convention convention)
    {
        var tagEnum = p.TagValue("enum");
        if (tagEnum is not null) return Idioms.TypeName(tagEnum, convention);
        if (p.Has("utf8")) return "string";
        if (p.Has("opaque")) return "void*";
        if (model.Enums.Any(e => e.Name == p.Type.Trim()))
            return Idioms.TypeName(p.Type.Trim(), convention);
        return CsType(model, p.Type);
    }

    public static string RenderNodeType(ApiModel model, ApiStruct component, string ns, string nativeNs, Convention convention)
    {
        var nodeName = component.TagValue("node") ?? throw new InvalidOperationException($"{component.Name} has no [node:] tag");
        var baseName = component.TagValue("base") ?? "Node";
        var nativeType = component.Name;

        var o = new List<string> { Header, "using System.Numerics;", $"using {nativeNs};\n", $"namespace {ns};\n" };
        o.Add(component.Doc is not null ? XmlDoc("", component.Doc).TrimEnd()
            : $"/// <summary>Mirrors <c>{nativeType}</c>.</summary>");
        o.Add($"public class {nodeName} : {baseName}");
        o.Add("{");

        o.Add($"    private {nativeType} _state = new();");
        o.Add("    private uint _cid;");
        o.Add("");
        o.Add($"    public {nodeName}()");
        o.Add("    {");
        foreach (var f in component.Fields)
            foreach (var line in FieldInit(model, f)) o.Add($"        {line}");
        o.Add("    }");
        o.Add("");

        foreach (var f in component.Fields)
        {
            var propName = Idioms.Pascal(f.Name);
            var propType = NodePropertyType(model, f);
            if (!string.IsNullOrEmpty(f.Doc)) o.Add($"    /// <summary>{Escape(f.Doc)}</summary>");
            o.Add($"    public {propType} {propName}");
            o.Add("    {");
            o.Add($"        get => {ReadField(f, "_state")};");
            o.Add("        set");
            o.Add("        {");
            foreach (var line in AssignField(f, "_state", "value")) o.Add($"            {line}");
            o.Add("            WriteIfBound();");
            o.Add("        }");
            o.Add("    }");
        }

        var componentName = convention.ComponentNameFor(component.Name);
        o.Add("");
        o.Add("    private void WriteIfBound()");
        o.Add("    {");
        o.Add("        if (IsBound) NodeWorld!.SetByCid(Entity, _cid, _state);");
        o.Add("    }");
        o.Add("");
        o.Add("    protected internal override void OnBind(NodeWorld nodeWorld)");
        o.Add("    {");
        o.Add($"        _cid = nodeWorld.CidOfName(\"{componentName}\");");
        o.Add("        nodeWorld.SetByCid(Entity, _cid, _state);");
        o.Add("    }");
        o.Add("}");
        return string.Join('\n', o);
    }

    static int? VectorArity(string cType)
    {
        var m = System.Text.RegularExpressions.Regex.Match(cType.Trim(), @"^float\s*\[(\d+)\]$");
        return m.Success && int.Parse(m.Groups[1].Value) is >= 2 and <= 4 ? int.Parse(m.Groups[1].Value) : null;
    }

    static string NodePropertyType(ApiModel model, ApiField f) =>
        VectorArity(f.Type) is int n ? $"Vector{n}" : CsType(model, f.Type);

    static string ReadField(ApiField f, string owner) =>
        VectorArity(f.Type) is int n
            ? $"new({string.Join(", ", Enumerable.Range(0, n).Select(i => $"{owner}.{f.Name}[{i}]"))})"
            : $"{owner}.{f.Name}";

    static readonly string[] VectorLanes = ["X", "Y", "Z", "W"];

    static IEnumerable<string> AssignField(ApiField f, string owner, string value) =>
        VectorArity(f.Type) is int n
            ? Enumerable.Range(0, n).Select(i => $"{owner}.{f.Name}[{i}] = {value}.{VectorLanes[i]};")
            : [$"{owner}.{f.Name} = {value};"];

    static IEnumerable<string> FieldInit(ApiModel model, ApiField f)
    {
        var d = f.TagValue("default");
        if (d is null) return [];
        if (VectorArity(f.Type) is int n)
        {
            var parts = d.Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            if (parts.Length != n)
                throw new InvalidOperationException(
                    $"{f.Name}: [default:{d}] has {parts.Length} components but the field is float[{n}]");
            return parts.Select((p, i) => $"_state.{f.Name}[{i}] = {p}f;");
        }
        return [$"_state.{f.Name} = {(CsType(model, f.Type) is "float" ? d + "f" : d)};"];
    }

    public static string RenderEnums(ApiModel model, string ns, Convention convention)
    {
        var o = new List<string> { Header, $"namespace {ns};\n" };
        foreach (var e in model.Enums)
        {
            o.Add(e.Doc is not null
                ? XmlDoc("", e.Doc).TrimEnd()
                : $"/// <summary>Mirrors <c>{e.Name}</c>.</summary>");
            o.Add($"public enum {Idioms.TypeName(e.Name, convention)}");
            o.Add("{");
            foreach (var v in e.Values)
            {
                if (!string.IsNullOrEmpty(v.Doc)) o.Add($"    /// <summary>{Escape(v.Doc)}</summary>");
                var name = Idioms.EnumMember(v.Name, e.Name);
                var val = v.IsInt ? v.RawValue : Idioms.EnumMember(v.RawValue, e.Name);
                o.Add($"    {name} = {val},");
            }
            o.Add("}");
            o.Add("");
        }
        return string.Join('\n', o);
    }

    public static string RenderProvider(ApiModel model, ApiStruct vtable, ClassifiedModel classified,
        string ns, string nativeNs, IReadOnlyList<string> extraUsings, Convention convention)
    {
        var typeName = Idioms.TypeName(vtable.Name, convention);
        var slots = classified.SlotsByVtable[vtable.Name];
        var plan = classified.Constructors[vtable.Name];

        var o = new List<string>
        {
            Header,
            "using System.Runtime.CompilerServices;", // CallConvCdecl, needed whenever a slot has a [callback] param
            "using System.Runtime.InteropServices;",
            "using KernelEngine.Common;",
            "using KernelEngine.Common.Native;",
            $"using {nativeNs};",
        };
        foreach (var u in extraUsings) o.Add($"using {u};");
        o.Add("");
        o.Add($"namespace {ns};");
        o.Add("");

        var nativeIface = "INative" + Idioms.Pascal(convention.StripPrefix(vtable.Name));
        o.Add($"/// <summary>Exposes the raw native {typeName.ToLowerInvariant()} pointer for cross-domain composition wiring.</summary>");
        o.Add($"public unsafe interface {nativeIface}");
        o.Add("{");
        o.Add($"    {vtable.Name}* Native {{ get; }}");
        o.Add("}");
        o.Add("");

        o.Add(XmlDoc("", vtable.Doc).TrimEnd());
        o.Add($"public unsafe partial class {typeName} : IDisposable, {nativeIface}");
        o.Add("{");
        o.Add($"    private {vtable.Name}* _native;");
        o.Add($"    private readonly delegate* unmanaged[Cdecl]<{vtable.Name}*, void> _destroy;");
        o.Add("    private readonly bool _borrowed;");
        o.Add("");
        o.Add($"    private {vtable.Name}* Handle => _native != null ? _native");
        o.Add($"        : throw new ObjectDisposedException(nameof({typeName}));");
        o.Add("");
        o.Add($"    {vtable.Name}* {nativeIface}.Native => Handle;");
        o.Add("");

        classified.LifecycleInit.TryGetValue(vtable.Name, out var initSlot);
        classified.LifecycleShutdown.TryGetValue(vtable.Name, out var shutdownSlot);
        var initCall = initSlot is not null
            ? $"        {{ ke_error* err2 = null; KernelError.ThrowIfFailed(_native->{initSlot}(_native, &err2), err2, \"{initSlot}\"); }}"
            : null;

        if (plan.Kind == ConstructorKind.FromFactory)
        {
            var factory = plan.Factory!;
            var fparams = factory.Params.Where(p => !convention.IsErrorOutParam(p)).ToList();
            var sig = string.Join(", ", fparams.Select(p => $"{Idioms.CsForeignType(p.Type)} {Idioms.Ident(p.Name!)}"));
            var call = string.Join(", ", fparams.Select(p => Idioms.Ident(p.Name!)));
            o.Add(XmlDoc("    ", factory.Doc, fparams.Select(p => (Idioms.Ident(p.Name!), p.Doc)),
                throwsOnFail: true).TrimEnd());
            o.Add($"    {(plan.NeedsWrapper ? "internal" : "public")} {typeName}({sig})");
            o.Add("    {");
            o.Add("        ke_error* err = null;");
            o.Add($"        var handle = {nativeNs}.NativeMethods.{convention.StripPrefix(factory.Name)}({(call.Length > 0 ? call + ", " : "")}&err);");
            o.Add($"        if (handle.@ref == null) throw KernelError.FromNative(err, \"{factory.Name}\");");
            o.Add("        _native = handle.@ref;");
            o.Add("        _destroy = handle.destroy;");
            if (initCall is not null) o.Add(initCall);
            o.Add("    }");
            o.Add("");
        }
        else if (plan.Kind == ConstructorKind.FromHandle)
        {
            var handleType = plan.HandleTypeName!;
            o.Add($"    /// <summary>Wraps an owner <c>{handleType}</c> and runs {typeName.ToLowerInvariant()}'s startup lifecycle hook.</summary>");
            if (initCall is not null) o.Add("    /// <exception cref=\"KernelError\">The native call failed.</exception>");
            o.Add($"    public {typeName}({handleType} handle)");
            o.Add("    {");
            o.Add("        if (handle.@ref == null) throw new ArgumentNullException(nameof(handle));");
            o.Add("        _native = handle.@ref;");
            o.Add("        _destroy = handle.destroy;");
            if (initCall is not null) o.Add(initCall);
            o.Add("    }");
            o.Add("");
        }

        o.Add($"    /// <summary>Wraps a <c>{vtable.Name}*</c> owned elsewhere. Disposing the result does not destroy it.</summary>");
        o.Add($"    public static {typeName} Borrow({vtable.Name}* native) => new(native, borrowed: true);");
        o.Add("");
        o.Add($"    private {typeName}({vtable.Name}* native, bool borrowed)");
        o.Add("    {");
        o.Add("        _native = native;");
        o.Add("        _destroy = null;");
        o.Add("        _borrowed = borrowed;");
        o.Add("    }");
        o.Add("");

        foreach (var cs in slots)
        {
            if (cs.Slot.Has("sink") || cs.Slot.Has("lifecycle") || cs.Slot.Has("raw_callback")
                || cs.Slot.Has("idiom") || cs.PublicParams.Any(p => p.Has("raw_callback")))
                continue;
            if (cs.PublicParams.Any(p => classified.Callbacks.Any(c => c.Name == p.Type.Trim())))
            {
                RenderCallbackMethod(o, vtable, cs, classified, typeName, convention);
                continue;
            }
            RenderSlotMethod(model, o, cs, convention);
        }

        o.Add($"    /// <summary>Releases the native {typeName.ToLowerInvariant()}.</summary>");
        o.Add("    public void Dispose()");
        o.Add("    {");
        o.Add("        OnDispose();");
        o.Add("        if (_native == null) return;");
        o.Add("        if (_borrowed) { _native = null; return; }");
        if (shutdownSlot is not null)
            o.Add($"        _native->{shutdownSlot}(_native, null);");
        o.Add("        _destroy(_native);");
        o.Add("        _native = null;");
        o.Add("    }");
        o.Add("");
        o.Add("    partial void OnDispose();");
        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

    static void RenderSlotMethod(ApiModel model, List<string> o, ClassifiedSlot cs, Convention convention)
    {
        var slot = cs.Slot;
        var name = Idioms.Pascal(slot.Name);

        switch (cs.Shape)
        {
            case SlotShape.ReturnsOutParam:
            {
                var ret = CsType(model, CTypes.Deref(cs.OutParam!.Type));
                var ins = cs.PublicParams.Where(p => p != cs.OutParam).ToList();
                var sig = string.Join(", ", ins.Select(p => $"{CsParamType(model, p, convention)} {Idioms.Ident(p.Name!)}"));
                var nativeArgs = string.Concat(cs.PublicParams.Select(p =>
                    ", " + (p == cs.OutParam ? "&result" : CallArg(p))));

                o.Add(XmlDoc("    ", slot.Doc, ins.Select(p => (Idioms.Ident(p.Name!), p.Doc)),
                    slot.ReturnDoc, cs.Fallible).TrimEnd());
                o.Add($"    public {ret} {name}({sig})");
                o.Add("    {");
                var (roPro, roDepth) = Utf8Prologue(ins, new string(' ', 8));
                o.AddRange(roPro);
                var roInd = new string(' ', 8 + roDepth * 4);
                o.Add($"{roInd}{ret} result;");
                if (cs.Fallible)
                {
                    o.Add($"{roInd}ke_error* err = null;");
                    o.Add($"{roInd}KernelError.ThrowIfFailed(Handle->{slot.Name}(Handle{nativeArgs}, &err), err, \"{slot.Name}\");");
                }
                else
                {
                    o.Add($"{roInd}Handle->{slot.Name}(Handle{nativeArgs});");
                }
                o.Add($"{roInd}return result;");
                for (var d = roDepth; d > 0; d--) o.Add(new string(' ', 4 + d * 4) + "}");
                o.Add("    }");
                o.Add("");
                return;
            }
            case SlotShape.TupleOutParams:
            {
                var ins = cs.PublicParams.Where(p => !cs.OutParams.Contains(p)).ToList();
                var sig = string.Join(", ", ins.Select(p => $"{CsParamType(model, p, convention)} {Idioms.Ident(p.Name!)}"));
                var names = cs.OutParams.Select(p => Idioms.Pascal(p.Name!)).ToList();
                var types = cs.OutParams.Select(p => CsType(model, CTypes.Deref(p.Type))).ToList();
                var retTuple = string.Join(", ", types.Zip(names, (t, n) => $"{t} {n}"));
                var locals = cs.OutParams.Select(p => Idioms.Ident(p.Name!)).ToList();
                var nativeArgs = cs.Slot.Params
                    .Where(p => !cs.Fallible || p != cs.Slot.Params[^1])
                    .Select(p => cs.OutParams.Contains(p) ? $"&{Idioms.Ident(p.Name!)}" : CallArg(p));
                var callArgs = string.Concat(nativeArgs.Select(a => ", " + a));

                o.Add(XmlDoc("    ", slot.Doc, ins.Select(p => (Idioms.Ident(p.Name!), p.Doc)),
                    throwsOnFail: cs.Fallible).TrimEnd());
                o.Add($"    public ({retTuple}) {name}({sig})");
                o.Add("    {");
                var (tuPro, tuDepth) = Utf8Prologue(ins, new string(' ', 8));
                o.AddRange(tuPro);
                var tuInd = new string(' ', 8 + tuDepth * 4);
                foreach (var (t, n) in types.Zip(locals)) o.Add($"{tuInd}{t} {n};");
                if (cs.Fallible)
                {
                    o.Add($"{tuInd}ke_error* err = null;");
                    o.Add($"{tuInd}KernelError.ThrowIfFailed(Handle->{slot.Name}(Handle{callArgs}, &err), err, \"{slot.Name}\");");
                }
                else
                {
                    o.Add($"{tuInd}Handle->{slot.Name}(Handle{callArgs});");
                }
                o.Add($"{tuInd}return ({string.Join(", ", locals)});");
                for (var d = tuDepth; d > 0; d--) o.Add(new string(' ', 4 + d * 4) + "}");
                o.Add("    }");
                o.Add("");
                return;
            }
            case SlotShape.Sequence:
            {
                var elem = CsType(model, CTypes.Deref(cs.SequenceParam!.Type));
                var pname = Idioms.Ident(cs.SequenceParam!.Name!);
                var others = cs.PublicParams.Where(p => p != cs.SequenceParam).ToList();
                var outs = others.Where(p => p.Has("out")).ToList();
                var ins = others.Where(p => !p.Has("out")).ToList();

                var sigParts = ins.Select(p => $"{CsParamType(model, p, convention)} {Idioms.Ident(p.Name!)}")
                    .Append($"Span<{elem}> {pname}")
                    .Concat(outs.Select(p => $"out {CsType(model, CTypes.Deref(p.Type))} {Idioms.Ident(p.Name!)}"));

                var retType = cs.Fallible || slot.Returns == "void" ? "void"
                    : CsType(model, slot.Returns);

                o.Add(XmlDoc("    ", slot.Doc,
                    ins.Select(p => (Idioms.Ident(p.Name!), p.Doc))
                       .Append((pname, cs.SequenceParam.Doc))
                       .Concat(outs.Select(p => (Idioms.Ident(p.Name!), p.Doc))),
                    slot.ReturnDoc, cs.Fallible).TrimEnd());
                o.Add($"    public {retType} {name}Raw({string.Join(", ", sigParts)})");
                o.Add("    {");
                foreach (var op in outs) o.Add($"        {CsType(model, CTypes.Deref(op.Type))} {Idioms.Ident(op.Name!)}Local;");

                var nativeArgs = cs.Slot.Params
                    .Where(p => !cs.Fallible || p != cs.Slot.Params[^1])
                    .Select(p =>
                        p == cs.SequenceParam ? "p"
                        : p == cs.CountParam ? $"({CsType(model, p.Type)}){pname}.Length"
                        : outs.Contains(p) ? $"&{Idioms.Ident(p.Name!)}Local"
                        : Idioms.Ident(p.Name!));

                var call = $"Handle->{slot.Name}(Handle, {string.Join(", ", nativeArgs)}";
                o.Add($"        fixed ({elem}* p = {pname})");
                o.Add("        {");
                if (cs.Fallible)
                {
                    o.Add("            ke_error* err = null;");
                    o.Add($"            KernelError.ThrowIfFailed({call}, &err), err, \"{slot.Name}\");");
                }
                else if (retType == "void")
                {
                    o.Add($"            {call});");
                }
                else
                {
                    o.Add($"            var result = {call});");
                }
                foreach (var op in outs) o.Add($"            {Idioms.Ident(op.Name!)} = {Idioms.Ident(op.Name!)}Local;");
                if (retType != "void" && !cs.Fallible) o.Add("            return result;");
                o.Add("        }");
                o.Add("    }");
                o.Add("");
                return;
            }
            case SlotShape.Try:
            {
                var ins = cs.PublicParams.Where(p => !p.Has("out")).ToList();
                var outs = cs.OutParams;
                var sigParts = ins.Select(p => $"{CsParamType(model, p, convention)} {Idioms.Ident(p.Name!)}")
                    .Concat(outs.Select(p => $"out {CsType(model, CTypes.Deref(p.Type))} {Idioms.Ident(p.Name!)}"));

                var tryName = name.StartsWith("Try") ? name : $"Try{name}";
                o.Add(XmlDoc("    ", slot.Doc,
                    cs.PublicParams.Select(p => (Idioms.Ident(p.Name!), p.Doc)), slot.ReturnDoc).TrimEnd());
                o.Add($"    public bool {tryName}({string.Join(", ", sigParts)})");
                o.Add("    {");
                foreach (var op in outs) o.Add($"        {CsType(model, CTypes.Deref(op.Type))} {Idioms.Ident(op.Name!)}Local;");
                var (tPro, tDepth) = Utf8Prologue(ins, new string(' ', 8));
                o.AddRange(tPro);
                var tInd = new string(' ', 8 + tDepth * 4);
                var tryArgs = cs.Slot.Params
                    .Where(p => !cs.Fallible || p != cs.Slot.Params[^1])
                    .Select(p => outs.Contains(p) ? $"&{Idioms.Ident(p.Name!)}Local" : CallArg(p));
                var tryCall = $"Handle->{slot.Name}(Handle, {string.Join(", ", tryArgs)}"
                    + (cs.Fallible ? ", null)" : ")")
                    + (slot.Returns == "ke_bool" ? " != 0" : "");
                o.Add($"{tInd}var found = {tryCall};");
                foreach (var op in outs) o.Add($"{tInd}{Idioms.Ident(op.Name!)} = {Idioms.Ident(op.Name!)}Local;");
                o.Add($"{tInd}return found;");
                for (var d = tDepth; d > 0; d--) o.Add(new string(' ', 4 + d * 4) + "}");
                o.Add("    }");
                o.Add("");
                return;
            }
            case SlotShape.Fallible:
            {
                var args = cs.PublicParams;
                var byReturn = convention.SignalsFailureByReturn(slot.Returns);
                var retType = byReturn ? "void" : CsType(model, slot.Returns);
                var sig = string.Join(", ", args.Select(p => $"{CsParamType(model, p, convention)} {Idioms.Ident(p.Name!)}"));
                var call = string.Concat(args.Select(p => ", " + CallArg(p)));
                o.Add(XmlDoc("    ", slot.Doc, args.Select(p => (Idioms.Ident(p.Name!), p.Doc)),
                    byReturn ? slot.ReturnDoc : null, throwsOnFail: true).TrimEnd());
                o.Add($"    public {retType} {name}({sig})");
                o.Add("    {");
                var (fPro, fDepth) = Utf8Prologue(args, new string(' ', 8));
                o.AddRange(fPro);
                var fInd = new string(' ', 8 + fDepth * 4);
                o.Add($"{fInd}ke_error* err = null;");
                if (byReturn)
                {
                    var boolCall = $"Handle->{slot.Name}(Handle{call}, &err)"
                        + (slot.Returns == "ke_bool" ? " != 0" : "");
                    o.Add($"{fInd}KernelError.ThrowIfFailed({boolCall}, err, \"{slot.Name}\");");
                }
                else
                {
                    o.Add($"{fInd}var result = Handle->{slot.Name}(Handle{call}, &err);");
                    if (CTypes.IsPointer(slot.Returns))
                        o.Add($"{fInd}if (result == null) throw KernelError.FromNative(err, \"{slot.Name}\");");
                    else
                        o.Add($"{fInd}if (err != null) throw KernelError.FromNative(err, \"{slot.Name}\");");
                    o.Add($"{fInd}return result;");
                }
                for (var d = fDepth; d > 0; d--) o.Add(new string(' ', 4 + d * 4) + "}");
                o.Add("    }");
                o.Add("");
                return;
            }
            default:
            {
                var args = cs.PublicParams;
                var sig = string.Join(", ", args.Select(p => $"{CsParamType(model, p, convention)} {Idioms.Ident(p.Name!)}"));
                var call = string.Concat(args.Select(p => ", " + CallArg(p)));
                var retType = slot.Returns == "ke_bool" ? "bool" : CsType(model, slot.Returns);
                var needsCast = retType == "nint"; // CsPrimitive maps `void *` -> nint; the raw call still returns void*
                o.Add(XmlDoc("    ", slot.Doc, args.Select(p => (Idioms.Ident(p.Name!), p.Doc)), slot.ReturnDoc).TrimEnd());
                o.Add($"    public {retType} {name}({sig})");
                o.Add("    {");
                var (pPro, pDepth) = Utf8Prologue(args, new string(' ', 8));
                o.AddRange(pPro);
                var pInd = new string(' ', 8 + pDepth * 4);
                if (slot.Returns == "ke_bool")
                    o.Add($"{pInd}return Handle->{slot.Name}(Handle{call}) != 0;");
                else if (retType == "void")
                    o.Add($"{pInd}Handle->{slot.Name}(Handle{call});");
                else if (needsCast)
                    o.Add($"{pInd}return (nint)Handle->{slot.Name}(Handle{call});");
                else
                    o.Add($"{pInd}return Handle->{slot.Name}(Handle{call});");
                for (var d = pDepth; d > 0; d--) o.Add(new string(' ', 4 + d * 4) + "}");
                o.Add("    }");
                o.Add("");
                return;
            }
        }

        string CallArg(ApiParam p) =>
            p.Has("utf8") ? $"(sbyte*){Idioms.Ident(p.Name!)}Ptr"
            : p.Type.Trim() == "ke_bool" ? $"{Idioms.Ident(p.Name!)} ? (byte)1 : (byte)0"
            : model.Enums.Any(e => e.Name == p.Type.Trim()) ? $"({p.Type.Trim()}){Idioms.Ident(p.Name!)}"
            : p.Has("enum") ? $"({Idioms.CsPrimitive(p.Type)}){Idioms.Ident(p.Name!)}"
            : Idioms.Ident(p.Name!);
    }

    static void RenderCallbackMethod(List<string> o, ApiStruct vtable, ClassifiedSlot cs,
        ClassifiedModel classified, string ownerType, Convention convention)
    {
        var slot = cs.Slot;
        var cbParam = cs.PublicParams.First(p => classified.Callbacks.Any(c => c.Name == p.Type.Trim()));
        var cbType = classified.Callbacks.First(c => c.Name == cbParam.Type.Trim());
        var ifaceName = "I" + Idioms.TypeName(cbType.Name, convention) + "Native";
        var hasLevel = classified.CallbackHasLevel.GetValueOrDefault(cbType.Name);
        var handlesField = $"_{Idioms.Camel(slot.Name)}Handles";
        var otherParams = cs.PublicParams.Where(p => p != cbParam).ToList();

        o.Add(XmlDoc("    ", slot.Doc, [(Idioms.Ident(cbParam.Name!), cbParam.Doc)], throwsOnFail: true).TrimEnd());
        o.Add($"    // Roots each managed callback implementation for as long as native code");
        o.Add($"    // holds a pointer to it; released by the destroy trampoline below.");
        o.Add($"    private readonly List<GCHandle> {handlesField} = [];");
        o.Add("");
        var lvlArg = hasLevel ? ", int minLevel = 0" : "";
        var otherArgs = string.Concat(otherParams.Select(p => $", {CsParamType2(p)} {Idioms.Ident(p.Name!)}"));
        o.Add($"    public void {Idioms.Pascal(slot.Name)}({ifaceName} {Idioms.Ident(cbParam.Name!)}{otherArgs}{lvlArg})");
        o.Add("    {");
        o.Add($"        var gch = GCHandle.Alloc({Idioms.Ident(cbParam.Name!)});");
        o.Add($"        {handlesField}.Add(gch);");
        o.Add($"        var native = new {cbType.Name}");
        o.Add("        {");
        o.Add("            handle = GCHandle.ToIntPtr(gch).ToPointer(),");
        if (hasLevel) o.Add("            min_level = minLevel,");
        foreach (var s in cbType.Slots)
            o.Add($"            {s.Name} = &{Idioms.Pascal(s.Name)}Trampoline,");
        o.Add("        };");
        o.Add("        ke_error* err = null;");
        var extraCall = string.Concat(otherParams.Select(p => ", " + Idioms.Ident(p.Name!)));
        o.Add($"        KernelError.ThrowIfFailed(Handle->{slot.Name}(Handle, native{extraCall}, &err), err, \"{slot.Name}\");");
        o.Add("    }");
        o.Add("");

        var cbParamCsType = CTypes.Deref(cbParam.Type);
        o.Add($"    /// <summary>{slot.Doc} Takes an already-built <c>{cbType.Name}</c> value directly — for one produced by a native factory, not a managed <see cref=\"{ifaceName}\"/>.</summary>");
        o.Add(XmlDoc("    ", null, otherParams.Select(p => (Idioms.Ident(p.Name!), p.Doc)), throwsOnFail: true).TrimEnd());
        o.Add($"    public void {Idioms.Pascal(slot.Name)}Raw({cbParamCsType} {Idioms.Ident(cbParam.Name!)}{otherArgs})");
        o.Add("    {");
        o.Add("        ke_error* err = null;");
        o.Add($"        KernelError.ThrowIfFailed(Handle->{slot.Name}(Handle, {Idioms.Ident(cbParam.Name!)}{extraCall}, &err), err, \"{slot.Name}\");");
        o.Add("    }");
        o.Add("");

        foreach (var s in cbType.Slots)
        {
            var trampParams = s.Params.Select(p =>
                (CTypes.IsPointer(p.Type) ? $"{CTypes.Deref(p.Type)}*" : Idioms.CsPrimitive(p.Type)) + " " + Idioms.Ident(p.Name!));
            var sig = string.Join(", ", new[] { $"{cbType.Name}* self" }.Concat(trampParams));
            o.Add("    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]");
            o.Add($"    private static {Idioms.CsPrimitive(s.Returns)} {Idioms.Pascal(s.Name)}Trampoline({sig})");
            o.Add("    {");
            if (s.Name == "destroy")
            {
                o.Add("        GCHandle.FromIntPtr((nint)self->handle).Free();");
            }
            else
            {
                var callArgs = string.Concat(s.Params.Select(p =>
                    ", " + (CTypes.IsPointer(p.Type) ? $"in *{Idioms.Ident(p.Name!)}" : Idioms.Ident(p.Name!))));
                o.Add($"        var target = ({ifaceName})GCHandle.FromIntPtr((nint)self->handle).Target!;");
                o.Add($"        target.{Idioms.Pascal(s.Name)}({callArgs.TrimStart(',', ' ')});");
            }
            o.Add("    }");
            o.Add("");
        }

        string CsParamType2(ApiParam p) => p.Has("enum") ? Idioms.TypeName(p.TagValue("enum")!, convention) : Idioms.CsPrimitive(p.Type);
    }

    public static string RenderCallbackInterface(ApiStruct cbType, string ns, string nativeNs, Convention convention)
    {
        var ifaceName = "I" + Idioms.TypeName(cbType.Name, convention) + "Native";
        var owned = cbType.Slots.Where(s => s.Name != "destroy").ToList();

        var o = new List<string>
        {
            Header,
            $"using {nativeNs};",
            "",
            $"namespace {ns};",
            "",
        };
        o.Add(XmlDoc("", cbType.Doc).TrimEnd());
        o.Add($"public unsafe interface {ifaceName}");
        o.Add("{");
        foreach (var s in owned)
        {
            o.Add(XmlDoc("    ", s.Doc).TrimEnd());
            var ps = string.Join(", ", s.Params.Select(p =>
                (CTypes.IsPointer(p.Type) ? $"in {CTypes.Deref(p.Type)}" : Idioms.CsPrimitive(p.Type)) + " " + Idioms.Ident(p.Name!)));
            o.Add($"    {Idioms.CsPrimitive(s.Returns)} {Idioms.Pascal(s.Name)}({ps});");
        }
        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

    public static string RenderFreeFunctions(string owner, List<GroupedFunction> fns, string ns, string nativeNs,
        string libraryName, Convention convention)
    {
        var ownerCs = Idioms.TypeName(owner, convention);
        var prefix = owner + "_";

        var o = new List<string>
        {
            Header,
            "using System.Runtime.InteropServices;",
            "",
            $"namespace {ns};",
            "",
            $"/// <summary>Free-function operations on <see cref=\"{owner}\"/>.</summary>",
            $"public static unsafe class {ownerCs}",
            "{",
        };

        foreach (var g in fns)
        {
            var f = g.Fn;
            var self = g.SelfParam;
            var rest = self is not null ? f.Params.Skip(1).ToList() : f.Params;
            var strippedName = f.Name.StartsWith(prefix) ? f.Name[prefix.Length..]
                : convention.StripPrefix(f.Name);
            var methodName = Idioms.Pascal(strippedName);
            var sig = string.Join(", ", rest.Select(p =>
                (p.Has("enum") ? Idioms.TypeName(p.TagValue("enum")!, convention) : Idioms.CsPrimitive(p.Type)) + " " + Idioms.Ident(p.Name!)));
            var call = string.Concat(rest.Select(p => ", " + (p.Has("enum") ? $"(int){Idioms.Ident(p.Name!)}" : Idioms.Ident(p.Name!))));
            var retType = f.Returns == "ke_bool" ? "bool" : Idioms.CsPrimitive(f.Returns);
            var selfSig = self is not null ? $"in {CTypes.Deref(self.Type)} {Idioms.Ident(self.Name!)}" : null;
            var fullSig = string.Join(", ", new[] { selfSig }.Where(s => s is not null).Append(sig).Where(s => s!.Length > 0));

            o.Add(XmlDoc("    ", f.Doc, rest.Select(p => (Idioms.Ident(p.Name!), p.Doc))).TrimEnd());
            o.Add($"    public static {retType} {methodName}({fullSig})");
            o.Add("    {");
            if (self is not null)
            {
                o.Add($"        fixed ({CTypes.Deref(self.Type)}* p = &{Idioms.Ident(self.Name!)})");
                o.Add((f.Returns == "ke_bool" ? $"            return Native.{f.Name}(p{call}) != 0;"
                                               : $"            return Native.{f.Name}(p{call});"));
            }
            else
            {
                var call2 = string.Join(", ", rest.Select(p => p.Has("enum") ? $"(int){Idioms.Ident(p.Name!)}" : Idioms.Ident(p.Name!)));
                o.Add((f.Returns == "ke_bool" ? $"        return Native.{f.Name}({call2}) != 0;"
                                               : $"        return Native.{f.Name}({call2});"));
            }
            o.Add("    }");
            o.Add("");
        }

        o.Add("    private static unsafe class Native");
        o.Add("    {");
        foreach (var g in fns)
        {
            var f = g.Fn;
            var rest = (g.SelfParam is not null ? f.Params.Skip(1) : f.Params)
                .Select(p => $"{(p.Has("enum") ? "int" : Idioms.CsPrimitive(p.Type))} {Idioms.Ident(p.Name!)}").ToList();
            var selfParamSig = g.SelfParam is not null ? $"{CTypes.Deref(f.Params[0].Type)}* {Idioms.Ident(f.Params[0].Name!)}" : null;
            var nativeSig = string.Join(", ", (selfParamSig is not null ? [selfParamSig] : Array.Empty<string>()).Concat(rest));
            o.Add($"        [DllImport(\"{libraryName}\", CallingConvention = CallingConvention.Cdecl,");
            o.Add($"                   EntryPoint = \"{f.Name}\", ExactSpelling = true)]");
            o.Add($"        public static extern {(f.Returns == "ke_bool" ? "byte" : Idioms.CsPrimitive(f.Returns))} {f.Name}({nativeSig});");
            o.Add("");
        }
        o.Add("    }");
        o.Add("}");
        o.Add("");
        return string.Join('\n', o);
    }

