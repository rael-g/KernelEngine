using System;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace KernelEngine.SourceGenerators;

/// <summary>
/// Emits one type per <c>.scene.toml</c> file in the project, named after the file and
/// implementing <c>IScene</c>, in the <c>Scenes</c> namespace under the project's root namespace.
/// A file whose name is not a valid C# identifier gets no type and reports <c>KESG007</c>.
/// </summary>
[Generator]
public sealed class SceneNameGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor SceneNameNotAnIdentifierRule = new(
        id: "KESG007",
        title: "Scene file cannot be named by type",
        messageFormat: "Scene file '{0}' has a name that is not a valid C# identifier, so no type is generated for it and LoadScene<T> cannot name it",
        category: "KernelEngine",
        defaultSeverity: DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    private const string SceneSuffix = ".scene.toml";

    private static string SceneNameOf(string path)
    {
        var file = Path.GetFileName(path);
        return file.EndsWith(SceneSuffix, StringComparison.OrdinalIgnoreCase)
            ? file.Substring(0, file.Length - SceneSuffix.Length)
            : Path.GetFileNameWithoutExtension(file);
    }

    /// <summary>
    /// Registers the scene files of the project as the input of one output, <c>Scenes.g.cs</c>.
    /// Nothing is emitted when the project has no scene file or no root namespace.
    /// </summary>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var scenes = context.AdditionalTextsProvider
            .Where(static t => t.Path.EndsWith(SceneSuffix, StringComparison.OrdinalIgnoreCase))
            .Select(static (t, _) => SceneNameOf(t.Path))
            .Collect();

        var rootNamespace = context.AnalyzerConfigOptionsProvider.Select(static (p, _) =>
            p.GlobalOptions.TryGetValue("build_property.RootNamespace", out var ns) && !string.IsNullOrEmpty(ns)
                ? ns
                : null);

        context.RegisterSourceOutput(scenes.Combine(rootNamespace), static (spc, pair) =>
        {
            var (names, ns) = pair;
            if (names.IsDefaultOrEmpty || ns is null) return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// One type per .scene.toml file. Do not edit; add or rename a scene file instead.");
            sb.AppendLine();
            sb.AppendLine($"namespace {ns}.Scenes;");

            foreach (var name in names.Distinct().OrderBy(n => n, StringComparer.Ordinal))
            {
                if (!IsIdentifier(name))
                {
                    spc.ReportDiagnostic(Diagnostic.Create(SceneNameNotAnIdentifierRule, Location.None, name));
                    continue;
                }
                sb.AppendLine();
                sb.AppendLine($"/// <summary>The <c>{name}.scene.toml</c> file.</summary>");
                sb.AppendLine($"public sealed class {name} : global::KernelEngine.Framework.IScene");
                sb.AppendLine("{");
                sb.AppendLine($"    public static string SceneName => \"{name}\";");
                sb.AppendLine("}");
            }

            spc.AddSource("Scenes.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }

    private static bool IsIdentifier(string name)
    {
        if (string.IsNullOrEmpty(name)) return false;
        if (!char.IsLetter(name[0]) && name[0] != '_') return false;
        for (var i = 1; i < name.Length; i++)
            if (!char.IsLetterOrDigit(name[i]) && name[i] != '_') return false;
        return true;
    }
}
