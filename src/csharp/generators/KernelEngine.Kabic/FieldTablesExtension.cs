using Kabic.CSharp;
using System.Text;
using System.Text.Json.Nodes;

using Kabic;
using Kabic.Pipeline;

namespace KernelEngine.Kabic;

/// <summary>
/// Writes each domain's <c>cOut</c> header: the registered name of its components, and a field
/// table for every struct tagged <c>[table]</c>, so the native side applies a scene to component
/// memory by reading a description.
/// </summary>
public sealed class FieldTablesExtension : IKabicExtension
{
    /// <inheritdoc/>
    public string Name => "fieldTables";

    /// <inheritdoc/>
    public void Run(ExtensionContext context)
    {
        var manifest = JsonNode.Parse(File.ReadAllText(context.ManifestPath))!.AsObject();
        var table = manifest["convention"]!["fieldTable"]!.AsObject();
        foreach (var entry in manifest["domains"]!.AsArray().Select(d => d!.AsObject()).Where(d => d["cOut"] is not null))
        {
            var model = context.Domains.First(d => d.Spec.Name == entry["name"]!.GetValue<string>()).Model;
            var path = entry["cOut"]!["file"]!.GetValue<string>();
            context.Emit(path, Header(model, entry["cOut"]!.AsObject(), table, context.Convention));
            foreach (var c in model.Structs.Where(c => !c.IsVtable && !c.External && c.Name.EndsWith("_component", StringComparison.Ordinal)))
            {
                var type = Idioms.TypeName(c.Name, context.Convention);
                var declared = Directory.EnumerateFiles(Path.Combine(context.Root, "src/csharp"), type + ".cs", SearchOption.AllDirectories)
                    .FirstOrDefault(f => File.ReadAllText(f).Contains($"partial struct {type}"));
                if (declared is null) continue;
                var ns = File.ReadLines(declared).First(l => l.StartsWith("namespace ", StringComparison.Ordinal))["namespace ".Length..].TrimEnd(';', ' ');
                context.Emit(Path.GetRelativePath(context.Root, Path.Combine(Path.GetDirectoryName(Path.GetDirectoryName(declared)!)!, "ComponentNames", type + ".g.cs")).Replace('\\', '/'),
                    $"// <auto-generated/>\n// Derived from ke_api.json. Do not edit; edit the C header instead.\n\nnamespace {ns};\n\npublic partial struct {type}\n{{\n    /// <summary>The name the component is registered under.</summary>\n    public const string Name = \"{ComponentName(c, context.Convention)}\";\n}}\n");
            }
        }
    }

    static string Header(ApiModel model, JsonObject cOut, JsonObject table, Convention convention)
    {
        var guard = cOut["guard"]!.GetValue<string>();
        var variants = table["variants"]!.AsObject();
        var o = new StringBuilder();
        o.Append($"/* <auto-generated/> Derived from ke_api.json. Do not edit; edit the C header instead. */\n#ifndef {guard}\n#define {guard}\n\n");
        o.Append($"#include <{table["include"]!.GetValue<string>()}>\n");
        foreach (var include in cOut["includes"]!.AsArray()) o.Append($"#include <{include!.GetValue<string>()}>\n");
        o.Append("#include <stddef.h>\n\n");

        var named = model.Structs.Where(s => !s.IsVtable && !s.External && s.Name.EndsWith("_component", StringComparison.Ordinal)).ToList();
        foreach (var s in named)
            o.Append($"#define {table["nameMacroPrefix"]!.GetValue<string>()}{ComponentName(s, convention).ToUpperInvariant()} \"{ComponentName(s, convention)}\"\n");
        if (named.Count > 0) o.Append('\n');

        foreach (var s in model.Structs.Where(s => !s.IsVtable && !s.External && s.Has("table")))
        {
            o.Append($"static const {table["entryType"]!.GetValue<string>()} {s.Name}_fields[] = {{\n");
            foreach (var f in s.Fields.Where(f => !f.Has("output") && KindOf(model, f) is not null))
            {
                var variant = variants[KindOf(model, f)!]!.AsObject();
                o.Append($"    {{ \"{f.TagValue("name") ?? f.Name}\", {variant["constant"]!.GetValue<string>()}, offsetof({s.Name}, {f.Name}), "
                    + $"sizeof((({s.Name} *)0)->{f.Name}), {DefaultOf(f, KindOf(model, f)!, variants)}, NULL, 0 }},\n");
            }
            o.Append("};\n\n");
        }
        o.Append($"#endif /* {guard} */\n");
        return o.ToString();
    }

    static string ComponentName(ApiStruct s, Convention convention) => convention.StripPrefix(s.Name)[..^"_component".Length];

    static string? KindOf(ApiModel model, ApiField f)
    {
        if (f.Has("bool")) return "bool";
        var type = f.Type.Replace("const ", "").Replace("struct ", "").Trim();
        if (model.Enums.Any(e => e.Name == type)) return "int";
        return type switch
        {
            "ke_vec2" or "float[2]" => "vec2",
            "ke_vec3" or "float[3]" => "vec3",
            "ke_vec4" or "float[4]" => "vec4",
            "ke_quat" => "quat",
            "float" or "double" => "float",
            "bool" or "_Bool" => "bool",
            "int8_t" or "int16_t" or "int32_t" or "int64_t" or "uint8_t" or "uint16_t" or "uint32_t" or "uint64_t" or "int" => "int",
            _ when type.StartsWith("char[", StringComparison.Ordinal) => "string",
            _ => null,
        };
    }

    static string DefaultOf(ApiField f, string kind, JsonObject variants)
    {
        if (f.TagValue("default") is not { } raw) return $"{{ {variants["null"]!["constant"]!.GetValue<string>()}, {{ 0 }} }}";
        var parts = raw.Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        var value = kind switch
        {
            "string" => $"\"{raw}\"",
            "bool" => raw is "1" or "true" ? "true" : "false",
            "int" => raw,
            "float" => CDouble(parts[0]),
            _ => "{ " + string.Join(", ", parts.Select(p => CDouble(p) + "f")) + " }",
        };
        return $"{{ {variants[kind]!["constant"]!.GetValue<string>()}, {{ {variants[kind]!["member"]!.GetValue<string>()} = {value} }} }}";
    }

    static string CDouble(string raw) => raw.Contains('.') ? raw : raw + ".0";
}
