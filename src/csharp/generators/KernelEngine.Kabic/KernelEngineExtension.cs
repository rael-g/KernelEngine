using System.Text;

using Kabic;
using Kabic.CSharp;
using Kabic.Factories;
using Kabic.Pipeline;

namespace KernelEngine.Kabic;

/// <summary>
/// What a KernelEngine host needs of every class the factories extension projects: a constructor
/// that sends the library's log to a <c>Microsoft.Extensions.Logging.ILoggerFactory</c> through the library's
/// log-callback setter. Runs with the section of the factories extension.
/// </summary>
public sealed class KernelEngineExtension : IKabicExtension
{
    /// <inheritdoc/>
    public string Name => "factories";

    /// <inheritdoc/>
    public void Run(ExtensionContext context)
    {
        var factories = FactoriesExtension.Read(context);
        var jobs = global::Kabic.Bindings.BindingsPlanner.Plan(context.Root, context.ManifestPath);
        foreach (var f in factories)
        {
            if (f.Job.Library is not { } library)
            {
                context.Report($"factories: the bindings entry '{f.Job.Name}' names no library, so its log-callback setter is unknown");
                continue;
            }
            var setter = context.Convention.StripPrefix(library) + "_set_log_callback";
            var logJob = jobs.FirstOrDefault(j => j.Traverse.Any(t => Path.GetFileName(t) == context.Convention.StripPrefix(library) + "_log.h")) ?? f.Job;
            var dir = Path.GetRelativePath(context.Root, f.ProjectDir).Replace('\\', '/');
            context.Emit($"{dir}/Generated/{f.ClassName}.Logging.g.cs", Logging(f, $"{logJob.Namespace}.{logJob.MethodsClass}.{setter}"));
        }
    }

    private static string Header(Factory f) =>
        $"// <auto-generated/>\n// Derived from the factory header. Do not edit; edit the header instead.\n\n#nullable enable\n\nnamespace {f.ManagedNamespace};\n\n";

    private static string Logging(Factory f, string setter)
    {
        var parameters = FactoriesExtension.Parameters(f);
        var o = new StringBuilder(Header(f));
        o.Append($"public sealed unsafe partial class {f.ClassName}\n{{\n");
        o.Append("    /// <summary>The same construction, with the library logging to <paramref name=\"loggerFactory\"/>.</summary>\n");
        o.Append("    /// <param name=\"loggerFactory\">Creates the logger of each scope the library logs under; null leaves the library logging where it did.</param>\n");
        foreach (var a in f.Arguments)
            o.Append($"    /// <param name=\"{a.Name}\">{Xml(a.Doc)}</param>\n");
        o.Append($"    public {f.ClassName}(Microsoft.Extensions.Logging.ILoggerFactory? loggerFactory{(parameters.Length > 0 ? ", " + parameters : "")}) : {(FactoriesExtension.ChainsThroughThis(f) ? "this" : "base")}(CreateLogged(loggerFactory{(f.Arguments.Count > 0 ? ", " + FactoriesExtension.Names(f) : "")}))\n    {{\n    }}\n\n");
        o.Append($"    private static {FactoriesExtension.CreatedType(f)} CreateLogged(Microsoft.Extensions.Logging.ILoggerFactory? loggerFactory{(f.Arguments.Count > 0 ? ", " + FactoriesExtension.Parameters(f, withDefaults: false) : "")})\n    {{\n");
        o.Append($"        if (loggerFactory is not null) {setter}(KernelEngine.Logger.NativeLogging.Callback, KernelEngine.Logger.NativeLogging.ContextOf(loggerFactory));\n");
        o.Append($"        return Create({FactoriesExtension.Names(f)});\n    }}\n}}\n");
        return o.ToString();
    }

    private static string Xml(string? text) =>
        (text ?? "").Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\n", " ").Trim();
}
