using System.Text;

using Kabic;
using Kabic.CSharp;
using Kabic.Factories;
using Kabic.Pipeline;

namespace KernelEngine.Kabic;

/// <summary>
/// What a KernelEngine host needs of every class the factories extension projects: a constructor
/// that sends the library's log to a <c>KernelEngine.Logger.ILogger</c> through the library's
/// log-callback setter, and an <c>Add&lt;Class&gt;</c> registration into
/// <c>Microsoft.Extensions.DependencyInjection</c> that resolves the providers and the logger and
/// registers the instance as its contract's <c>INative</c> interface, and as the contract's managed
/// interface when the contract is tagged <c>[interface]</c>. Runs with the section of the factories
/// extension.
/// </summary>
public sealed class KernelEngineExtension : IKabicExtension
{
    /// <inheritdoc/>
    public string Name => "factories";

    /// <inheritdoc/>
    public void Run(ExtensionContext context)
    {
        foreach (var f in FactoriesExtension.Read(context))
        {
            if (f.Job.Library is not { } library)
            {
                context.Report($"factories: the bindings entry '{f.Job.Name}' names no library, so its log-callback setter is unknown");
                continue;
            }
            var setter = context.Convention.StripPrefix(library) + "_set_log_callback";
            var dir = Path.GetRelativePath(context.Root, f.ProjectDir).Replace('\\', '/');
            context.Emit($"{dir}/Generated/{f.ClassName}.Logging.g.cs", Logging(f, setter));
            context.Emit($"{dir}/Generated/{f.ClassName}.Registration.g.cs", Registration(f, context.Convention));
        }
    }

    private static string Header(Factory f) =>
        $"// <auto-generated/>\n// Derived from the factory header. Do not edit; edit the header instead.\n\n#nullable enable\n\nnamespace {f.ManagedNamespace};\n\n";

    private static string Logging(Factory f, string setter)
    {
        var parameters = FactoriesExtension.Parameters(f);
        var o = new StringBuilder(Header(f));
        o.Append($"public sealed unsafe partial class {f.ClassName}\n{{\n");
        o.Append("    /// <summary>The same construction, with the library logging to <paramref name=\"logger\"/>.</summary>\n");
        o.Append("    /// <param name=\"logger\">Receives every line the library logs.</param>\n");
        foreach (var a in f.Arguments)
            o.Append($"    /// <param name=\"{a.Name}\">{Xml(a.Doc)}</param>\n");
        o.Append($"    public {f.ClassName}(KernelEngine.Logger.ILogger logger{(parameters.Length > 0 ? ", " + parameters : "")}) : base(CreateLogged(logger{(f.Arguments.Count > 0 ? ", " + FactoriesExtension.Names(f) : "")}))\n    {{\n    }}\n\n");
        o.Append($"    private static {f.Contract.Spec.NativeNamespace}.{f.HandleType} CreateLogged(KernelEngine.Logger.ILogger logger{(f.Arguments.Count > 0 ? ", " + FactoriesExtension.Parameters(f, withDefaults: false) : "")})\n    {{\n");
        o.Append("        ArgumentNullException.ThrowIfNull(logger);\n");
        o.Append($"        {f.Job.Namespace}.{f.Job.MethodsClass}.{setter}(KernelEngine.Logger.LogCallbackNative.Pointer, KernelEngine.Logger.LogCallbackNative.Pin(logger.Log));\n");
        o.Append($"        return Create({FactoriesExtension.Names(f)});\n    }}\n}}\n");
        return o.ToString();
    }

    private static string Registration(Factory f, Convention convention)
    {
        var contractName = f.ContractClass[(f.ContractClass.LastIndexOf('.') + 1)..];
        var vtable = CType.Of(f.Contract.Model.Structs.First(s => s.Name == f.HandleType).Fields[0].Type).Name;
        var contractInterface = $"{f.Contract.Spec.Namespace}.{Idioms.NativeInterface(vtable, convention)}";
        var managedInterface = f.Contract.Model.Structs.First(s => s.Name == vtable).Has("interface") || f.Contract.Spec.AbstractionsOutDir is not null
            ? $"{f.Contract.Spec.Namespace}.I{contractName}"
            : null;
        var resolved = f.Arguments.Select(a => a.IsRequiredProvider ? $"sp.GetRequiredService<{a.ManagedType}>()"
            : a.IsOptionalProvider ? $"sp.GetService<{a.ManagedType.TrimEnd('?')}>()"
            : a.Name).ToList();
        var values = string.Concat(f.Arguments.Where(a => !a.ManagedType.Contains(".INative"))
            .Select(a => $", {(a.IsString ? "string?" : a.ManagedType)} {a.Name} = default"));
        var args = string.Join(", ", resolved);
        var o = new StringBuilder(Header(f));
        o.Append("using Microsoft.Extensions.DependencyInjection;\n\n");
        o.Append($"/// <summary>Registers <see cref=\"{f.ClassName}\"/> with a service collection.</summary>\n");
        o.Append($"public static class {f.ClassName}Registration\n{{\n");
        o.Append($"    /// <summary>\n    /// Registers one <see cref=\"{f.ClassName}\"/>, created on first resolution with its providers from the\n");
        o.Append($"    /// container and the given values, as itself, as <see cref=\"{contractInterface}\"/>{(managedInterface is null ? "" : $" and as <see cref=\"{managedInterface}\"/>")}. The library logs to the\n");
        o.Append("    /// registered <c>KernelEngine.Logger.ILogger</c>, or to stderr when there is none.\n    /// </summary>\n");
        o.Append($"    public static IServiceCollection Add{f.ClassName}(this IServiceCollection services{values})\n    {{\n");
        o.Append($"        services.AddSingleton(sp => sp.GetService<KernelEngine.Logger.ILogger>() is {{ }} logger\n");
        o.Append($"            ? new {f.ClassName}(logger{(args.Length > 0 ? ", " + args : "")})\n");
        o.Append($"            : new {f.ClassName}({args}));\n");
        o.Append($"        services.AddSingleton<{contractInterface}>(sp => sp.GetRequiredService<{f.ClassName}>());\n");
        if (managedInterface is not null)
            o.Append($"        services.AddSingleton<{managedInterface}>(sp => sp.GetRequiredService<{f.ClassName}>());\n");
        o.Append("        return services;\n    }\n}\n");
        return o.ToString();
    }

    private static string Xml(string? text) =>
        (text ?? "").Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\n", " ").Trim();
}
