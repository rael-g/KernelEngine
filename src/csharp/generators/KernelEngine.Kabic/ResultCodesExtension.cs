using System.Text;

using Kabic;
using Kabic.Pipeline;

namespace KernelEngine.Kabic;

/// <summary>
/// Projects the manifest's table of result codes into <c>NativeResults</c>, the translation between
/// a native code and the managed exception that stands for it.
/// </summary>
public sealed class ResultCodesExtension : IKabicExtension
{
    const string Result = "KernelEngine.Result.Native.Result";
    const string Prefix = "KE_RESULT_";

    const string Header = "// <auto-generated/>\n// Derived from scripts/api_domains.json. Do not edit; edit the manifest instead.\n\n";

    const string Opening = """
#nullable enable

namespace KernelEngine;

/// <summary>
/// Turns the result code a native call returned into the exception that stands for it. The detail
/// of a failure is in the failing library's log, never in the code, so the message names the call
/// and the code only.
/// </summary>
public static class NativeResults
{
    /// <summary>Throws the exception for <paramref name="code"/> when it is not <c>KE_OK</c>.</summary>
    /// <param name="code">What the call returned.</param>
    /// <param name="context">The name of the call, prefixed to the message.</param>
    public static void ThrowIfFailed(KernelEngine.Result.Native.Result code, string context)
    {
        if (code != KernelEngine.Result.Native.Result.Ok)
            throw FromCode(code, context);
    }

    /// <summary>The exception that stands for a code other than <c>KE_OK</c>.</summary>
    /// <param name="code">What the call returned.</param>
    /// <param name="context">The name of the call, prefixed to the message.</param>
    public static Exception FromCode(KernelEngine.Result.Native.Result code, string context) =>
        Create(code, $"{context} failed with {Name(code)}; the library's log holds the detail");

    static string Name(KernelEngine.Result.Native.Result code) =>
        Enum.IsDefined(code) ? code.ToString() : $"result code 0x{(uint)code:x8}";

""";

    const string CodeDoc = """
    /// <summary>
    /// The code that stands for <paramref name="exception"/>: the first code whose exception
    /// type it is exactly, or the general code.
    /// </summary>
    /// <param name="exception">What a managed handler threw.</param>
""";

    /// <inheritdoc/>
    public string Name => "resultCodes";

    /// <inheritdoc/>
    public void Run(ExtensionContext context)
    {
        var options = context.Options ?? throw new InvalidOperationException("resultCodes: the extension needs its options");
        var path = options["out"]!.GetValue<string>();
        var general = options["general"]!.GetValue<string>();
        var codes = options["codes"]!.AsArray()
            .Select(c => (Code: Member(c!["code"]!.GetValue<string>()), Managed: c["managed"]!.GetValue<string>()))
            .ToList();

        var o = new StringBuilder(Header + Opening);
        o.Append($"\n    static Exception Create({Result} code, string message) => code switch\n    {{\n");
        foreach (var (code, managed) in codes.Where(c => c.Code != "General"))
            o.Append($"        {Result}.{code} => new {managed}(message),\n");
        o.Append($"        _ => new {general}(message),\n    }};\n\n");
        o.Append(CodeDoc).Append('\n');
        o.Append($"    public static {Result} ToCode(Exception exception) => exception.GetType().Name switch\n    {{\n");
        foreach (var (code, managed) in codes.DistinctBy(c => c.Managed).Where(c => c.Managed != general))
            o.Append($"        \"{managed}\" => {Result}.{code},\n");
        o.Append($"        _ => {Result}.General,\n    }};\n}}\n");
        context.Emit(path, o.ToString());
    }

    static string Member(string code) =>
        string.Concat(code[Prefix.Length..].Split('_').Select(w => w[0] + w[1..].ToLowerInvariant()));
}
