using System.Text;

using Kabic;
using Kabic.CSharp;
using Kabic.Pipeline;

namespace KernelEngine.Kabic;

/// <summary>
/// Projects every component a header tags <c>[node:&lt;Name&gt;]</c> into an abstract node class of the
/// C# node SDK: it derives from the class its <c>base:</c> names, or from <c>Node</c>, reaches the
/// component of the node a behaviour visits, and adds the component, born as engine_node_types.h
/// says, to the components of every type deriving from it. Section: <c>{"outDir": "&lt;dir&gt;", "namespace": "&lt;ns&gt;", "usings": [...]}</c>.
/// </summary>
public sealed class NodeBasesExtension : IKabicExtension
{
    /// <inheritdoc/>
    public string Name => "nodeBases";

    /// <inheritdoc/>
    public void Run(ExtensionContext context)
    {
        var options = context.Options!;
        var outDir = options["outDir"]!.GetValue<string>();
        var ns = options["namespace"]!.GetValue<string>();
        var usings = options["usings"]!.AsArray().Select(u => u!.GetValue<string>()).ToList();
        var initials = context.Domains.SelectMany(d => d.Model.Data).Select(d => d.Name).ToHashSet();
        foreach (var model in context.Domains.Select(d => d.Model))
            foreach (var component in model.Structs.Where(s => !s.IsVtable && !s.External && s.Has("node")))
                context.Emit($"{outDir}/{component.TagValue("node")}.g.cs", Render(component, ns, usings, initials, context.Convention));
    }

    static string Render(ApiStruct component, string ns, IReadOnlyList<string> usings, IReadOnlySet<string> initials, Convention convention)
    {
        var name = component.TagValue("node")!;
        var registered = convention.StripPrefix(component.Name);
        registered = registered.EndsWith("_component", StringComparison.Ordinal) ? registered[..^"_component".Length] : registered;
        var type = Idioms.TypeName(component.Name, convention);
        var initial = $"ke_{registered}_node_initial";
        var born = initials.Contains(initial)
            ? $"NodeWith.Of(\"{registered}\", EngineNodeTypes.{Idioms.Pascal(registered)}NodeInitial)"
            : $"new() {{ Name = \"{registered}\" }}";
        var o = new StringBuilder();
        o.Append("// <auto-generated/>\n// Derived from the header's [node:] tag. Do not edit; edit the C header instead.\n\n#nullable enable\n\n");
        foreach (var u in usings) o.Append($"using {u};\n");
        o.Append($"\nnamespace {ns};\n\n");
        o.Append($"/// <summary>A node carrying <c>{registered}</c>: what a node type deriving from it reaches of it, and how it is born.</summary>\n");
        o.Append($"public abstract partial class {name} : {component.TagValue("base") ?? "Node"}\n{{\n");
        o.Append($"    /// <summary>The <c>{registered}</c> of the node a behaviour is visiting.</summary>\n");
        var accessor = Idioms.Pascal(registered) != name ? Idioms.Pascal(registered)
            : System.Text.RegularExpressions.Regex.Replace(name, "[0-9]+D$", "") is { Length: > 0 } bare && bare != name ? bare : type;
        o.Append($"    protected ref {type} {accessor} => ref Component<{type}>(\"{registered}\");\n\n");
        o.Append("    /// <inheritdoc/>\n");
        o.Append($"    protected internal override IEnumerable<NodeWith> With => [.. base.With, {born}];\n");
        o.Append("}\n");
        return o.ToString();
    }
}
