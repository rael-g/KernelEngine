using System.Text.RegularExpressions;

using Kabic;
using Kabic.CSharp;
using Kabic.Pipeline;

namespace KernelEngine.Kabic;

/// <summary>
/// Projects every struct a header tags <c>[node:]</c> into a partial node class, and each domain's
/// node types into one registrar. Accessors, state and binding are the source generator's job.
/// </summary>
public sealed class NodesExtension : IKabicExtension
{
    const string Header = "// <auto-generated/>\n// Derived from ke_api.json. Do not edit; edit the C header instead.\n\n#nullable enable\n";

    const string NodeNamespace = "KernelEngine.Framework";

    /// <inheritdoc/>
    public string Name => "nodes";

    /// <inheritdoc/>
    public void Run(ExtensionContext context)
    {
        var borrows = context.Domains.SelectMany(d => d.Model.Enums).First(e => e.Name == "ke_script_borrow" && !e.External);
        context.Emit("src/csharp/framework/KernelEngine.Framework/Generated/ScriptBorrowWrappers.g.cs", BorrowWrappers(borrows, context.Convention));
        foreach (var (spec, model) in context.Domains.Select(d => (d.Spec, d.Model)))
        {
            var nodes = model.Structs.Where(s => !s.IsVtable && !s.External && s.Has("node")).ToList();
            if (nodes.Count == 0) continue;
            foreach (var node in nodes)
                context.Emit($"{spec.OutDir}/{node.TagValue("node")}.g.cs", NodeType(model, spec, node, context.Convention));
            var registrar = Idioms.TypeName(spec.Name, context.Convention) + "NodeTypes";
            context.Emit($"{spec.OutDir}/{registrar}.g.cs", Registrar(registrar, nodes.Select(n => n.TagValue("node")!), NodeNamespace));
        }
    }

    static string BorrowWrappers(ApiEnum kinds, Convention convention)
    {
        const string reach = "global::KernelEngine.Framework.Native.ScriptBorrow";
        var o = new List<string>
        {
            Header, $"namespace {NodeNamespace};", "",
            "/// <summary>Marks a borrow wrapper with the reach it resolves with, so a projection recognises a borrow parameter by what it means.</summary>",
            "[AttributeUsage(AttributeTargets.Struct)]", "public sealed class NodeBorrowAttribute : Attribute", "{",
            "    /// <summary>Where this wrapper's borrow looks for the node it names.</summary>",
            $"    public {reach} Reach {{ get; }}", "",
            "    /// <param name=\"reach\">Where this wrapper's borrow looks for the node it names.</param>",
            $"    public NodeBorrowAttribute({reach} reach) => Reach = reach;", "}", "",
        };
        foreach (var value in kinds.Values)
        {
            var member = Idioms.EnumMember(value.Name, kinds.Name);
            o.AddRange([
                "/// <summary>",
                $"/// {Escape(value.Doc ?? $"A borrow resolved with {member}.")} Obtained as a parameter rather than stored in a field:",
                "/// re-resolved each time it is handed over, so it can never dangle, and its type is what puts",
                "/// <typeparamref name=\"T\"/>'s components into the borrowing body's access list.",
                "/// </summary>",
                $"[NodeBorrow({reach}.{member})]",
                $"public readonly ref struct {member}<T> where T : class", "{",
                "    private readonly T? _node;", "",
                "    /// <summary>The borrowed node, or null when none matched.</summary>",
                "    public T? Node => _node;", "",
                "    /// <summary>True when a node matched this borrow.</summary>",
                "    public bool IsBound => _node is not null;", "",
                "    /// <param name=\"node\">The node this borrow resolved to, or null when none matched.</param>",
                $"    public {member}(T? node) => _node = node;", "",
                "    /// <summary>Unwraps the borrow, throwing when nothing matched.</summary>",
                "    public T Value => _node ?? throw new InvalidOperationException(",
                $"        $\"No node of type {{typeof(T).Name}} is bound for this {member.ToLowerInvariant()} borrow.\");",
                "}", ""]);
        }
        return string.Join('\n', o);
    }

    static string NodeType(ApiModel model, DomainSpec spec, ApiStruct node, Convention convention)
    {
        var state = Idioms.TypeName(node.Name, convention);
        var name = convention.StripPrefix(node.Name).Replace("_component", "");
        var o = new List<string> { Header };
        o.AddRange(new[] { "System.Numerics", spec.Namespace }.Concat(spec.Usings).Where(u => u != NodeNamespace).Distinct().Select(u => $"using {u};"));
        o.AddRange(["", $"namespace {NodeNamespace};\n"]);
        o.Add($"/// <summary>{Escape(node.Doc ?? $"Mirrors <c>{node.Name}</c>.")}</summary>");
        o.Add($"[GeneratedNodeComponent(typeof({state}), \"{name}\")]");
        o.Add($"public partial class {node.TagValue("node")} : {node.TagValue("base") ?? "Node"}");
        o.Add("{");
        foreach (var field in node.Fields.Where(f => !f.Has("internal")))
        {
            o.Add("");
            if (!string.IsNullOrEmpty(field.Doc)) o.Add($"    /// <summary>{Escape(field.Doc)}</summary>");
            o.Add($"    [NativeField(\"{Idioms.Pascal(field.Name)}\", Component = typeof({state}))]");
            o.Add($"    public partial {PropertyType(model, field, convention)} {Idioms.Pascal(field.TagValue("name") ?? field.Name)} {{ get; set; }}");
        }
        o.Add("}");
        return string.Join('\n', o);
    }

    static string PropertyType(ApiModel model, ApiField field, Convention convention)
    {
        var type = field.Type.Trim();
        if (Regex.IsMatch(type, @"^(const\s+)?char\s*\[\d+\]$")) return "string";
        if (convention.Project(Languages.CSharp, field.Type) is { } projected) return projected;
        if (field.Has("bool") || type is "_Bool") return "bool";
        if (Regex.Match(type, @"^float\s*\[([234])\]$") is { Success: true } vector) return $"System.Numerics.Vector{vector.Groups[1].Value}";
        return Primitives.GetValueOrDefault(type) ?? Idioms.TypeName(type, convention);
    }

    static readonly Dictionary<string, string> Primitives = new()
    {
        ["float"] = "float", ["double"] = "double", ["bool"] = "bool", ["int32_t"] = "int", ["uint32_t"] = "uint",
        ["int64_t"] = "long", ["uint64_t"] = "ulong", ["uint8_t"] = "byte", ["int"] = "int",
    };

    static string Registrar(string name, IEnumerable<string> nodes, string ns) => string.Join('\n', [
        Header, "using Microsoft.Extensions.DependencyInjection;", "", $"namespace {ns};", "",
        "/// <summary>Registers every node type generated for this domain.</summary>",
        $"public static class {name}", "{",
        "    /// <summary>Registers this domain's node types with the scene node registry.</summary>",
        $"    public static IServiceCollection Add{name}(this IServiceCollection services)", "    {",
        .. nodes.Select(n => $"        services.AddNodeType<{n}>();"),
        "        return services;", "    }", "}"]);

    static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
