"""
compile_slang.py — compile a Slang shader to a backend language and embed it
as a C header (a NUL-terminated string array).

Usage:
  python compile_slang.py --input X.slang --output Y.h --name ident [--target wgsl]

Why a wrapper instead of slangc's own -o / -source-embed:
  slangc 2025.17.2 emits a DIFFERENT (invalid) WGSL module when writing to a
  file via -o or -source-embed-style than when writing to stdout — the file
  path drops the @location on inter-stage vertex outputs, which WGSL rejects.
  Capturing stdout is the only path that produces a valid module, so this
  script runs slangc with stdout capture and does the C-string embedding here.

slangc is located via PATH or the Vulkan SDK ($VULKAN_SDK/Bin or /bin).
"""

import argparse
import os
import shutil
import subprocess
import sys


def find_slangc():
    exe = shutil.which("slangc")
    if exe:
        return exe
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        for sub in ("Bin", "bin"):
            cand = os.path.join(sdk, sub, "slangc")
            for ext in ("", ".exe"):
                if os.path.exists(cand + ext):
                    return cand + ext
    return None


def embed_c_string(name, text):
    """Render WGSL/text source as a NUL-terminated C string literal array."""
    lines = ["// Generated by compile_slang.py — do not edit.", "#pragma once", ""]
    lines.append(f"static const char {name}[] =")
    for line in text.splitlines():
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{esc}\\n"')
    lines.append("    ;")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="Compile a .slang shader to an embedded C header.")
    ap.add_argument("--input", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--name", help="C identifier for the embedded array (C-header mode)")
    ap.add_argument("--target", default="wgsl")
    ap.add_argument("--entry", help="Single entry-point name (with --stage). Emitting one "
                                    "entry point per module avoids duplicate shared "
                                    "declarations when a uniform is used across stages.")
    ap.add_argument("--stage", help="Shader stage for --entry (vertex|fragment|compute).")
    ap.add_argument("--include", action="append", default=[],
                    help="Additional include search path (repeatable) — passed to slangc as -I. "
                         "Needed when a shader uses 'import ke;' or imports an engine pass module.")
    ap.add_argument("--raw", action="store_true",
                    help="Write the raw compiled source (e.g. for Zig @embedFile) "
                         "instead of a C-string header.")
    args = ap.parse_args()
    if not args.raw and not args.name:
        print("Error: --name is required unless --raw is set.", file=sys.stderr)
        sys.exit(1)

    slangc = find_slangc()
    if not slangc:
        print("Error: slangc not found on PATH or under $VULKAN_SDK.", file=sys.stderr)
        sys.exit(1)

    cmd = [slangc, args.input, "-target", args.target]
    for inc in args.include:
        cmd += ["-I", inc]
    if args.entry:
        cmd += ["-entry", args.entry]
    if args.stage:
        cmd += ["-stage", args.stage]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"slangc failed for {args.input}:\n{result.stderr.strip()}", file=sys.stderr)
        sys.exit(1)

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", newline="\n") as f:
        f.write(result.stdout if args.raw else embed_c_string(args.name, result.stdout))


if __name__ == "__main__":
    main()
